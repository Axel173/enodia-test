#!/bin/sh
# devwatch.sh — «Что запрашивает устройство»: временное наблюдение за DNS-запросами и
# активными соединениями ОДНОГО клиента LAN, чтобы точечно закинуть его домены/адреса
# «мимо VPN» (боль Mi Home: bypass-домены Xiaomi не ловятся, лечилось только полным VPN off —
# [[mihome-be7000-vpn]]). Два источника, оба уже есть в busybox:
#   • dnsmasq query-log (log-queries + log-facility в ОЗУ) → какие ДОМЕНЫ резолвит клиент.
#     Включается ПО КНОПКЕ на короткое окно (verbose на весь LAN — постоянно держать нельзя),
#     авто-выключается по таймеру. Устройства со СВОИМ DoH мимо dnsmasq тут не видны (оговорка).
#   • conntrack -L -s <ip> → активные соединения СЕЙЧАС (dst-IP/порт), даже если DNS уже в кэше.
#
# Действия («→ мимо VPN» и т.п.) делает НЕ этот скрипт, а панель через apply-bypass.sh add-dst
# (тот же путь, что «Сайты мимо VPN») — здесь только НАБЛЮДЕНИЕ (read) + toggle лога (2 write-verb).
#
# ГРАБЛИ (см. CLAUDE.md):
#   • Конфиг query-log пишем в ЖИВОЙ conf-dir /tmp/dnsmasq.d (НЕ /etc — стоковый init на рестарте
#     копит /etc→/tmp аддитивно, стухший файл переживёт; /tmp=RAM, на ребуте само исчезает).
#   • log-queries НЕ переключается по SIGHUP → нужен полный рестарт dnsmasq (краткий DNS-блип на LAN).
#   • Нет nohup/setsid → авто-стоп через start-stop-daemon -b (уникальный pidfile на запуск).
#   • busybox awk без index()/split()/user-функций → парсим полями ($i), без них.

ENODIA_DIR="/data/usr/app/enodia"
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Сброс УЖЕ УСТАНОВЛЕННЫХ соединений — только через ct-lib.sh: на ядре 4.4 (AX3600/BE3600)
# утилиты conntrack в прошивке НЕТ ВООБЩЕ, и прежний `conntrack -F || true` был тихим no-op —
# правило стояло, а поток шёл по-старому через NSS/ECM. Шим = прежнее поведение (частичный
# apply-scripts не должен падать), полноценный сброс живёт в самой библиотеке.
if [ -f "$ENODIA_DIR/ct-lib.sh" ]; then . "$ENODIA_DIR/ct-lib.sh"; fi
if ! command -v ct_list_src >/dev/null 2>&1; then
    ct_list_src()   { [ -n "$1" ] && conntrack -L -s "$1" 2>/dev/null; return 0; }
fi
if ! command -v ct_list_all >/dev/null 2>&1; then
    ct_list_all()   { conntrack -L 2>/dev/null || cat /proc/net/nf_conntrack 2>/dev/null; return 0; }
fi
# Возраст записи журнала считаем через age_since (clock-lib.sh): часы роутера ПРЫГАЮТ вперёд
# через ~13 мин после загрузки, и голая разность в этот момент показала бы «час назад» у записи,
# сделанной минуту назад. Шим — на случай частично доехавшего apply-scripts.
if [ -f "$ENODIA_DIR/clock-lib.sh" ]; then . "$ENODIA_DIR/clock-lib.sh"; fi
if ! command -v age_since >/dev/null 2>&1; then
    # clock-raw: библиотеки нет — считаем голой разностью, как было до неё
    age_since() { echo $(( $(date +%s) - $1 )); }
fi
SELF="$ENODIA_DIR/devwatch.sh"
QLOG="/tmp/enodia-dnsq.log"                 # лог dnsmasq (ОЗУ)
QCONF="/tmp/dnsmasq.d/07-querylog.conf"  # сниппет query-log в ЖИВОМ conf-dir
UNTIL="/tmp/enodia-devwatch.until"          # epoch, до которого наблюдаем (переживает окно, не ребут)
DEF_SECS=120; MIN_SECS=10; MAX_SECS=300
# --- ЖУРНАЛ «НЕ ОТВЕТИЛИ ЗА ОКНО» --------------------------------------------
# Список соединений — МГНОВЕННЫЙ срез: запись о молчащем потоке живёт в conntrack, пока идут
# попытки, и исчезает через таймаут (замерено на BE7000: unreplied UDP 60 с, зависший TCP в
# SYN_SENT 30 с). То есть «что отвалилось три минуты назад» в нём не увидеть НИКОГДА, а это ровно
# тот вопрос, ради которого экран и открывают. Домены такой болезни не знают: их пишет dnsmasq
# непрерывно и независимо от того, открыта ли панель. Даём соединениям ту же непрерывность —
# сэмплер живёт в фоновом процессе ОКНА (той же сплилке, что делает авто-стоп), поэтому копит и
# при закрытом экране. Журнал в ОЗУ: на ребуте исчезает сам, флеш не пишем.
DEADLOG="/tmp/enodia-devwatch-dead.tsv"     # src dst dport proto tx first_seen last_seen (через пробел)
SPID="/tmp/enodia-devwatch-sampler.pid"     # ЧЕЙ сейчас сэмплер: перезапуск окна перебивает файл,
                                         # прежняя сплилка видит чужой pid и уходит (иначе два
                                         # писателя в один журнал)
SAMPLE_EVERY=5                           # шаг опроса, с — вдвое меньше самого короткого таймаута
DEAD_MAX=200                             # потолок журнала: сканер портов не должен съесть ОЗУ
DEAD_SHOW=40                             # сколько отдаём панели (свежие сверху)

# Полный рестарт dnsmasq (единственный способ подхватить log-queries). Идентично
# dnsmasq_reload() из lists-lib.sh — тут инлайним, чтобы не тянуть весь lib ради строки.
dns_restart() { /etc/init.d/dnsmasq restart >/dev/null 2>&1 || killall -HUP dnsmasq 2>/dev/null; }

now() { date +%s; }

watching() {  # код 0 = сейчас наблюдаем (until в будущем И конфиг на месте)
	[ -f "$QCONF" ] || return 1
	u=$(cat "$UNTIL" 2>/dev/null); case "$u" in ''|*[!0-9]*) return 1 ;; esac
	[ "$(now)" -lt "$u" ]
}

secs_left() {
	u=$(cat "$UNTIL" 2>/dev/null); case "$u" in ''|*[!0-9]*) echo 0; return ;; esac
	l=$((u - $(now))); [ "$l" -gt 0 ] && echo "$l" || echo 0
}

start() {
	s="$1"; case "$s" in ''|*[!0-9]*) s="$DEF_SECS" ;; esac
	[ "$s" -lt "$MIN_SECS" ] && s="$MIN_SECS"; [ "$s" -gt "$MAX_SECS" ] && s="$MAX_SECS"
	mkdir -p /tmp/dnsmasq.d 2>/dev/null
	# СНАЧАЛА отбираем владение окном у прежнего сэмплера, и только потом чистим. Иначе между
	# очисткой и подъёмом нового сэмплера (а между ними ещё dns_restart — это секунда и больше)
	# старый успевает проснуться, увидеть в $SPID СВОЙ pid и вписать в ТОЛЬКО ЧТО очищенный журнал
	# записи прошлого окна: новое окно началось бы с чужих строк под подписью «за окно наблюдения».
	: > "$SPID" 2>/dev/null                 # пустой владелец ≠ pid любого живого сэмплера
	: > "$QLOG" 2>/dev/null                 # чистим лог прошлого окна (свежий срез)
	: > "$DEADLOG" 2>/dev/null              # …и журнал «не ответили»: окно новое — срез новый
	printf 'log-queries\nlog-facility=%s\n' "$QLOG" > "$QCONF"
	echo $(( $(now) + s )) > "$UNTIL"
	dns_restart
	# Авто-стоп: детач-сплилка на s секунд. Уникальный pidfile на запуск (перезапуск наблюдения
	# бампит UNTIL; старая сплилка проснётся, увидит UNTIL в будущем и НЕ тронет — стоп сделает
	# только та, что проснулась после реального UNTIL). Без -m -p матч всех sh → берём уник. имя.
	rm -f /tmp/devwatch-stop.*.pid 2>/dev/null
	start-stop-daemon -S -b -m -p "/tmp/devwatch-stop.$$.pid" -x /bin/sh -- "$SELF" _autostop "$s" 2>/dev/null
	printf '{"ok":true,"watching":true,"secs_left":%d}\n' "$s"
}

stop() {
	rm -f "$QCONF" "$UNTIL" 2>/dev/null
	dns_restart
	printf '{"ok":true,"watching":false,"secs_left":0}\n'
}

# Внутренняя: поспать окно и выключить, ЕСЛИ окно реально истекло (иначе наблюдение продлили).
_autostop() {
	# ЭТА ЖЕ сплилка теперь и СЭМПЛЕР: раз в SAMPLE_EVERY снимает мёртвые потоки в журнал окна.
	# Почему здесь, а не в `view`: журнал обязан копиться и при ЗАКРЫТОМ экране — иначе он повторил
	# бы болезнь живого списка («смотришь — видишь, отвернулся — потерял»), а домены копятся именно
	# так, независимо от панели.
	# Прежняя логика «проснулся, UNTIL в будущем — уходи» работала на ОДНОМ пробуждении. У цикла
	# так нельзя: перезапуск окна поднимает ВТОРУЮ сплилку, и обе писали бы в один журнал. Владелец
	# окна — тот, чей pid лежит в $SPID (последний записавший), остальные уходят на первом же тике.
	echo $$ > "$SPID" 2>/dev/null
	_dwleft="${1:-$DEF_SECS}"
	while [ "$_dwleft" -gt 0 ]; do
		[ "$(cat "$SPID" 2>/dev/null)" = "$$" ] || exit 0   # окно перезапустили — мы лишние
		watching || break                                   # истекло или нажали «Стоп»
		ct_list_all | ct_scan | awk '$5>0' | _dead_merge
		sleep "$SAMPLE_EVERY"
		_dwleft=$((_dwleft - SAMPLE_EVERY))
	done
	watching && exit 0        # UNTIL ещё в будущем → продлили, эта сплилка лишняя
	# watching()=false в ДВУХ случаях: (а) окно истекло (QCONF ещё на месте) — надо снять+рестартнуть;
	# (б) юзер уже нажал «Стоп» (stop() убрал QCONF и УЖЕ перезапустил dnsmasq) — тогда повторный
	# рестарт = лишний DNS-блип на весь LAN через минуту после ручного стопа. Различаем по наличию QCONF.
	[ -f "$QCONF" ] || exit 0
	rm -f "$QCONF" "$UNTIL" 2>/dev/null
	dns_restart
}

# JSON-массив доменов (свежие сверху, уникальные, ≤LIMIT) для клиента <ip> из query-log.
# Формат строки dnsmasq: "... query[A] example.com from 192.168.31.121" — берём поле ПЕРЕД
# "from", когда следующее поле = наш ip. Reverse+dedup: свежие первыми, без повторов.
# --- «Что куда идёт» (индикатор маршрута) ------------------------------------
# Смысл: список доменов/соединений без ответа «а этот сейчас в VPN или мимо?» заставляет
# пользователя гадать и тыкать наугад. Считаем маршрут ЧЕСТНО, в том же порядке, в каком его
# решает ядро: сперва вырезы (цепочка VPN_EXCLUDE стоит первой в mangle PREROUTING и ACCEPT'ом
# рвёт обход), потом маркировка по сетам. Порядок проверок ниже = порядок правил на роутере.
#
# ДОМЕНЫ — без единого форка: их маршрут задан СТРОКАМИ в dnsmasq-конфах, читаем конфы разом в
# строки и матчим через case (busybox без index(); та же идиома, что BSET ниже).
# Свои домены разбираем ПО СЕТУ, а не скопом: enodia_list = «в VPN», enodia_bypass = «мимо VPN»
# (domain.sh держит оба направления в одном файле — см. его шапку). Скопом было бы враньё:
# домен, уведённый мимо, показывался бы как «в VPN».
#
# ЧЛЕНСТВО В СПИСКЕ, А НЕ АНКОР НА КОНЕЦ СТРОКИ: строка conf'а агрегирована — `ipset=/дом/a,b`
# (groups.sh; dnsmasq применяет к домену РОВНО ОДНУ строку, поэтому сеты домена сведены в одну).
# Прежний `s|/grp_vpn$|` видел бы только ПОСЛЕДНИЙ сет списка, а домен, попавший в середину,
# читался бы как «правила нет» — врал бы ровно там, где правило только что завели.
conf_doms() {   # <conf> <сет> → домены этого сета, через пробел
	awk -F/ -v s="$2" '/^ipset=/ && NF==3 && ("," $3 ",") ~ ("," s ",") {print $2}' "$1" 2>/dev/null | tr '\n' ' '
}
load_dom_routes() {
	GRP_CONF=/tmp/dnsmasq.d/10-groups.conf
	GEO_CONF=/tmp/dnsmasq.d/11-geo.conf
	CUSTOM_CONF=/etc/dnsmasq.d/enodia-custom.conf
	DOM_GRP_OUT=" $(conf_doms "$GRP_CONF" grp_out) "
	DOM_GRP_VPN=" $(conf_doms "$GRP_CONF" grp_vpn) "
	DOM_OWN_VPN=" $(conf_doms "$CUSTOM_CONF" enodia_list) "
	DOM_OWN_OUT=" $(conf_doms "$CUSTOM_CONF" enodia_bypass) "
	DOM_S2=" $(slot_doms 2) "; DOM_S3=" $(slot_doms 3) "; DOM_S4=" $(slot_doms 4) "
	# Домены «в десинк»: гео-категории с действием desync (сет geo_zapret в 11-geo.conf) и СВОЙ пул
	# менеджера источников (zapret_dom в 07-zapret-dom.conf). Своего conf'а у zapret больше нет —
	# вшитая четвёрка категорий снята, спрашивать нечего.
	DOM_ZAP=" $(conf_doms "$GEO_CONF" geo_zapret)$(conf_doms /tmp/dnsmasq.d/07-zapret-dom.conf zapret_dom) "
}

# --- правила САМОГО устройства (цепочка VPN_DEV) ------------------------------
# Они стоят ВЫШЕ всего остального (порядок цепочек в apply-bypass.sh), значит и спрашивать про
# них надо ПЕРВЫМИ. Без этого бейдж врал бы ровно там, где человек только что завёл правило:
# домен показывался бы «общим списком» или «группой», хотя едет он по правилу устройства.
# DEV_DOMS — токены «дом=вердикт» (членство через case, busybox без index()), DEV_SETS — «сет:вердикт»
# для адресов из conntrack (сеты держат и CIDR, строкой их не сматчить).
load_dev_rules() {   # $1 = IP клиента
	DEV_DOMS=" "; DEV_SETS=""
	# Устройство «целиком в десинк» (.desync-ips): его трафик идёт НАПРЯМУЮ и десинкается nfqws
	# ПО ИСТОЧНИКУ, то есть ни в один dst-набор это не записано и по адресам не читается вовсе.
	# Без флага такой клиент выглядел бы как «просто напрямую» — самый частый вопрос «режим включил,
	# а где он виден».
	DESYNC_SRC=0
	grep -qxF "$1" "$ENODIA_STATE/.desync-ips" 2>/dev/null && DESYNC_SRC=1
	[ -f "$ENODIA_DIR/groups.sh" ] || return 0
	_dvl=$(sh "$ENODIA_DIR/groups.sh" dev-list "$1" 2>/dev/null)
	[ -n "$_dvl" ] || return 0
	DEV_DOMS=" $(printf '%s\n' "$_dvl" | awk -F"$(printf '\t')" '
		$2 !~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+(\/[0-9]+)?$/ {
			v = ($3=="vpn") ? (($4+0 > 0) ? "slot" $4 : "vpn") : (($3=="block") ? "block" : "bypass")
			printf "%s=%s ", $2, v }') "
	DEV_SETS=$(sh "$ENODIA_DIR/groups.sh" dev-rules 2>/dev/null | awk -F"$(printf '\t')" -v ip="$1" '
		$1==ip { v = ($3=="vpn") ? (($4+0 > 0) ? "slot" $4 : "vpn") : (($3=="block") ? "block" : "bypass")
			print $2 ":" v }')
}
# Домены ДОП-ВЫХОДА (слота): grp_vpn_s<N> от groups.sh + geo_vpn_s<N> от geo.sh — ОБА, иначе
# гео-категория, уведённая на выход, показалась бы «общим списком». Читаем те же живые
# dnsmasq-конфы, что и базовые сеты (без форков), поэтому слоты стоят ровно столько же.
slot_doms() {   # $1 = id
	printf '%s%s' "$(conf_doms "$GRP_CONF" "grp_vpn_s$1")" "$(conf_doms "$GEO_CONF" "geo_vpn_s$1")"
}
# Слот-сеты, СУЩЕСТВУЮЩИЕ на роутере, в порядке ядра (для каждого N: grp, затем geo; N = 2,3,4).
# Список собираем ОДНИМ `ipset list -n`, а не шестью `ipset test` на каждый адрес: у большинства
# доп-выходов нет вовсе, и тогда цикл в ip_route не делает НИ ОДНОГО лишнего форка (замер в
# шапке ip_route: 200 форков ≈ 0.21 с — вслепую добавить 6 сетов на адрес удвоило бы окно).
load_slot_sets() {
	SLOT_SETS=""
	_have=" $(ipset list -n 2>/dev/null | tr '\n' ' ') "
	for _n in 2 3 4; do
		for _p in grp_vpn_s geo_vpn_s; do
			case "$_have" in *" $_p$_n "*) SLOT_SETS="$SLOT_SETS $_p$_n" ;; esac
		done
	done
}

# --- ГДЕ ДЕСИНК СТОИТ НА САМОМ ДЕЛЕ -------------------------------------------
# Раньше источник «десинк» ставился по ЧЛЕНСТВУ адреса в списке существующих пулов — то есть по
# НАМЕРЕНИЮ, а не по факту. Два расхождения, оба замерены 28.08.2026 на BE7000:
#   * zapret заводит NFQUEUE ТОЛЬКО на `--dport 443` (его «ГРАНИЦА ЧЕСТНО», см. шапку zapret.sh),
#     а экран подписывал «десинк» соединению на UDP 7600, которого nfqws не видит вовсе — после
#     появления порт-правил такая подпись встала сразу на 27 строках среза;
#   * пул может СУЩЕСТВОВАТЬ и быть наполнен, а правил под него не заведено (выход-десинк
#     выключен) — тогда десинка нет ни для одного адреса этого пула.
# Поэтому спрашиваем ЯДРО: какие пары «сет:порт» реально уехали в NFQUEUE (плюс `@src:порт` —
# правила по ИСТОЧНИКУ, «устройство целиком в десинк»). Один форк на срез. Заведут второй порт или
# новый пул — экран поедет за ними сам, и второй копии этого знания в проекте не появится: прежний
# список слов был зеркалом zapret.sh и по построению мог отстать.
load_desync_wired() {
	DESYNC_WIRED=$(iptables -t mangle -S POSTROUTING 2>/dev/null | awk '
		/-j NFQUEUE/{ _s=""; _p=""; _src="";
		  for(i=1;i<=NF;i++){
		    if($i=="--match-set") _s=$(i+1);
		    else if($i=="--dport") _p=$(i+1);
		    else if($i=="-s") _src=$(i+1);
		  }
		  if(_p=="") next;
		  if(_s!="") print _s":"_p; else if(_src!="") print "@src:"_p }' 2>/dev/null | sort -u | tr '
' ' ')
}
# grp_name <домен> [слот] → «группа «Игры»» — ИМЯ группы, а не безликое «группа». Пользователь
# спрашивает «а почему этот домен мимо VPN?» — ответ «правило есть где-то в группах» бесполезен,
# надо сказать, в КАКОЙ. dnsmasq-conf имён не хранит (там только сет) → ищем домен в членах групп.
# Форки только на СОВПАДЕНИИ (домен уже признан членом группы), т.е. на единицы строк из десятков.
#
# ОДИН домен лежит в НЕСКОЛЬКИХ .list разом (тот же youtube.com — и в рабочем пуле, и в отключённом
# запасном): брать первый попавшийся нельзя, назовём чужую — и, скорее всего, ВЫКЛЮЧЕННУЮ группу,
# которая на маршрут не влияет вовсе. Поэтому перебираем все совпадения и берём ВКЛЮЧЁННУЮ, а при
# известном слоте — ещё и привязанную ИМЕННО к нему (маршрут-то мы уже определили по его сету).
# Имя — поле 5 реестра (id⇥enabled⇥dir⇥slot⇥name[⇥src]); когда-то читалось поле 4, т.е. СЛОТ
# (в панели это выглядело как «группа «0»»).
grp_name() {   # $1 = домен, $2 = слот (опц.; пусто = не проверять)
	for _gf in $(grep -lxF "$1" "$ENODIA_STATE/groups/"*.list 2>/dev/null); do
		_gid=$(basename "$_gf" .list)
		_gl=$(awk -F"$(printf '\t')" -v id="$_gid" '$1==id{print}' "$ENODIA_STATE/groups/groups.tsv" 2>/dev/null | head -1)
		[ -n "$_gl" ] || continue
		[ "$(printf '%s' "$_gl" | cut -f2)" = 1 ] || continue         # выключенная маршрут не задаёт
		# Группа УСТРОЙСТВА сюда не годится: её служебное имя ответило бы на вопрос «почему домен
		# идёт туда» чужим правилом (оно действует для другого источника). Для своего устройства
		# ответ даёт dom_route ещё выше — «правило устройства».
		[ -n "$(printf '%s' "$_gl" | cut -f6)" ] && continue
		if [ -n "$2" ] && [ "$(printf '%s' "$_gl" | cut -f4)" != "$2" ]; then continue; fi
		_gn=$(printf '%s' "$_gl" | cut -f5)
		[ -n "$_gn" ] && { printf 'группа «%s»' "$_gn"; return; }
	done
	printf 'группа'
}
# --- правила по портам (цепочка VPN_PORTS) ------------------------------------
# Они стоят ВЫШЕ всего остального: VPN_PORTS — ПЕРВАЯ цепочка в mangle PREROUTING (порядок держит
# ensure_prerouting_order в apply-bypass.sh), а её ACCEPT обрывает обход ТАБЛИЦЫ — до маркировки по
# сетам дело не доходит вовсе. Пока этой ветки не было, экран писал «в VPN» напротив каждого адреса
# из iplist_set, хотя правило «1024-65535 напрямую» уводило тот же трафик мимо туннеля (замерено
# 28.08.2026 на BE7000: ACCEPT правила насчитал 119K пакетов, игра при этом шла напрямую и не
# подключалась). Это то же враньё «сет наполнен ≠ трафик помечен», от которого сторожит гейт
# MARK_LIVE ниже, — только источник другой.
#
# Порт есть ТОЛЬКО у соединения: у домена его нет, поэтому у dom_route такой ветки быть не может —
# какое правило сработает, зависит от порта, который домен ещё не выбрал.
# Локалку спрашивать не нужно: преамбула VPN_PORTS RETURN'ит приватные сети, а emit_conns их и так
# не показывает.
#
# Читаем ОДИН раз на срез (как load_dev_rules): записи «proto:порты:куда» через пробел, порядок
# ФАЙЛА = порядок правил в цепочке, выигрывает первое совпавшее. Двоеточие разделителем безопасно —
# все три поля из словаря без двоеточий (proto/dir — слова, порты после port_list_norm = цифры,
# запятые, дефисы).
load_port_rules() {   # $1 = IP клиента
	PORT_RULES=""
	[ -s "$ENODIA_STATE/.port-rules" ] || return 0
	_lpt=$(printf '	')
	# `done < файл` (не пайп) — цикл в ТЕКУЩЕМ шелле, иначе PORT_RULES не пережил бы пайп.
	while IFS="$_lpt" read -r _psrc _ppro _ppts _pdir; do
		[ -n "$_pdir" ] || continue
		[ "$_psrc" = any ] || [ "$_psrc" = "$1" ] || continue
		case "$_ppro" in udp|tcp|both) ;; *) continue ;; esac
		case "$_pdir" in vpn|direct|block|s2|s3|s4) ;; *) continue ;; esac
		case "$_ppts" in ''|*[!0-9,al-]*) continue ;; esac   # цифры, запятые, дефис или слово all
		PORT_RULES="$PORT_RULES $_ppro:$_ppts:$_pdir"
	done < "$ENODIA_STATE/.port-rules"
}

# port_hit <список портов> <порт> → 0, если порт попадает в список («all» или «N,M-K»).
# Без форков: список режем через IFS, а не `tr` — на 50 соединений это полсотни лишних процессов.
# `set --` внутри функции меняет ЕЁ позиционные параметры, поэтому $1/$2 читаем в свои переменные
# ДО него.
port_hit() {
	[ "$1" = all ] && return 0
	_hl=$1; _hp=$2; _hI=$IFS; IFS=','
	set -- $_hl
	IFS=$_hI
	for _ht in "$@"; do
		case "$_ht" in
			*-*) _ha=${_ht%-*}; _hb=${_ht#*-}
			     if [ "$_hp" -ge "$_ha" ] 2>/dev/null && [ "$_hp" -le "$_hb" ] 2>/dev/null; then return 0; fi ;;
			*)   [ "$_ht" = "$_hp" ] && return 0 ;;
		esac
	done
	return 1
}

# port_route <proto> <порт> → PORT_VERDICT = vpn|direct|block|sN («» = правила нет).
# Переменной, а не печатью: ip_route зовут для КАЖДОГО соединения, и `$( )` стоил бы форка на
# каждое (замер в шапке ip_route: 200 форков ≈ 0.21 с — бюджет окна и так занят ipset test).
port_route() {
	PORT_VERDICT=""
	[ -n "$PORT_RULES" ] || return 0
	case "$1" in udp|tcp) ;; *) return 0 ;; esac   # icmp и прочее правилами по портам не ловится
	case "$2" in ''|0|*[!0-9]*) return 0 ;; esac
	for _pr in $PORT_RULES; do
		_ppr=${_pr%%:*}; _pdr=${_pr##*:}; _ppl=${_pr#*:}; _ppl=${_ppl%:*}
		[ "$_ppr" = both ] || [ "$_ppr" = "$1" ] || continue
		port_hit "$_ppl" "$2" || continue
		PORT_VERDICT=$_pdr
		return 0
	done
	return 0
}

# desync_via <ip> → DESYNC_VIA = «десинк устройства» | «десинк» | «» (пусто = десинка нет).
# Десинк — НЕ маршрут: трафик всё равно идёт напрямую, ломают только рукопожатие. Поэтому он
# всегда лишь ИСТОЧНИК — и спрашивают о нём ТРИ разные ветки ip_route (мёртвая маркировка, прямое
# правило по портам, общий низ). Держим ОДНУ копию: забыть спросить в одной из них — значит снова
# писать «просто напрямую» там, где десинк работает.
# Переменной, а не печатью: ip_route зовут на КАЖДОЕ соединение, `$( )` стоил бы форка на каждое.
desync_via() {   # $1 = ip назначения, $2 = порт назначения
	DESYNC_VIA=""
	[ -n "$2" ] || return 0                 # порта нет (icmp) — nfqws такой пакет не видит
	# Правила ПО ИСТОЧНИКУ («устройство целиком в десинк») — первыми: они специфичнее пула.
	case " $DESYNC_WIRED " in *" @src:$2 "*)
		[ "$DESYNC_SRC" = 1 ] && { DESYNC_VIA="десинк устройства"; return 0; } ;;
	esac
	for _dw in $DESYNC_WIRED; do
		case "$_dw" in @src:*) continue ;; esac
		[ "${_dw##*:}" = "$2" ] || continue      # правило заведено на ДРУГОЙ порт
		if ipset test "${_dw%:*}" "$1" >/dev/null 2>&1; then DESYNC_VIA=десинк; return 0; fi
	done
	return 0
}

# dom_route <домен> → печатает "маршрут|источник|своё". Пусто = явного правила НЕТ (домен поедет по
# общему списку/напрямую — по IP, а это уже видно в соединениях; врать «напрямую» тут нельзя).
# «своё»=1 → правило наше, одиночное (domain.sh) ⇒ панель может предложить его СНЯТЬ. Правило
# группы снимать поштучно нельзя (это состав группы) — панель вместо этого называет группу.
#
# ПОРЯДОК = порядок правил в ядре: «мимо VPN» (ACCEPT в VPN_EXCLUDE, цепочка первая в mangle
# PREROUTING) проверяется РАНЬШЕ маркировки. Домен, лежащий и там и там, реально поедет мимо —
# так и покажем.
#
# СУФФИКСНОЕ сравнение, а не точное: dnsmasq-правило `ipset=/youtube.com/…` ловит И все поддомены
# (www.youtube.com, i.ytimg…), а в query-log устройство светит именно ПОДдомен. Точный матч врал бы
# «правила нет» на самом частом случае (правило есть и работает). Поднимаемся к родителю, пока в
# имени 2+ точки — до голого TLD не доходим (правило «/com/» никто не пишет). Форков нет: чистые
# строковые case (busybox без index()), десятки доменов = десятки итераций.
dom_route() {
	_d="$1"
	while [ -n "$_d" ]; do
		# Правило САМОГО устройства — выше всех прочих цепочек, поэтому проверяется первым.
		case "$DEV_DOMS" in *" $_d="*)
			_dv=${DEV_DOMS#*" $_d="}; _dv=${_dv%% *}
			printf '%s|правило устройства|0' "$_dv"; return ;;
		esac
		case "$DOM_GRP_OUT" in *" $_d "*) printf 'bypass|%s|0' "$(grp_name "$_d" 0)"; return ;; esac
		case "$DOM_OWN_OUT" in *" $_d "*) printf 'bypass|свой домен|1'; return ;; esac
		# Десинк-пулы ПОСЛЕ вырезов, но ПЕРЕД слотами и общей маркировкой — ровно так их цепочка
		# (ENODIA_ZAPRET) стоит в mangle PREROUTING. Маршрут остаётся «напрямую»: десинк не меняет
		# путь пакета, он ломает рукопожатие — причину пишем источником (см. ip_route).
		case "$DOM_ZAP" in *" $_d "*) printf 'direct|десинк|0'; return ;; esac
		# Доп-выходы ПЕРЕД базовыми сетами: в mark-core слот-цикл стоит ВЫШЕ общего списка и
		# перебивает его. Проверь мы их после — домен, реально уезжающий в выход, показывался бы
		# как «в VPN, общий список» (ровно это и врало про youtube.com на byedpi-выходе).
		case "$DOM_S2" in *" $_d "*) printf 'slot2|%s|0' "$(grp_name "$_d" 2)"; return ;; esac
		case "$DOM_S3" in *" $_d "*) printf 'slot3|%s|0' "$(grp_name "$_d" 3)"; return ;; esac
		case "$DOM_S4" in *" $_d "*) printf 'slot4|%s|0' "$(grp_name "$_d" 4)"; return ;; esac
		case "$DOM_GRP_VPN" in *" $_d "*) printf 'vpn|%s|0' "$(grp_name "$_d" 0)"; return ;; esac
		case "$DOM_OWN_VPN" in *" $_d "*) printf 'vpn|свой домен|1'; return ;; esac
		case "$_d" in *.*.*) _d="${_d#*.}" ;; *) break ;; esac
	done
	# Явного правила на домен нет — но само УСТРОЙСТВО может быть «целиком в десинк» (nfqws по
	# источнику): тогда напрямую идёт всё, что оно спрашивает, и молчать об этом нельзя.
	[ "$DESYNC_SRC" = 1 ] && { printf 'direct|десинк устройства|0'; return; }
	printf '||0'
}
# ip_route <ip> → печатает "маршрут|источник". Форки ipset test НЕОБХОДИМЫ: сеты держат подсети
# (iplist_set = 3.5k CIDR), строкой их не сматчить. Короткое замыкание на первом попадании;
# замер на железе — 200 форков ≈ 0.21 с, для окна на 50 соединений приемлемо.
# Порядок = порядок правил в ядре: сперва всё, что даёт ACCEPT в VPN_EXCLUDE (плоский вырез,
# сет группы, сет одиночных доменов «мимо VPN»), потом маркировка по сетам.
ip_route() {   # <ip> [proto] [порт]
	# ПОРТ-ПРАВИЛА ПЕРВЫМИ — цепочка VPN_PORTS стоит выше выреза, правил устройства и маркировки
	# (см. блок load_port_rules). `direct`/`block` терминальны и без живой маркировки: первое —
	# просто ACCEPT, второе — DROP, оба работают на стоковом ядре. А `vpn`/`sN` без `ip rule`
	# мертвы, поэтому при MARK_LIVE=0 проваливаемся в общий гейт ниже — он ответит честное
	# «напрямую», а не выдуманный туннель.
	port_route "$2" "$3"
	case "$PORT_VERDICT" in
		block)  printf 'block|правило по портам';  return ;;
		vpn)    if [ "$MARK_LIVE" = 1 ]; then printf 'vpn|правило по портам'; return; fi ;;
		s[234]) if [ "$MARK_LIVE" = 1 ]; then printf 'slot%s|правило по портам' "${PORT_VERDICT#s}"; return; fi ;;
		direct)
			# «Напрямую» НЕ возвращаем молча: ACCEPT в VPN_PORTS живёт в PREROUTING, а NFQUEUE
			# десинка — в POSTROUTING. Это РАЗНЫЕ хуки, ACCEPT второй не отменяет, и десинк на
			# такой пакет продолжает действовать. Промолчав, экран написал бы «напрямую · правило
			# по портам» поверх РАБОТАЮЩЕГО десинка — то самое умолчание, от которого заведён
			# источник у веток ниже.
			desync_via "$1" "$3"
			if [ -n "$DESYNC_VIA" ]; then printf 'direct|правило по портам + %s' "$DESYNC_VIA"
			else printf 'direct|правило по портам'; fi
			return ;;
	esac
	# ДЕЙСТВУЕТ ЛИ НАША МАРКИРОВКА ВООБЩЕ. Всё, что ниже до десинка, судит по ЧЛЕНСТВУ В СЕТЕ —
	# а сет может быть наполнен при полностью пустом ядре: установка «только панель» прогревает
	# iplist_set (3.5k CIDR) ещё до выбора транспорта, References у него 0, правил в mangle нет
	# ни одного. На таком роутере экран устройства писал «в VPN» напротив 8.8.8.8, хотя роутер
	# работает КАК СТОК (замерено на AX3600 17.08.2026). Спрашиваем ядро — форма та же, что у
	# сторожа (watchdog.sh: `fwmark 0x1 lookup 1000`), плюс таблицы доп-выходов.
	# Десинк маркировки НЕ требует (nfqws в NFQUEUE) — его ветки ниже остаются живыми.
	if [ "$MARK_LIVE" != 1 ]; then
		desync_via "$1" "$3"
		[ -n "$DESYNC_VIA" ] && { printf 'direct|%s' "$DESYNC_VIA"; return; }
		printf 'direct|'; return
	fi
	# Сеты правил САМОГО устройства — цепочка VPN_DEV стоит выше выреза и общей маркировки.
	for _ds in $DEV_SETS; do
		ipset test "${_ds%%:*}" "$1" >/dev/null 2>&1 || continue
		printf '%s|правило устройства' "${_ds#*:}"; return
	done
	case "$BSET" in *" $1 "*) printf 'bypass|вырез'; return ;; esac
	ipset test grp_out    "$1" >/dev/null 2>&1 && { printf 'bypass|группа'; return; }
	ipset test enodia_bypass "$1" >/dev/null 2>&1 && { printf 'bypass|свой домен'; return; }
	# Слот-сеты ПЕРЕД базовыми (порядок mark-core: слот перебивает общий список). SLOT_SETS уже
	# отфильтрован по существующим и упорядочен — нет выходов, нет и форков.
	for _ss in $SLOT_SETS; do
		ipset test "$_ss" "$1" >/dev/null 2>&1 || continue
		case "$_ss" in geo_*) _sv=гео ;; *) _sv=группа ;; esac
		printf 'slot%s|%s' "${_ss##*_s}" "$_sv"; return
	done
	ipset test grp_vpn    "$1" >/dev/null 2>&1 && { printf 'vpn|группа';    return; }
	ipset test enodia_list   "$1" >/dev/null 2>&1 && { printf 'vpn|свой домен'; return; }
	ipset test iplist_set "$1" >/dev/null 2>&1 && { printf 'vpn|общий список'; return; }
	# Десинк — это НЕ отдельный маршрут: трафик всё равно идёт напрямую, у него лишь ломают
	# рукопожатие. Поэтому маршрут остаётся `direct` (новый токен потребовал бы правок панели), а
	# ПРИЧИНУ пишем в источник — иначе экран честно показывал бы «напрямую» и умалчивал о десинке.
	desync_via "$1" "$3"
	[ -n "$DESYNC_VIA" ] && { printf 'direct|%s' "$DESYNC_VIA"; return; }
	printf 'direct|'
}

emit_domains() {  # emit_domains <ip>
	ip="$1"; LIMIT=50
	# Печатаем ТОЛЬКО элементы (скобки [...] ставит view) — иначе "domains":[[]] в пустом случае.
	[ -f "$QLOG" ] || return
	load_dom_routes
	first=1
	awk -v ip="$ip" -v lim="$LIMIT" '
		{ for(i=1;i<=NF;i++) if($i=="from" && $(i+1)==ip){ a[++n]=$(i-1); break } }
		END{ c=0; for(i=n;i>=1;i--){ d=a[i]; if(d!="" && !(d in seen)){ seen[d]=1; print d; if(++c>=lim) break } } }
	' "$QLOG" 2>/dev/null | while IFS= read -r d; do
		[ -n "$d" ] || continue
		d=$(printf '%s' "$d" | tr -d '"\\')
		[ "$first" -eq 1 ] || printf ','
		first=0
		# Объект, а не голая строка: панели нужен ещё и маршрут домена (индикатор «что куда идёт»)
		# + признак «правило наше» (можно ли предложить кнопку «снять правило»).
		r=$(dom_route "$d"); rest="${r#*|}"
		printf '{"name":"%s","route":"%s","via":"%s","own":%s}' \
			"$d" "${r%%|*}" "${rest%|*}" "$([ "${rest##*|}" = 1 ] && echo true || echo false)"
	done
	printf ''
}

# ct_scan — РАЗБОР строк conntrack в машинный вид: «src dst dport proto noreply» на строку.
# ЕДИНСТВЕННОЕ место, где живут и разбор полей, и правило «поток мёртв»: потребителей ДВА — живой
# срез (emit_conns) и сэмплер окна (_autostop). Вторая копия правила разъехалась бы молча, и метка
# в списке говорила бы про одно соединение не то же, что запись в журнале.
#
# noreply = сколько пакетов УШЛО, не получив НИ ОДНОГО в ответ (0 = всё нормально). Флаг
# [UNREPLIED] ставит САМО ядро, счётчик первого направления даёт «сколько раз постучались». Порог
# 3 пакета (или TCP в SYN_SENT) отделяет мёртвый адрес от только что начатого соединения — иначе
# метка мигала бы на каждом здоровом коннекте в первые миллисекунды.
#
# В строке conntrack ДВА src=/dst= (оригинал + обратка) — берём ПЕРВЫЕ: обратка несёт WAN-адрес
# роутера, и по ней мы показали бы чужой публичный IP. Протокол берём ИМЕНЕМ, а не номером поля: у
# /proc впереди два лишних столбца («ipv4 2»), у утилиты conntrack их нет (ct-lib.sh отдаёт оба
# формата как есть), а голое tcp/udp встречается только в шапке строки — до первого src=.
#
# Приватку/богоны/мультикаст отсеиваем ЗДЕСЬ, у обоих потребителей вопрос один: «куда клиент ходит
# НАРУЖУ». Пустые поля заменяем затычками (`0`/`-`): `read` схлопывает подряд идущие разделители,
# и пустое поле В СЕРЕДИНЕ исчезло бы, сдвинув все следующие.
ct_scan() {
	awk '
	{ s=""; d=""; p=""; pr=""; hdr=1; unrep=0; np=0; tx=0; syn=0;
	  for(i=1;i<=NF;i++){
	    if(substr($i,1,4)=="src="){ if(s=="") s=substr($i,5); hdr=0; continue }
	    if(hdr && ($i=="tcp" || $i=="udp")){ pr=$i; continue }
	    if($i ~ /^dst=/ && d==""){ d=substr($i,5); continue }
	    if($i ~ /^dport=/ && p==""){ p=substr($i,7); continue }
	    if($i ~ /^packets=/){ np++; if(np==1) tx=substr($i,9)+0; continue }
	    if($i=="[UNREPLIED]"){ unrep=1; continue }
	    if($i=="SYN_SENT"){ syn=1; continue }
	  }
	  if(s=="" || d=="") next
	  if(d ~ /^(10\.|127\.|169\.254\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.|100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.|22[4-9]\.|23[0-9]\.|0\.)/) next
	  nr=0; if(unrep && (tx>=3 || syn)) nr=(tx>0?tx:1)
	  print s" "d" "(p==""?0:p)" "(pr==""?"-":pr)" "nr }
	' 2>/dev/null
}

# _dead_merge — влить свежие мёртвые потоки («src dst dport proto tx» на stdin) в журнал окна.
# Ключ — четвёрка «кто→куда:порт/прото», счётчик берём МАКСИМАЛЬНЫЙ (поток мог быть переоткрыт),
# отметку последнего появления — текущую. Потолок DEAD_MAX: новые КЛЮЧИ сверх него не заводим, уже
# известные обновляем всегда — иначе сканер портов вытеснил бы то, ради чего журнал и открыли.
#
# ПОМНИМ И ПЕРВОЕ ПОЯВЛЕНИЕ. Живому списку хватает мгновенного вердикта, а журнал ХРАНИТ запись всё
# окно — и туда лезет шум: TCP успевает побывать в SYN_SENT доли секунды на СОВЕРШЕННО ЗДОРОВОМ
# соединении, и один такой снимок остался бы в списке «не ответили» до конца окна (замерено на
# живом роутере 28.08.2026: за 15 с натекли две ложные записи с tx=1). Отсюда правило «молчал на
# ДВУХ опросах подряд» — сам фильтр в emit_dead, здесь только копим факты. Настоящий мёртвый поток
# это переживает: запись conntrack о нём держится десятками секунд, то есть попадёт в НЕСКОЛЬКО
# тиков подряд.
_dead_merge() {
	[ -f "$DEADLOG" ] || : > "$DEADLOG"
	# Ветки различаем ПО ЧИСЛУ ПОЛЕЙ, а не привычным `FNR==NR`: при ПУСТОМ журнале (первое окно,
	# первый тик) у первой же строки из stdin FNR==NR тоже истинно, и все свежие записи уехали бы
	# в разбор журнала — где их отсеет `NF>=6`. Итог: журнал вечно пуст, и ни одной ошибки в логе.
	# Формы разные по построению: журнал несёт отметку времени шестым полем, свежая запись — нет.
	awk -v now="$(now)" -v cap="$DEAD_MAX" '
		NF>=7 { k=$1" "$2" "$3" "$4; if(!(k in O)){O[k]=1; n++} TX[k]=$5+0; F[k]=$6+0; TS[k]=$7+0; next }
		NF==5 { k=$1" "$2" "$3" "$4
		  if(!(k in O)){ if(n>=cap) next; O[k]=1; n++; F[k]=now }
		  if($5+0>TX[k]) TX[k]=$5+0
		  TS[k]=now }
		END{ for(k in O) print k" "TX[k]" "F[k]" "TS[k] }
	' "$DEADLOG" - > "$DEADLOG.new" 2>/dev/null && mv "$DEADLOG.new" "$DEADLOG" 2>/dev/null
	rm -f "$DEADLOG.new" 2>/dev/null
}

# JSON-массив активных соединений {ip,port,rule,route,via,noreply} клиента <ip> из conntrack (уник.
# по dst, без приватки/LAN — их «мимо VPN» бессмысленно). rule = НАШЕ правило по этому адресу
# (подсказка UI). noreply = сколько пакетов УШЛО в адрес, не получив НИ ОДНОГО в ответ (0 = всё
# нормально): «куда трафик не доходит» — вопрос, ради которого этот экран и открывают, а список
# живых соединений на него не отвечал вовсе. Отвечает conntrack: флаг [UNREPLIED] он ставит сам,
# счётчик первого направления даёт «сколько раз постучались». Порог 3 пакета (или TCP в SYN_SENT)
# отделяет мёртвый адрес от только что начатого соединения — иначе метка мигала бы на каждом
# здоровом коннекте в первые миллисекунды.
emit_conns() {  # emit_conns <ip>
	ip="$1"; LIMIT=50
	# Наборы адресов с правилом (строкой, /32 срезан) — членство без форков (case), busybox без index().
	BSET=" $(sed 's#/32$##' "$ENODIA_STATE/.bypass-dst" 2>/dev/null | tr '\n' ' ') "
	VSET=" $(sed 's#/32$##' "$ENODIA_STATE/.vpn-dst"    2>/dev/null | tr '\n' ' ') "
	first=1
	ct_list_src "$ip" | ct_scan | awk '
		# ДЕДУП ПО АДРЕСУ БЕРЁТ ХУДШИЙ ПОТОК, а не первый попавшийся: к одному серверу их бывает
		# несколько, и отвечающий keepalive прятал бы молчащий игровой порт — ровно тот случай,
		# ради которого метка и заведена. Печатаем в END, порядок всё равно задаёт sort ниже.
		{ d=$2; nr=$5+0; if(!(d in best) || nr>best[d]){ best[d]=nr; P[d]=$3; PR[d]=$4 } }
		END{
		  # Первое поле — приоритет для sort: мёртвые ВВЕРХ, иначе head -50 срезал бы именно их
		  # (замерено 28.08.2026: у активного ПК срез упирался в лимит). busybox sort без -k
		  # сортирует строку целиком, ведущая цифра и решает — ключ обязан быть ПЕРВЫМ полем.
		  for(d in best) print (best[d]?0:1)" "d" "P[d]" "PR[d]" "best[d]
		}
	' 2>/dev/null | sort | head -n "$LIMIT" | while read -r _dwpri cip cport cproto cnr; do
		[ -n "$cip" ] || continue
		# rule — НАШЕ одиночное правило по адресу: vpn (.vpn-dst) | bypass (.bypass-dst) | "" (нет).
		# Ровно три состояния домена (см. domain.sh), поэтому UI рисует те же три кнопки. Это НЕ
		# то же, что route/via ниже: route — ФАКТИЧЕСКИЙ маршрут, он может быть «мимо» из-за
		# группы или общего списка, а снять групповое правило кнопкой одиночного нельзя — не
		# путаем «почему едет так» с «что тут можем снять мы».
		rule=""; case "$BSET" in *" $cip "*) rule=bypass ;; esac
		[ -n "$rule" ] || case "$VSET" in *" $cip "*) rule=vpn ;; esac
		case "$cport" in ''|*[!0-9]*) cport=0 ;; esac
		case "$cproto" in udp|tcp) ;; *) cproto="" ;; esac
		case "$cnr" in ''|*[!0-9]*) cnr=0 ;; esac
		[ "$first" -eq 1 ] || printf ','
		first=0
		r=$(ip_route "$cip" "$cproto" "$cport")
		printf '{"ip":"%s","port":%d,"rule":"%s","route":"%s","via":"%s","noreply":%d}' "$cip" "$cport" "$rule" "${r%%|*}" "${r#*|}" "$cnr"
	done
	printf ''
}

# JSON-массив «не ответили за окно наблюдения» {ip,port,proto,tx,ago,route,via} для клиента <ip>.
# Живой список отвечает «что молчит СЕЙЧАС», этот — «что молчало, пока мы смотрели», включая уже
# закрывшееся: запись conntrack о молчащем потоке живёт минуту, и без журнала такой случай нельзя
# было увидеть вовсе. Пересечение между списками ЗАКОННО и намеренно: пока попытки идут, адрес
# виден в обоих, и это ровно то, что человек ожидает («вот оно сейчас, вот оно же за окно»).
# Свежие сверху: отметку времени ставим ПЕРВЫМ полем — у busybox sort нет ключей, он сортирует
# строку целиком. Возраст — через age_since: часы прыгают, голая разность врала бы «час назад».
#
# ПОКАЗЫВАЕМ ТОЛЬКО ТО, ЧТО МОЛЧАЛО НА ДВУХ ОПРОСАХ ПОДРЯД (last − first >= SAMPLE_EVERY): иначе
# сюда попадает мгновенный SYN_SENT здорового соединения и висит тут всё окно. В живом списке
# такого фильтра не нужно — там запись исчезает сама, как только соединение установилось.
emit_dead() {   # emit_dead <ip>
	[ -s "$DEADLOG" ] || return
	first=1
	awk -v me="$1" -v grace="$SAMPLE_EVERY" '$1==me && NF>=7 && ($7-$6)>=grace { print $7" "$2" "$3" "$4" "$5 }' "$DEADLOG" 2>/dev/null \
		| sort -r | head -n "$DEAD_SHOW" | while read -r dts dip dport dproto dtx; do
		[ -n "$dip" ] || continue
		case "$dport" in ''|*[!0-9]*) dport=0 ;; esac
		case "$dproto" in udp|tcp) ;; *) dproto="" ;; esac
		case "$dtx" in ''|*[!0-9]*) dtx=0 ;; esac
		[ "$first" -eq 1 ] || printf ','
		first=0
		r=$(ip_route "$dip" "$dproto" "$dport")
		printf '{"ip":"%s","port":%d,"proto":"%s","tx":%d,"ago":%d,"route":"%s","via":"%s"}' \
			"$dip" "$dport" "$dproto" "$dtx" "$(age_since "$dts")" "${r%%|*}" "${r#*|}"
	done
	printf ''
}

# Единый срез для панели: наблюдаем ли, сколько осталось, домены, соединения. ОДИН вызов (DRY,
# меньше форков на поллинг). ip уже провалидирован CGI (dotted-quad) — в shell не расширяется опасно.
view() {  # view <ip>
	ip="$1"
	# ОДИН форк на весь срез (индикатор зовут для каждого домена и каждого соединения) — см.
	# комментарий в ip_route: без живой маркировки членство в сете ещё ничего не значит.
	MARK_LIVE=0
	ip -4 rule show 2>/dev/null | grep -qE 'fwmark 0x[1-4](/\S+)? lookup 100[0-4]' && MARK_LIVE=1
	# Загрузчики — ОДИН раз на срез и ДО обоих списков: ip_route зовут и живой список, и журнал
	# «не ответили за окно». Держи их внутри emit_conns — и второй список молча зависел бы от
	# порядка вызовов (работает, пока сосед вызван раньше; перестанет — беззвучно).
	load_slot_sets                  # какие слот-сеты есть (ip_route ходит по ним ПЕРЕД базовыми)
	load_dev_rules "$ip"            # …а по сетам ПРАВИЛ УСТРОЙСТВА — ещё раньше (VPN_DEV выше всех)
	load_port_rules "$ip"           # …а VPN_PORTS — выше и них (первая цепочка в mangle PREROUTING)
	load_desync_wired               # …и отдельно: на каких «сет:порт» десинк РЕАЛЬНО стоит
	w=false; watching && w=true
	printf '{"watching":%s,"secs_left":%s,"domains":[' "$w" "$(secs_left)"
	emit_domains "$ip"
	printf '],"conns":['
	emit_conns "$ip"
	printf '],"dead":['
	emit_dead "$ip"
	printf ']}\n'
}

case "$1" in
	start)     start "$2" ;;
	stop)      stop ;;
	status)    w=false; watching && w=true; printf '{"watching":%s,"secs_left":%s}\n' "$w" "$(secs_left)" ;;
	view)      case "$2" in *[!0-9.]*|'') printf '{"error":"bad ip"}\n' ;; *) view "$2" ;; esac ;;
	_autostop) _autostop "$2" ;;
	*)         echo "usage: $0 {start [secs]|stop|status|view <ip>}" >&2; exit 1 ;;
esac
