#!/bin/sh
# lease-lib.sh — ЕДИНСТВЕННЫЙ ответ «кому принадлежит адрес в локальной сети».
#
# ЗАЧЕМ ОТДЕЛЬНАЯ БИБЛИОТЕКА. Вся политика проекта висит на IPv4 клиента: `.bypass-ips`,
# `.fullvpn-ips`, `.desync-ips`, `.keep-vpn-ips`, `.port-rules`, правила устройства в groups.sh —
# везде ключ это адрес. А адрес НЕ является идентичностью устройства: его выдаёт dnsmasq на
# 12 часов (miot — на час), и телефоны давно ходят с РАНДОМИЗИРОВАННЫМ MAC. Смена MAC = новая
# аренда = новый IP; старая при этом живёт в `/tmp/dhcp.leases` до истечения срока.
#
# Что из этого следует и ради чего написан файл (замерено на живом роутере 10.08.2026, 5 из 11
# клиентов уже с locally administered MAC):
#   1. СПИСОК УСТРОЙСТВ ВРЁТ. Один телефон видно ДВАЖДЫ — под старым и новым адресом, — и
#      родная морда Xiaomi (она смотрит на живые ассоциации, а не на аренды) показывает только
#      новый. Ровно с этого начинается «в панели один IP, в морде другой».
#   2. ПРАВИЛО МОЛЧА УЕЗЖАЕТ. Настроили «этот ноут целиком в VPN» — ноут переподключился с новым
#      MAC, получил другой адрес, и правило осталось на прежнем. У ноутбука политики больше нет,
#      а прилетевший на освободившийся адрес сосед её унаследовал. Ни одна проверка проекта этого
#      не ловит: правило есть, iptables тикает, «всё работает».
#
# КОНТРАКТ. Библиотека только ЧИТАЕТ состояние сети (аренды + neighbor) и ведёт ОДИН свой
# персист — `.ip-owner`, снимок «кому принадлежал адрес в момент, когда на него завели правило».
# Сравнение снимка с текущим владельцем и есть ответ на вопрос «правило ещё про то устройство?».
#   lease_mac_of  <ip>    — MAC из аренды (пусто = аренды нет: статика на клиенте или ушёл срок)
#   lease_host_of <ip>    — имя из аренды («*» = без имени ⇒ пусто)
#   lease_exp_of  <ip>    — unix-время истечения аренды
#   lease_ip_of_mac <mac> — где этот MAC СЕЙЧАС (самая свежая его аренда)
#   neigh_mac_of  <ip>    — MAC из neighbor-таблицы (единственный источник для статики)
#   ip_owner_now  <ip>    — владелец сейчас: аренда, иначе neighbor
#   mac_is_random <mac>   — код 0, если MAC локально администрируемый (privacy-MAC телефона)
#   ip_is_local   <ip>    — код 0, если адрес вообще принадлежит сетям ЭТОГО роутера
#   owner_note    <ip>    — запомнить нынешнего владельца адреса (зовут при заведении правила)
#   owner_get     <ip>    — что запомнили: `MAC<TAB>host<TAB>ts` (пусто = не запоминали)
#   owner_forget  <ip>    — забыть (правил на адресе не осталось)
#
# ПОЧЕМУ СНИМОК, А НЕ ЖУРНАЛ АРЕНД. Журнал требует, чтобы кто-то регулярно его вёл (cron/сторож),
# и всё равно теряет смены между тиками. Нам же нужен ровно один факт — состояние на момент
# заведения правила, — и его знает тот, кто правило заводит.
#
# busybox-замечания: нет `local` ⇒ все переменные с префиксом `_l` (затирать имена вызывающего
# нельзя — грабля с `_id` в vpn-server.sh); у `sort` НЕТ `-k` ⇒ «самая свежая аренда» ищется
# awk-проходом с максимумом, а не сортировкой; MAC везде приводим к НИЖНЕМУ регистру (аренды и
# neighbor печатают строчными, а панель Xiaomi и человек — заглавными, и строки перестали бы
# совпадать сами с собой).

LEASE_FILE="${LEASE_FILE:-/tmp/dhcp.leases}"
LEASE_OWNER_FILE="${LEASE_OWNER_FILE:-${ENODIA_DIR:-/data/usr/app/enodia}/.ip-owner}"
LEASE_OWNER_MAX=300          # кольцо: строка ~50 Б, потолок держит файл в пределах 15 КБ на 20-МБ флеше

_lmac_norm() { printf '%s' "$1" | tr 'A-Z' 'a-z' | tr -d ' \t\r\n'; }

# --- аренды dnsmasq: <expiry> <mac> <ip> <host> <clientid> -------------------------------
lease_mac_of()  { [ -n "$1" ] || return 1; awk -v w="$1" '$3==w{print $2; exit}' "$LEASE_FILE" 2>/dev/null; }
lease_exp_of()  { [ -n "$1" ] || return 1; awk -v w="$1" '$3==w{print $1; exit}' "$LEASE_FILE" 2>/dev/null; }
# Имя «*» dnsmasq пишет, когда клиент его не прислал — для читателя это ПУСТО, а не звёздочка.
lease_host_of() {
    [ -n "$1" ] || return 1
    _lh=$(awk -v w="$1" '$3==w{print $4; exit}' "$LEASE_FILE" 2>/dev/null)
    [ "$_lh" = "*" ] && _lh=""
    printf '%s' "$_lh"
}

# Где MAC сейчас. Аренд на один MAC бывает НЕСКОЛЬКО (клиент менял client-id, dual-boot),
# поэтому берём с максимальным сроком истечения — она и есть действующая.
lease_ip_of_mac() {
    [ -n "$1" ] || return 1
    _lm=$(_lmac_norm "$1")
    awk -v m="$_lm" '$2==m && $1+0>b {b=$1+0; ip=$3} END{if(ip!="") print ip}' "$LEASE_FILE" 2>/dev/null
}

# --- neighbor: единственный источник для устройства со СТАТИКОЙ на клиенте ---------------
# FAILED/INCOMPLETE — это «спрашивали, никто не ответил», такая запись владельцем не считается.
neigh_mac_of() {
    [ -n "$1" ] || return 1
    ip neigh show 2>/dev/null | awk -v w="$1" '$1==w && /lladdr/ && $NF!="FAILED" && $NF!="INCOMPLETE"{print $5; exit}'
}

# Владелец адреса СЕЙЧАС. Порядок источников: аренда (там же имя), затем neighbor.
ip_owner_now() {
    _lo=$(lease_mac_of "$1")
    [ -n "$_lo" ] || _lo=$(neigh_mac_of "$1")
    [ -n "$_lo" ] || return 1
    _lmac_norm "$_lo"
}

# Локально администрируемый MAC = бит 0x02 первого октета. Практически всегда это privacy-MAC
# телефона: он МЕНЯЕТСЯ, и закрепление адреса за таким MAC бессмысленно — панель обязана про это
# сказать, иначе человек «закрепит IP» и получит тот же дрейф через неделю.
mac_is_random() {
    case "$(_lmac_norm "$1")" in
        ?[2367abef]:*) return 0 ;;
    esac
    return 1
}

# АДРЕС ИЗ ЭТОЙ СЕТИ ВООБЩЕ? Третий вопрос про адрес — после «чей он» и «не уехал ли»:
# СУЩЕСТВУЕТ ли он здесь. Правила ключуются по IPv4, а бэкап настроек носят МЕЖДУ роутерами, и
# с чужого приезжают адреса чужой локалки (замерено на импорте BE7000→AX3600: три правила на
# 192.168.31.x при нашей сети 192.168.28.0/24). Сработать они не могут НИКОГДА, но в списке
# устройств выглядят обычной строкой «мимо VPN» — человек уверен, что настройка на месте.
# Спрашиваем ЯДРО (`ip route get`): оно одно знает маски ВСЕХ мостов, и своего разбора CIDR на
# busybox заводить не надо. Локальный = ведёт в мост (br-lan/br-guest/br-miot) ЛИБО лежит в
# подсети «доступа домой»: режимы пиров хранит apply-bypass по адресу пира, а несущей awgs0 при
# выключенном сервере нет вовсе ⇒ по маршруту адрес пира неотличим от чужого (проверено: уходит
# в WAN через шлюз). Дефолт подсети — тот же, что у vpn-server.sh::subnet().
ip_is_local() {
    [ -n "$1" ] || return 1
    # Маршрут спрашиваем ПЕРВЫМ: подавляющее большинство адресов — обычные клиенты локалки, и
    # они отвечают здесь же, не читая файлов. `lo` — адрес САМОГО роутера (`ip route get` печатает
    # `local … dev lo`): он местный, и правило на нём бессмысленно по другой причине, чужой сетью
    # его звать нельзя. Берём ПЕРВУЮ строку: у `ip route get` за ней идёт `cache`-хвост.
    _ldev=$(ip route get "$1" 2>/dev/null | sed -n '1s/.* dev \([^ ]*\).*/\1/p')
    case "$_ldev" in br-*|awgs0|lo) return 0 ;; esac
    # Не мост — но, возможно, пир «доступа домой»: при ВЫКЛЮЧЕННОМ сервере несущей awgs0 нет
    # вовсе, и адрес пира по маршруту неотличим от чужого (проверено: уходит в WAN через шлюз).
    _lsub=$(cat "${ENODIA_DIR:-/data/usr/app/enodia}/server/subnet" 2>/dev/null)
    [ -n "$_lsub" ] || _lsub=10.77.0
    case "$1" in "$_lsub".*) return 0 ;; esac
    return 1
}

# --- снимок «кому принадлежал адрес, когда на него завели правило» -----------------------
# Файл: IP<TAB>MAC<TAB>host<TAB>unix-время. Одна строка на адрес, перезапись — целиком.
owner_get() {
    [ -n "$1" ] || return 1
    [ -f "$LEASE_OWNER_FILE" ] || return 1
    awk -F'\t' -v w="$1" '$1==w{print $2"\t"$3"\t"$4; exit}' "$LEASE_OWNER_FILE" 2>/dev/null
}

# Записываем ТОЛЬКО когда владелец известен: строка без MAC ничего не доказывает, а по её наличию
# читатель судит «правило заводили вот для этого устройства». Часы роутера до ntpsetclock врут
# (RTC нет) — метку времени в таком случае не ставим, читателю она нужна лишь для показа.
owner_note() {
    [ -n "$1" ] || return 1
    _lom=$(ip_owner_now "$1") || return 1
    _loh=$(lease_host_of "$1")
    _lot=$(date +%s 2>/dev/null); [ "${_lot:-0}" -gt 1700000000 ] 2>/dev/null || _lot=0
    _lof=$(dirname "$LEASE_OWNER_FILE")
    [ -d "$_lof" ] || return 1
    _lotmp="$LEASE_OWNER_FILE.tmp.$$"
    { [ -f "$LEASE_OWNER_FILE" ] && awk -F'\t' -v w="$1" '$1!=w' "$LEASE_OWNER_FILE" 2>/dev/null | tail -n "$LEASE_OWNER_MAX"
      printf '%s\t%s\t%s\t%s\n' "$1" "$_lom" "$_loh" "$_lot"
    } > "$_lotmp" 2>/dev/null || { rm -f "$_lotmp" 2>/dev/null; return 1; }
    mv "$_lotmp" "$LEASE_OWNER_FILE" 2>/dev/null || { rm -f "$_lotmp" 2>/dev/null; return 1; }
    return 0
}

owner_forget() {
    [ -n "$1" ] || return 1
    [ -f "$LEASE_OWNER_FILE" ] || return 0
    _lotmp="$LEASE_OWNER_FILE.tmp.$$"
    awk -F'\t' -v w="$1" '$1!=w' "$LEASE_OWNER_FILE" 2>/dev/null > "$_lotmp" || { rm -f "$_lotmp" 2>/dev/null; return 1; }
    mv "$_lotmp" "$LEASE_OWNER_FILE" 2>/dev/null || { rm -f "$_lotmp" 2>/dev/null; return 1; }
    return 0
}
