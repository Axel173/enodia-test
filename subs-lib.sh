#!/bin/sh
# subs-lib.sh — ОБЩИЙ слой подписок: реестр `.subs` + закачка тела + анти-SSRF.
#
# Зачем отдельным файлом. Раньше «скачать подписку» умела ровно одна точка — CGI `fetch_sub`
# (панель), потому что разбор тела жил в БРАУЗЕРЕ. С появлением headless-обновления по cron
# (`subs-update.sh`) потребителей стало два, а копировать гард от SSRF и детект gzip в оба —
# ровно та ситуация, из которой выросла грабля «stale lists-lib» (две копии разъехались).
# Поэтому: примитивы — здесь, потребители сорсят с шим-фолбэком (как ip-lib/dns-lib/router-lib).
#
# Формат реестра `$ENODIA_STATE/.subs` — строки «tag⇥url⇥label» (⇥=TAB, label последним: может
# содержать пробелы). URL = КРЕД: наружу (list/бэкап-без-секретов/diag) не отдаётся, работа
# с подпиской идёт по tag. Файл пишет только CGI (save_sub/rename_sub/edit_sub_url/remove_sub),
# здесь — только ЧТЕНИЕ: cron не должен трогать реестр (иначе гонка с панелью).

: "${ENODIA_STATE:=/data/usr/app/enodia-state}"
# Реестр подписок — ПЕРСИСТ, а прежнее имя переменной указывало на каталог КОДА. Алиас
# каталога — самая незаметная форма такой ошибки: слэша после него нет, поэтому его не
# видит ни grep по `$ENODIA_DIR/`, ни проверка C46. Имя теперь само говорит, где файл.
SUBS_STATE="$ENODIA_STATE"

SUBS_TAB=$(printf '\t')

# sub_ip_public <адрес> — ЛИТЕРАЛ адреса публичный? Вынесено из sub_host_public по двум
# причинам: тот же вердикт нужен КАЖДОМУ шагу редиректа (см. sub_get_once), и у IPv6 гарда
# не было вовсе — `http://[::1]:8088/…` проезжал мимо проверки целиком (имя с двоеточием шло
# в nslookup, тот литерал не резолвит, а «не зарезолвили» здесь трактуется как «пропускаем»).
sub_ip_public() {
	case "$1" in
		*:*)
			_l6=$(printf '%s' "$1" | tr 'A-Z' 'a-z')
			case "$_l6" in
				*::ffff:*.*.*.*) sub_ip_public "${_l6##*:}"; return $? ;;   # v4-mapped
				::|::1|0:0:0:0:0:0:0:1) return 1 ;;                         # loopback/unspecified
				fe8*:*|fe9*:*|fea*:*|feb*:*) return 1 ;;                    # link-local fe80::/10
				f[cd]*:*) return 1 ;;                                       # ULA fc00::/7
			esac
			return 0 ;;
	esac
	case "$1" in
		127.*|10.*|169.254.*|192.168.*|0.*|255.255.255.255) return 1 ;;
		172.16.*|172.17.*|172.18.*|172.19.*|172.2[0-9].*|172.3[0-1].*) return 1 ;;
	esac
	return 0
}

# sub_host_public <url> — хост URL публичный? Панель и cron ходят под root, поэтому ссылка
# подписки НЕ должна вести на внутренние сервисы (127.0.0.1:8088, роутер 192.168.31.1,
# cloud-metadata 169.254.169.254). Имя резолвим и проверяем полученный IP. 0 = публичный
# (можно), 1 = приватный/loopback/link-local (блок). Не зарезолвили — НЕ блокируем (curl всё
# равно не сходит; ложно отвергать легит-подписку при неготовом DNS не хотим).
sub_host_public() {
	_h=$(printf '%s' "$1" | sed -e 's|^[a-zA-Z][a-zA-Z0-9+.-]*://||' -e 's|[/?#].*$||' -e 's|^[^@]*@||' -e 's|\]:[0-9]*$|]|' -e 's|:[0-9]*$||' -e 's|^\[||' -e 's|\]$||')
	[ -n "$_h" ] || return 1
	case "$_h" in
		*:*)       _ip="$_h" ;;                       # IPv6-литерал (скобки уже сняты)
		*[!0-9.]*) _ip=$(nslookup "$_h" 2>/dev/null | awk '/^Name:/{f=1;next} f&&/Address/{x=$NF; if(x ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$/){print x; exit}}') ;;
		*)         _ip="$_h" ;;
	esac
	[ -n "$_ip" ] || return 0
	sub_ip_public "$_ip"
}

# Потолок тела подписки. Тело живёт в /tmp = ОЗУ, а 200 серверов — это десятки КБ: всё, что
# больше, либо не подписка, либо злой умысел. Ограничение НУЖНО в двух местах — на закачке и на
# РАСПАКОВКЕ: «1 КБ архива → гигабайт распакованного» кладёт роутер целиком, а gunzip мы зовём
# на любом теле (магию байтов не читаем — `od` в busybox нет).
SUB_MAXSIZE=${SUB_MAXSIZE:-4194304}

# sub_get_once <url> <файл> [доп. опции curl] — одна попытка со следованием редиректам ВРУЧНУЮ.
# Почему не `-L --max-redirs 3`: короткая цепочка от подмены не защищает НИСКОЛЬКО — гард
# sub_host_public проверяет только ИСХОДНУЮ ссылку, а ОДНОГО хопа `Location: http://127.0.0.1:8088/…`
# довольно, чтобы root-curl сходил во внутренний сервис (комментарий тут прежде утверждал
# обратное). Теперь каждый хоп проходит тот же гард ДО перехода.
# `-f` намеренно НЕТ: тело ошибки провайдера («No keys available after processing») читает
# update_one и показывает человеку ЕГО СЛОВА вместо «не распознали серверов».
sub_get_once() {
	_gu="$1"; _go="$2"; shift 2
	_hop=0
	while [ "$_hop" -le 3 ]; do
		sub_host_public "$_gu" || return 1
		rm -f "$_go" 2>/dev/null
		_loc=$(curl -s --max-time 25 --max-filesize "$SUB_MAXSIZE" -A "be7000-panel/1.0" \
			"$@" -o "$_go" -w '%{redirect_url}' "$_gu" 2>/dev/null)
		[ -n "$_loc" ] || break
		_gu="$_loc"; _hop=$((_hop+1))
	done
	# --max-filesize молчит, когда сервер не сказал Content-Length (chunked), поэтому размер
	# сверяем и по факту: усечь по месту нечем (тело пишет сам curl), но принять — тем более.
	if [ -s "$_go" ]; then
		_sz=$(wc -c < "$_go" 2>/dev/null); case "$_sz" in ''|*[!0-9]*) _sz=0 ;; esac
		[ "$_sz" -gt "$SUB_MAXSIZE" ] && { rm -f "$_go" 2>/dev/null; return 1; }
	fi
	[ -s "$_go" ]
}

# sub_fetch <url> <файл> [доп. опции curl] — скачать тело подписки в файл. Возврат 0 = непустое тело.
# Доп. опции нужны НЕ подписке, а второму потребителю — пакетному импорту списка доменов/адресов из
# панели: там `-f` ОБЯЗАТЕЛЕН. Для подписки тело ошибки осмысленно (её показывают человеку словами
# провайдера), а для списка страница 404 — это «список», и её текст молча превращается в правила
# (замер: из типовой строки ошибки парсер достаёт ДВА «домена»). Один загрузчик, разная политика
# у вызывающего — вместо второй копии закачки.
# Тело качаем В ФАЙЛ, а не в переменную: часть панелей (durev) отдаёт gzip БЕЗУСЛОВНО, а
# NUL-байты обрезали бы shell-переменную. `od` в busybox НЕТ ⇒ магию байтов не читаем, а
# ПРОБУЕМ разжать (удалось + непусто ⇒ был gzip).
#
# ДВЕ ПОПЫТКИ, и это не перестраховка (замер на живом BE7000 29.07.2026): хост подписки часто
# сам лежит в `iplist_set` (opencck) ⇒ router-локальный curl метится в mangle OUTPUT и уходит
# ВНУТРЬ ТУННЕЛЯ, а VPS этот хост не отдаёт — `http=000` при живой подписке. Тот же корень, что
# у пинга серверов подписки. Порядок попыток осознан: сперва как есть (у кого подписка ЗАБЛОКИРОВАНА
# провайдером, её достаёт как раз туннель), затем принудительно через WAN (`--interface` = SO_BINDTODEVICE,
# мимо fwmark-роутинга).
sub_fetch() {
	_u="$1"; _o="$2"
	[ -n "$_u" ] && [ -n "$_o" ] || return 1
	shift 2
	rm -f "$_o" "$_o.gz" 2>/dev/null
	SUB_FETCH_VIA=""
	sub_get_once "$_u" "$_o" "$@"
	if [ ! -s "$_o" ]; then
		_wan=$(ip route get 8.8.8.8 2>/dev/null | sed -n 's/.* dev \([a-z0-9._-]*\).*/\1/p' | head -1)
		if [ -n "$_wan" ]; then
			sub_get_once "$_u" "$_o" "$@" --interface "$_wan"
			[ -s "$_o" ] && SUB_FETCH_VIA="$_wan"
		fi
	fi
	[ -s "$_o" ] || { rm -f "$_o" 2>/dev/null; return 1; }
	if gunzip -c "$_o" 2>/dev/null | head -c "$SUB_MAXSIZE" > "$_o.gz" && [ -s "$_o.gz" ]; then
		mv "$_o.gz" "$_o"
	else
		rm -f "$_o.gz" 2>/dev/null
	fi
	[ -s "$_o" ]
}

# sub_tags — все теги реестра (по одному в строке).
sub_tags() { [ -f "$SUBS_STATE/.subs" ] && cut -d"$SUBS_TAB" -f1 "$SUBS_STATE/.subs" 2>/dev/null; }
# sub_url_of <tag> / sub_label_of <tag> — поля реестра (пусто = подписки нет).
sub_url_of()   { [ -f "$SUBS_STATE/.subs" ] && grep "^$1$SUBS_TAB" "$SUBS_STATE/.subs" 2>/dev/null | head -1 | cut -d"$SUBS_TAB" -f2; }
sub_label_of() { [ -f "$SUBS_STATE/.subs" ] && grep "^$1$SUBS_TAB" "$SUBS_STATE/.subs" 2>/dev/null | head -1 | cut -d"$SUBS_TAB" -f3-; }

# sub_owner_tag <имя-конфига> — ЧЬЯ это подписка. Теги бывают префиксами друг друга
# («liberty» ⊂ «liberty-vpn»), а «-» встречается и ВНУТРИ тега ⇒ голый префикс `sub-<tag>-`
# ловит чужие файлы. Владелец = ДЛИННЕЙШИЙ подходящий тег среди всех тегов реестра
# (зеркало ownerTag() в panel.js и del_sub_configs в cgi-bin/action).
sub_owner_tag() {
	_b="$1"; _own=""; _ol=-1
	for _g in $(sub_tags); do
		case "$_b" in sub-"$_g"-*) _gl=${#_g}; [ "$_gl" -gt "$_ol" ] && { _own="$_g"; _ol=$_gl; } ;; esac
	done
	printf '%s' "$_own"
}

# sub_names_keep_other <tag> [файл] — строки `.sub-names`, владелец которых НЕ <tag> (stdout).
# Голый `grep -v "^sub-<tag>-"` здесь ошибочен ровно по причине sub_owner_tag, и цена ошибки
# выше, чем у конфигов: `.sub-names` — КАРТА ИДЕНТИЧНОСТИ, по ней сервер находит СВОЙ файл.
# Потеряв строку, следующий прогон заводит серверу НОВЫЙ файл, а старый (если он активный —
# его prune_stale намеренно не трогает) остаётся сиротой и не обновляется больше никогда.
# Замерено на живом роутере: теги «liberty» и «liberty-vpn», активный `sub-liberty-vpn-12`
# без строки имени. Тег передаём явно — в remove_sub его в реестре уже нет.
# Строки с ЧУЖИМ/неопознанным владельцем сохраняем: чистим только своё.
sub_names_keep_other() {
	_kt="$1"; _nf="${2:-$SUBS_STATE/.sub-names}"
	[ -f "$_nf" ] || return 0
	_tl=$(sub_tags 2>/dev/null | tr '\n' ' ')
	case " $_tl " in *" $_kt "*) : ;; *) _tl="$_tl $_kt" ;; esac
	# read БЕЗ хвостового перевода строки теряет последнюю запись (busybox, замерено) ⇒ `|| [ -n ]`.
	while IFS= read -r _ln || [ -n "$_ln" ]; do
		[ -n "$_ln" ] || continue
		_nb=${_ln%%"$SUBS_TAB"*}; _own=""; _ol=-1
		for _g in $_tl; do
			case "$_nb" in sub-"$_g"-*) _gl=${#_g}; [ "$_gl" -gt "$_ol" ] && { _own="$_g"; _ol=$_gl; } ;; esac
		done
		[ "$_own" = "$_kt" ] && continue
		printf '%s\n' "$_ln"
	done < "$_nf"
	return 0
}
