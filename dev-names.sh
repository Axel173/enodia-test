#!/bin/sh
# dev-names.sh — СВОИ ИМЕНА УСТРОЙСТВАМ («Алиса» вместо 3C:0B:4F:59:E7:D0).
#
# ЗАЧЕМ (Роман, 04.09.2026). Имя в списке устройств приезжает РОВНО из одного места — из DHCP-запроса клиента (поле hostname
# аренды). Его нет и не будет у трёх видов устройств: клиент, который имени не сообщает (Яндекс Алиса, часть IoT), клиент со
# статикой на самом себе (DHCP-запроса нет вовсе — devices-static-no-lease) и строка без аренды (правило на адресе). Такое
# устройство висит в панели голым MAC, и человек каждый раз лезет выяснять, что это. Записать его «в хосты» не поможет:
# dns-hosts.sh — это «домен → IP» для резолва, список устройств имён оттуда не берёт.
#
# ЭТО МЕТКА ДЛЯ ПАНЕЛИ, а не имя в сети: в DHCP, DNS и родную морду Xiaomi она не уходит (там своё имя, в `/etc/xqDb`, чужую
# базу не трогаем). Макет называет это так же: «метка для панели дёшево, настоящее имя в сети — только со строгой проверкой».
#
# КЛЮЧ — MAC, А НЕ IP. Адрес лишь ОДОЛЖЕН на срок аренды (lease-lib.sh, ip-not-identity-lease-drift): метка на адресе уехала бы
# вместе с ним на чужое устройство. У строки без MAC (офлайн-правило, которому владельца не найти) метки нет — нечем её
# привязать. Граница честности та же, что у закрепления адреса: телефон с privacy-MAC придёт под другим MAC — и метка к нему не
# относится (лечится в настройках Wi-Fi телефона, не у нас).
#
# ГДЕ ЖИВЁТ: `$ENODIA_STATE/.dev-names` — TSV `mac⇥имя`, единственная истина; переживает ребут и обновление, входит в бэкап
# (cgi-bin/backup, импорт кладёт файл целиком, мимо лока). ЧИТАТЕЛИ — `cgi-bin/data` (emit_devices, поле `alias`) и
# `wifi-stats.sh` (срез станций) — ходят ТОЛЬКО через `list`, один запуск на весь список (форк на каждое из сотни устройств
# стоил бы дороже самого списка). Разбор файла поэтому ОДИН: руками правленый персист (CRLF с Windows, таб в имени, MAC
# прописными, повтор строки, файл из чужого бэкапа) приходит к читателям уже чистым, и одно устройство не зовут на двух экранах
# по-разному, а управляющий байт не рвёт JSON всего списка (ревью 27.09.2026: CR из файла ронял «Устройства» целиком).
#
# Команды:
#   dev-names.sh set <mac> <имя>  — задать метку (пустое имя = снять)
#   dev-names.sh del <mac>        — снять метку
#   dev-names.sh get <mac>        — метка или пусто
#   dev-names.sh list             — все метки, `mac⇥имя`: MAC строчными и настоящий, имя без управляющих байтов, кавычки и
#                                   обратной косой (в JSON оно уходит как есть), на MAC — первая строка
ENODIA_DIR=${ENODIA_DIR:-/data/usr/app/enodia}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
STORE="$ENODIA_STATE/.dev-names"
TAB=$(printf '\t')
NL='
'
# Разбор MAC — у владельца ответа «кто это устройство» (lease-lib.sh). Шимы — на payload без библиотеки: те же выражения.
if [ -f "$ENODIA_DIR/lease-lib.sh" ]; then . "$ENODIA_DIR/lease-lib.sh"; fi
command -v mac_norm >/dev/null 2>&1 || mac_norm() { printf '%s' "$1" | tr 'A-Z' 'a-z' | tr -d ' \t\r\n'; }
command -v mac_ok   >/dev/null 2>&1 || mac_ok()   { printf '%s' "$1" | grep -qE '^[0-9a-f]{2}(:[0-9a-f]{2}){5}$'; }
# «Жив ли процесс И наш ли он» — у daemon-lib.sh (NUL в cmdline — в пробелы: busybox grep читает файл до первого NUL, а у
# держателя из CGI первым словом стоит `sh`, и имя скрипта он бы не увидел). Шим — та же строка.
if [ -f "$ENODIA_DIR/daemon-lib.sh" ]; then . "$ENODIA_DIR/daemon-lib.sh"; fi
command -v pid_runs >/dev/null 2>&1 || pid_runs() { [ -n "$1" ] && [ -r "/proc/$1/cmdline" ] && tr '\000' ' ' < "/proc/$1/cmdline" 2>/dev/null | grep -qE "$2"; }

# Потолок имени — БАЙТАМИ и ОТКАЗОМ, а не обрезкой: `cut -c` в busybox режет байты, и обрезанная кириллица дала бы обрывок буквы
# в JSON всего списка. 96 байт — 48 русских букв или 96 латинских: на подпись в строке хватает с запасом.
NAME_MAX=96
LOCK=/tmp/.enodia-dev-names.lock

# Писателей несколько (две вкладки панели), а запись — read-modify-write целого файла ⇒ лок-КАТАЛОГ (mkdir атомарен) с ПИДом.
# Протух — если держателя нет: пид мёртв ИЛИ уже чужой (пиды переиспользуются, а лок в /tmp живёт до ребута), либо пида нет
# дольше, чем живой держатель пишет его (миг после mkdir): держатель умер между mkdir и echo. Судим по /proc, а не по возрасту
# (часы роутера прыгают, C24). Не взять за 5 с — отказ словами, а не тихая потеря чужой правки.
lock_take() {
    _li=0
    while ! mkdir "$LOCK" 2>/dev/null; do
        _li=$((_li+1)); [ "$_li" -gt 5 ] && return 1
        _lp=$(cat "$LOCK/pid" 2>/dev/null | tr -d ' \r\n')
        if [ -n "$_lp" ]; then
            pid_runs "$_lp" 'dev-names' || { rm -rf "$LOCK" 2>/dev/null; continue; }
        elif [ "$_li" -ge 3 ]; then
            rm -rf "$LOCK" 2>/dev/null; continue
        fi
        sleep 1
    done
    echo $$ > "$LOCK/pid" 2>/dev/null
    return 0
}
lock_drop() { rm -rf "$LOCK" 2>/dev/null; }

# Имя человека → безопасная строка персиста: таб и переводы строки — в пробел (это разделители TSV, но человеку — пробел),
# прочие управляющие байты, кавычка и обратная косая — вон (JSON), пробелы по краям — вон, подряд идущие — в один.
san_name() { printf '%s' "$1" | tr '\t\r\n' '   ' | tr -d '\000-\037"\\' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//; s/[[:space:]][[:space:]]*/ /g'; }

# ЕДИНСТВЕННЫЙ разбор персиста (см. шапку): управляющие байты, кроме таба и перевода строки, кавычку и косую — вон ещё до awk;
# MAC — строчными и только настоящий; хвост полей (таб в имени) — пробелом; пустое имя — не метка; на MAC — первая строка.
cmd_list() {
    [ -f "$STORE" ] || return 0
    tr -d '\000-\010\013-\037"\\' < "$STORE" 2>/dev/null | awk -F"$TAB" '
    {
        m = tolower($1); gsub(/ /, "", m)
        if (m !~ /^[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]:[0-9a-f][0-9a-f]$/) next
        if (m in seen) next
        n = $2; for (i = 3; i <= NF; i++) n = n " " $i
        gsub(/  +/, " ", n); sub(/^ /, "", n); sub(/ $/, "", n)
        if (n == "") next
        seen[m] = 1; print m "\t" n
    }'
}

cmd_get() {
    _gm=$(mac_norm "$1"); mac_ok "$_gm" || return 1
    cmd_list | awk -F"$TAB" -v m="$_gm" '$1==m { print $2; exit }'
}

# Переписать строку MAC (или снять её, если имени нет). Новое содержимое собираем В ПАМЯТИ из разобранного персиста и
# проверяем записанное ЧТЕНИЕМ: busybox awk и `printf >>` на полном разделе (20-МБ /data, «No space» бывает и от UBIFS GC)
# возвращают 0, и прежняя форма «временный файл пуст ⇒ снять персист» превращала сбой записи в УДАЛЕНИЕ всех имён, а
# оборванную запись — в подмену персиста обрывком (ревью 27.09.2026). Пустой персист теперь — только настоящий итог правки.
store_write() {   # $1 = mac, $2 = имя (пусто = снять)
    _wb=$(cmd_list | awk -F"$TAB" -v m="$1" '$1!=m')
    [ -n "$2" ] && _wb="${_wb:+$_wb$NL}$1$TAB$2"
    if [ -z "$_wb" ]; then rm -f "$STORE"; return $?; fi
    _wt="$STORE.$$"
    if printf '%s\n' "$_wb" > "$_wt" 2>/dev/null && [ "$(cat "$_wt" 2>/dev/null)" = "$_wb" ]; then
        mv "$_wt" "$STORE" && return 0
    fi
    rm -f "$_wt"; return 1
}

cmd_set() {
    _sm=$(mac_norm "$1")
    mac_ok "$_sm" || { echo "[dev-names] у устройства нет MAC — метку привязать не к чему"; return 1; }
    _sn=$(san_name "$2")
    # Имя из одних запрещённых знаков («"», «\») — НЕ «снять»: человек что-то написал и ждёт метку, а молча стёртая прежняя
    # метка с тостом «имя снято» читается как чужая ошибка. Снимает только пустое поле (или одни пробелы).
    if [ -z "$_sn" ] && [ -n "$(printf '%s' "$2" | tr -d ' \t\r\n')" ]; then
        echo "[dev-names] в имени нет ни одного допустимого знака — кавычки и обратная косая не сохраняются"; return 1
    fi
    if [ "$(printf '%s' "$_sn" | wc -c)" -gt "$NAME_MAX" ]; then
        echo "[dev-names] имя слишком длинное: до 48 букв кириллицей или 96 латиницей — сократите"; return 1
    fi
    lock_take || { echo "[dev-names] имена сейчас правит другая операция — повторите"; return 1; }
    store_write "$_sm" "$_sn"; _sr=$?
    lock_drop
    [ "$_sr" = 0 ] || { echo "[dev-names] не удалось записать имя (место на разделе?)"; return 1; }
    # MAC в ответе — прописными, как его показывает вся панель (персист хранит строчными).
    _su=$(printf '%s' "$_sm" | tr 'a-z' 'A-Z')
    if [ -n "$_sn" ]; then echo "[dev-names] устройство $_su: имя «$_sn»"; else echo "[dev-names] устройство $_su: своё имя снято"; fi
}

case "$1" in
    set)  cmd_set "$2" "$3" ;;
    del)  cmd_set "$2" "" ;;
    get)  cmd_get "$2" ;;
    list) cmd_list; exit 0 ;;
    *) echo "usage: $0 set <mac> <имя> | del <mac> | get <mac> | list"; exit 2 ;;
esac
