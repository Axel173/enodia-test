#!/bin/sh
# ipt-lib.sh — ЕДИНСТВЕННЫЙ владелец ожидания xtables-лока. Сорсится (`. ipt-lib.sh`), сам ничего
# не печатает и не меняет: подменяет команды `iptables`/`ip6tables` одноимёнными функциями, которые
# добавляют `-w <секунды>`. Все 256 мест, где проект ставит правила, остаются как были (счёт — C36).
#
# ЗАЧЕМ. iptables держит общий файловый лок на время команды. Если лок занят, а `-w` не задан,
# утилита НЕ ЖДЁТ: печатает «another app is currently holding the xtables lock» и выходит с
# ошибкой. Правило при этом не встаёт. Половина наших вызовов глушит stderr в /dev/null ⇒ отказ
# не виден ВООБЩЕ: панель зелёная, правило есть в персисте, а в ядре его нет. Ровно этот класс
# отказа детектит rule-heal сторожа — то есть мы за него уже платили, только с другого конца.
#
# КТО КОНКУРИРУЕТ. Минуту делят чужие писатели стока (sp_check.sh */5, mobile_accel.sh */3,
# startscene_crontab.lua ежеминутно, mipctld, upnp) и наши (heal.sh */1, watchdog.sh */2,
# traffic-acct */5). На минуте, кратной 30, писателей шесть — а apply-bypass в этот момент кладёт
# до 60 правил подряд: попасть в занятый лок тут не гипотеза, а вопрос времени.
#
# ПОЧЕМУ ПОДМЕНА КОМАНДЫ, А НЕ ОБЁРТКА `ipt_a`/`ipt_d`. Обёртка требует переписать все 256 мест с
# разными редиректами и разбором кодов — механический риск больше пользы. Хуже другое: следующий
# вызов, написанный руками (а их пишут постоянно), обёртку МОЛЧА обойдёт. Функция с именем утилиты
# чинит и уже написанное, и то, что напишут завтра, — и остаётся ровно одним владельцем.
#
# ГЛАВНАЯ ГРАБЛЯ: `-w` — РАЗНОЕ в разных версиях. Секунды у `-w` появились в iptables 1.6.0; в
# 1.4.x `--wait` аргумента НЕ БЕРЁТ, и лишняя «5» падает как «unknown arguments found on
# commandline» с кодом 2 — то есть слепое `-w 5` на старой сборке уронило бы КАЖДОЕ правило
# проекта разом (а роутеров у нас три поколения). Поэтому поддержку СПРАШИВАЕМ у самой утилиты
# (read-only проба), ответ кэшируем в /tmp на загрузку, а «не умеет» = прежний путь БАЙТ-В-БАЙТ.
# Голый `-w` без секунд (ждать ВЕЧНО) сознательно не используем: заклиненный на локе heal или
# сторож в cron хуже не вставшего правила — добудиться его нечем, а cron будет плодить копии.
#
# ЗАЩИТА ОТ РЕКУРСИИ. Функция зовёт бинарь по АБСОЛЮТНОМУ пути, найденному ДО её определения. Не
# нашли бинарь в стандартных каталогах — функцию не определяем вовсе, и `iptables` ищется по PATH
# ровно как раньше: fork-бомба на роутере дороже любой пользы от ожидания лока.

IPT_WAIT_SEC=${IPT_WAIT_SEC:-5}      # сколько ждём лок; 5 с — как в ipt_check_t сторожа
IPT_WAIT_CACHE=/tmp/.ipt-wait        # вердикт пробы (RAM: гибнет с ребутом — как и версия утилиты)
IP6T_WAIT_CACHE=/tmp/.ip6t-wait

# ПОТОЛОК ДВЕ ЦИФРЫ — и здесь, и при чтении кэша ниже. «Ждать вечно» запрещено шапкой, но запрет
# обходится молча: достаточно, чтобы в переменной или в /tmp-кэше оказалось «99999999», и каждый
# вызов iptables начнёт ждать лок почти бесконечно — правил нет, лога нет, cron копит процессы.
# Поэтому форму проверяем ОБА раза: доверять собственному файлу в /tmp тоже нельзя.
case "$IPT_WAIT_SEC" in [1-9]|[1-9][0-9]) ;; *) IPT_WAIT_SEC=5 ;; esac

# Абсолютные пути ищем ДО определения функций (см. «защита от рекурсии»). Форма `if`, а не
# `[ … ] && …`: под set -e страж последней командой цикла вернул бы 1 и уронил ВЕСЬ source.
: "${IPT_BIN:=}"
: "${IP6T_BIN:=}"
# Унаследованное из окружения значение (форма `:=` берёт что угодно) проверяем на исполнимость:
# иначе обёртка определится поверх НЕСУЩЕСТВУЮЩЕГО пути и роутер молча останется без правил —
# ровно тот отказ, от которого защищает поиск бинаря заранее. Не прошло — чистим и ищем сами.
if [ -n "$IPT_BIN" ]  && [ ! -x "$IPT_BIN" ];  then IPT_BIN=;  fi
if [ -n "$IP6T_BIN" ] && [ ! -x "$IP6T_BIN" ]; then IP6T_BIN=; fi
for _iptdir in /usr/sbin /sbin /usr/bin /bin; do
	if [ -z "$IPT_BIN" ]  && [ -x "$_iptdir/iptables" ];  then IPT_BIN="$_iptdir/iptables";   fi
	if [ -z "$IP6T_BIN" ] && [ -x "$_iptdir/ip6tables" ]; then IP6T_BIN="$_iptdir/ip6tables"; fi
done

# Умеет ли ЭТА сборка `-w <секунды>`: печатает число или `no`. Проба read-only (`-S INPUT` в
# filter) — она ничего не меняет и есть на любом роутере.
# ЧЕСТНАЯ ГРАНИЦА: провал пробы бывает двух родов, и различить их обязательно. Если БЕЗ `-w` та же
# команда проходит — сборка старая, вердикт `no` кэшируем. Если не проходит и без `-w` (нет
# модулей, лок держат дольше пробы, утилиту подменили) — это не ответ про `-w`, и кэш мы НЕ пишем:
# следующий процесс спросит заново. Иначе одна неудачная секунда на буте отключала бы ожидание
# лока до самого ребута.
_ipt_wait_probe() {                  # $1 — бинарь, $2 — файл кэша
	_iptw=
	if [ -r "$2" ]; then read -r _iptw < "$2" 2>/dev/null || _iptw=; fi
	# Форма ЖЁСТКАЯ (`no` или 1–2 цифры), а не «начинается с цифры»: кэш лежит в общем /tmp, и
	# значение оттуда уходит прямо в `-w`. См. потолок в шапке.
	case "$_iptw" in
		no|[1-9]|[1-9][0-9]) printf '%s' "$_iptw"; return 0 ;;
	esac
	if "$1" -w "$IPT_WAIT_SEC" -t filter -S INPUT >/dev/null 2>&1; then
		echo "$IPT_WAIT_SEC" > "$2" 2>/dev/null || true
		printf '%s' "$IPT_WAIT_SEC"
		return 0
	fi
	if "$1" -t filter -S INPUT >/dev/null 2>&1; then
		echo no > "$2" 2>/dev/null || true
	fi
	printf 'no'
	return 0
}

# Разбор вердикта в опцию: пусто = зовём как раньше. Считаем ОДИН раз на процесс.
: "${IPT_WOPT:=}"
: "${IPT_WREADY:=}"
: "${IP6T_WOPT:=}"
: "${IP6T_WREADY:=}"

if [ -n "$IPT_BIN" ]; then
iptables() {
	if [ -z "$IPT_WREADY" ]; then
		IPT_WREADY=1
		_iptv=$(_ipt_wait_probe "$IPT_BIN" "$IPT_WAIT_CACHE")
		case "$_iptv" in [1-9]*) IPT_WOPT="-w $_iptv" ;; *) IPT_WOPT= ;; esac
	fi
	if [ -z "$IPT_WOPT" ]; then "$IPT_BIN" "$@"; return $?; fi
	# shellcheck disable=SC2086
	"$IPT_BIN" $IPT_WOPT "$@"
	_iptrc=$?
	# Код 2 = «неверные параметры»: команда разобрана не была, значит НЕ применилась и повтор
	# безопасен (той же логикой живёт ipt_check_t сторожа). Страховка на сборку, где `-w <сек>`
	# проходит у чтения, но не у записи; на нормальной сборке ветка мертва.
	if [ "$_iptrc" = 2 ]; then "$IPT_BIN" "$@"; _iptrc=$?; fi
	return "$_iptrc"
}
fi

if [ -n "$IP6T_BIN" ]; then
ip6tables() {
	if [ -z "$IP6T_WREADY" ]; then
		IP6T_WREADY=1
		_iptv=$(_ipt_wait_probe "$IP6T_BIN" "$IP6T_WAIT_CACHE")
		case "$_iptv" in [1-9]*) IP6T_WOPT="-w $_iptv" ;; *) IP6T_WOPT= ;; esac
	fi
	if [ -z "$IP6T_WOPT" ]; then "$IP6T_BIN" "$@"; return $?; fi
	# shellcheck disable=SC2086
	"$IP6T_BIN" $IP6T_WOPT "$@"
	_iptrc=$?
	if [ "$_iptrc" = 2 ]; then "$IP6T_BIN" "$@"; _iptrc=$?; fi
	return "$_iptrc"
}
fi

# ipt_wait_mode — ЧЕМ мы ждём лок на этом роутере: число секунд или `no`. Нужен диагностике
# (dump.sh: «правило не встало» и «правило не поставили» выглядят одинаково), а не тем, кто
# ставит правила: у них ответ один — best-effort.
ipt_wait_mode() {
	if [ -z "$IPT_BIN" ]; then echo no; return 0; fi
	# Пробу зовём В ПОДОБОЛОЧКЕ: в busybox sh нет `local`, и её внутренняя `_iptw` иначе затирала бы
	# одноимённую переменную ВЫЗЫВАЮЩЕГО (в проекте на этом уже горели — цикл `while read -r _id`
	# внутри srv_rules ронял `_id` у вызвавшей команды). Диагностику зовут раз, лишний форк не жалко.
	( _ipt_wait_probe "$IPT_BIN" "$IPT_WAIT_CACHE" )
	echo
}
