#!/bin/sh
# ip-lib.sh — общий примитив «внешний IPv4» (что видит удалённая сторона на заданном пути).
# ЕДИНЫЙ источник истины вместо россыпи разнобойных `curl … https://api.ipify.org` по проекту
# (cgi-bin/ip, status.sh, watchdog, диагностики). Только читает сеть, ничего не меняет.
#
# ГЛАВНАЯ ГРАБЛЯ (ядро 4.4 — AX3600/BE3600, поймано на железе 2026-07-16): hostname-проба
# `curl https://api.ipify.org` на ядре 4.4 молча возвращала ПУСТО — egress в шапке панели не
# отображался, status.sh писал «api.ipify.org не ответил», — при том что само имя РЕЗОЛВИЛОСЬ
# (nslookup ок) и туннель работал. IP-ЛИТЕРАЛ Cloudflare trace (`https://1.1.1.1/cdn-cgi/trace`,
# строка `ip=…`) НЕ зависит от DNS и отдаёт ответ на ОБОИХ ядрах (5.4 и 4.4) за ~0 с. Это тот же
# принцип «IP-литерал вместо хрупкого busybox-DNS», что и DoH в fetch_url движка списков.
# `-k`: на старом OpenSSL (1.0.2q, ядро 4.4) сертификат к 1.1.1.1 по IP не всегда валиден; из
# ответа берём ТОЛЬКО строку IP (не секрет), поэтому проверку сертификата тут можно опустить.

IP_PROBE_TRACE="https://1.1.1.1/cdn-cgi/trace"      # DNS-free дефолт; Cloudflare ∈ iplist_set
# ВТОРОЙ узел того же trace — ДОПОЛНИТЕЛЬНАЯ попытка, её просят четвёртым аргументом (tries=2).
# Нужна потому, что промах ОДНОЙ попытки бывает и на живом канале: замерено на AX3600 17.08.2026 —
# 3 пустых ответа из 10 с лимитом 7 с, ровно в минуты, когда dnsmasq грузил 300 тыс. строк гео
# (load 2.2); через полчаса на том же роутере 12/12 успехов за ~0 с. Бюджет съедает не сеть, а
# ЗАНЯТЫЙ роутер, и «пусто» тогда значит «не успели», а не «пути нет».
# ПОЧЕМУ НЕ ВСЕМ И НЕ ВСЕГДА — две границы, обе стоят дорого:
#   * `cmd_health` у xray/hy2 судит по ЭТОЙ пробе и зовётся в НЕОГРАНИЧЕННОМ цикле перебора
#     конфигов (у тестера их 102). Лишняя попытка на каждом мёртвом кандидате удлинила бы аварийный
#     failover на минуты — там дешевле промахнуться и дать сторожу перепроверить через 2 минуты;
#   * 1.1.1.1 ∈ iplist_set, а 1.0.0.1 — НЕТ (замерено) ⇒ у пробы БЕЗ bind'а смена адреса меняет и
#     ПУТЬ (первый уходит в туннель, второй напрямую) ⇒ ответ был бы про другой путь. Поэтому вторая
#     попытка возможна только при прибитом пути: --interface/--socks5.
# Итог: tries=1 по умолчанию (для всех прежних вызовов поведение БАЙТ-В-БАЙТ), tries=2 просит тот,
# чьё число читает человек и кто закрыт кэшем — панельный cgi-bin/ip.
IP_PROBE_TRACE2="https://1.0.0.1/cdn-cgi/trace"
IP_PROBE_URL="${IP_PROBE_URL:-$IP_PROBE_TRACE}"      # можно переопределить окружением/аргументом

# _ip_from_body <body> — выцепить IPv4 из ответа пробы. Сперва trace-строка `ip=1.2.3.4`; иначе
# тело целиком = «голый» IP (совместимость с api.ipify.org и подобными). Печатает IP или ничего.
# ВАЖНО: тело передаём АРГУМЕНТОМ, а не пайпом — иначе первая же стадия (`sed`) съест весь stdin,
# и ветка «голый IP» получит пусто (грабля busybox-пайпа, встречалась в проекте).
_ip_from_body() {
    _e=$(printf '%s\n' "$1" | sed -n 's/^ip=\([0-9.]*\).*/\1/p' | head -1)
    [ -n "$_e" ] || _e=$(printf '%s' "$1" | tr -d ' \t\r\n')
    printf '%s' "$_e" | grep -qE '^([0-9]{1,3}\.){3}[0-9]{1,3}$' && printf '%s' "$_e"
}

# probe_ext_ip <curl-bind-args> [timeout] [url] — IPv4, увиденный снаружи через заданный путь.
#   bind-args: ""                              — прямой выход роутера (как есть по маршрутам);
#              "--interface awg0"              — egress через awg-туннель;
#              "--socks5-hostname 127.0.0.1:10808" — egress через альт (xray/hy2/byedpi);
#              "--interface eth0"              — реальный WAN В ОБХОД собственного туннеля (bind к WAN-iface).
#   url: по умолчанию IP_PROBE_URL. Если задан кастомный (напр. сохранённый api.ipify.org) и он
#        промолчал — добиваем DNS-free trace'ом (фолбэк ниже). На успехе primary фолбэк не выполняется.
# Пусто на выходе = путь не ответил. Один сетевой вызов на успехе (цена фолбэка — только при пустом primary).
#   tries: 1 (умолчание) — как было; 2 — при пустом ответе добить ВТОРЫМ узлом trace (только с
#          bind'ом/socks, см. разбор у IP_PROBE_TRACE2). Цена — ещё один timeout, и только на промахе.
# Порядок попыток: кастомный URL (если задан) → trace 1.1.1.1 → [tries=2] trace 1.0.0.1.
probe_ext_ip() {
    _pa="$1"; _pt="${2:-7}"; _url="${3:-$IP_PROBE_URL}"; _pn="${4:-1}"
    [ -n "$_url" ] || _url="$IP_PROBE_TRACE"
    _body=$(curl -s -k $_pa --max-time "$_pt" "$_url" 2>/dev/null)   # $_pa НАМЕРЕННО без кавычек — сплит на аргументы
    _ip=$(_ip_from_body "$_body")
    [ -n "$_ip" ] && { printf '%s' "$_ip"; return 0; }
    if [ "$_url" != "$IP_PROBE_TRACE" ]; then                         # primary был кастомным — добиваем trace'ом
        _body=$(curl -s -k $_pa --max-time "$_pt" "$IP_PROBE_TRACE" 2>/dev/null)
        _ip=$(_ip_from_body "$_body")
        [ -n "$_ip" ] && { printf '%s' "$_ip"; return 0; }
    fi
    # Второй узел — по запросу И только с bind'ом/socks: у пробы «как решат маршруты» он измерил бы
    # ДРУГОЙ путь (1.0.0.1 вне iplist_set), а у health-цикла отнял бы минуты на переборе конфигов.
    if [ "$_pn" -gt 1 ] 2>/dev/null; then
        case "$_pa" in
            *--interface*|*--socks5*)
                _body=$(curl -s -k $_pa --max-time "$_pt" "$IP_PROBE_TRACE2" 2>/dev/null)
                _ip_from_body "$_body" ;;
        esac
    fi
    # КОД ВОЗВРАТА ВСЕГДА 0: контракт функции — «путь не ответил» это ПУСТАЯ СТРОКА, а не ошибка.
    # Без этой строки последней командой оставался бы grep внутри _ip_from_body, и rc зависел бы от
    # того, какой ветвью вышли (прежний код на дефолтном URL выходил через свой `return 0` ДО
    # фолбэка, а на кастомном — отдавал rc grep'а: разнобой на пустом ответе).
    # ЧЕСТНАЯ ГРАНИЦА (замерено, а не выведено): под `set -e` эта функция всё равно роняет скрипт, но
    # РАНЬШЕ — на `_body=$(curl …)`, потому что curl на таймауте выходит с 28. Сегодня из-под `set -e`
    # её не зовёт никто (только install.sh и build-byedpi.sh с `set -e`, и они её не зовут);
    # кто соберётся — обязан гасить сам (`|| true`), одним `return 0` тут не закрыться.
    return 0
}

# is_private_ip <ipv4> — 0, если адрес приватный/CGNAT/link-local/loopback (т.е. НЕ настоящий
# публичный WAN). Нужно, чтобы понять, стоит ли ради «реального WAN» делать сетевую пробу: если
# адрес WAN-интерфейса уже публичный (обычный роутер на границе), проба избыточна — берём его как есть.
# Диапазоны: 10/8, 172.16/12, 192.168/16, 100.64/10 (CGNAT), 169.254/16 (link-local), 127/8.
is_private_ip() {
    case "$1" in
        10.*|127.*|169.254.*|192.168.*) return 0 ;;
        172.1[6-9].*|172.2[0-9].*|172.3[0-1].*) return 0 ;;
        100.6[4-9].*|100.[7-9][0-9].*|100.1[0-1][0-9].*|100.12[0-7].*) return 0 ;;
    esac
    return 1
}
