#!/bin/sh
# transport.sh — ОРКЕСТРАТОР транспортов VPN (тонкий слой НАД плагинами transport-*).
#
# ИДЕЯ (чистая плагинная модель, чтобы добавлять транспорты дёшево — xray, hysteria2, …):
#   * Плагин транспорта (transport-awg.sh / xray-transport.sh / …) несёт ОДИН контракт
#     up|down|health|failover|status и отвечает ТОЛЬКО за СВОЮ несущую:
#       up   — взять default в table 1000 (+ FORWARD/MASQUERADE/DNS своей схемы);
#       down — ЧИСТО отпустить несущую -> fail-open в прямой (НЕ решает, что поднять следом!).
#   * Что поднять следующим (cross awg<->xray<->…) решает ЭТОТ оркестратор, а НЕ плагин.
#   * Маркировка (mark-core: ipset->MARK + ip rule fwmark->table) — ОБЩАЯ, держим отдельно.
#
# РЕЕСТР транспортов — $REGISTRY (порядок = приоритет для cross-перебора). Добавить
# hysteria2 = одна строка в $REGISTRY + ветки в plugin_for()/transport_ready(). Всё
# остальное (меню, heal, watchdog) пойдёт через этот оркестратор без правок.
#
# БЕЗОПАСНОСТЬ: всё на ip rule fwmark -> table 1000. Любой down/смерть несущей = fail-open
# в main (прямой), не блэкхол. Оркестратор НЕ трогает awg0-интерфейс при switch (тёплый
# резерв сохраняется — down плагина снимает лишь маршрутизацию, не интерфейс).
#
# Команды:
#   transport.sh active            — текущий активный транспорт (.transport)
#   transport.sh configured        — НАСТРОЕН ли транспорт вообще: 0 да · 1 НЕТ ни одного
#                                    (установка «только панель») · 2 старая копия скрипта
#   transport.sh names             — ВСЕ известные имена транспортов (SELECTABLE), без проверки
#                                    готовности: единственный ответ на «а такой транспорт бывает?»
#   transport.sh ready [<name>]    — может ли <name> (деф. active) ПОДНЯТЬСЯ на этом роутере:
#                                    0 да · 1 НЕТ (нет бинаря/конфига/ядро не умеет) · 2 старая копия
#   transport.sh list              — ГОТОВЫЕ к включению транспорты (бинарь + конфиг + ядро)
#   transport.sh installed [<name>]— у кого на месте БИНАРИ (без конфига и без «умеет ли ядро»):
#                                    разница с list и есть причина «стоит, а включить нельзя».
#                                    С именем — про ОДИН транспорт и КОДОМ: 0 да · 1 нет · 2 старая копия
#   transport.sh next <name>       — следующий ГОТОВЫЙ транспорт != <name> (для cross)
#   transport.sh up [<name>]       — поднять несущую <name> (деф. active) поверх mark-core
#   transport.sh down [<name>]     — отпустить несущую <name> (деф. active) -> fail-open в прямой
#   transport.sh switch <name>     — отпустить текущую несущую, поднять <name>, записать .transport
#   transport.sh health [<name>]   — здоровье несущей (деф. active): 0 здоров / 1 нет
#   transport.sh failover [<name>] — перебор резервов ВНУТРИ транспорта (деф. active)
#   transport.sh slots-up          — поднять несущие ВСЕХ включённых слотов (boot/heal)
#   transport.sh slot-up <id>      — поднять несущую слота; slot-down <id> — отпустить (→ fallback)
#   transport.sh slot-health <id>  — жив ли доп-выход (0 жив / 1 просел / 2 плагин не умеет)
#   transport.sh slot-list         — транспорты, готовые нести доп-выход (см. slot_ready)

ENODIA_DIR=/data/usr/app/enodia
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
TRANSPORT_FLAG="$ENODIA_STATE/.transport"
MARK_CORE="$ENODIA_DIR/mark-core.sh"
# Лок «идёт ручная смена несущей» — ТОТ ЖЕ файл, что берёт switch-vpn.sh при смене страны, и на
# который смотрят heal.sh (выходит) и watchdog.sh (выходит). До сих пор его брал только
# switch-vpn, а cmd_switch (панель «включить ByeDPI/Zapret/xray», proto-install, cross сторожа) —
# нет. Окно между `down` старого и `up` нового при этом ничем не защищено: `.transport` ещё
# указывает на СНИМАЕМЫЙ транспорт, и тик сторожа успевает позвать его health/failover, а те
# честно переподнимают несущую (byedpi reup_carrier, xray/hy2 ФАЗА 0) вместе с `default dev xtun`
# в table 1000 — ПОВЕРХ уже поднятой новой. Итог: осиротевшие демоны на socks 10808 и таблица,
# смотрящая в чужую несущую (класс Б4-5). Берём лок на всё переключение.
SWITCH_LOCK=/tmp/enodia-switching.lock
# Где лежит бинарь (store-lib.sh). Оркестратору это нужно для ОБЕИХ проверок готовности:
# «бинаря нет» и «бинарь на выдернутой флешке» обязаны читаться ОДИНАКОВО — как «транспорт не
# готов», после чего работает штатный fail-open. Без накопителя — прежний путь байт-в-байт.
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
command -v bin_path >/dev/null 2>&1 || bin_path() { printf '%s' "$ENODIA_BIN/$1"; }

# Реестр: порядок приоритета и cross-перебора. Порядок = приоритет cross («awg» как
# надёжная база первой). xray и hy2 на флеше взаимоисключающи (см. transport_ready). byedpi
# (локальный DPI-десинк без VPS) — ПОСЛЕДНИЙ в cross: дешёвый fallback, но покрытие частичное
# (ISP-зависимое), потому VPS-транспорты пробуем раньше, byedpi — перед уходом в прямой режим.
REGISTRY="awg xray hy2 byedpi"

# СЕЛЕКТОР (что показывать/переключать вручную) = реестр + zapret. zapret (nfqws-десинк
# направо БЕЗ VPS) — ПСЕВДО-транспорт: он не socks и НЕ участвует в авто-cross/failover (его
# нет в REGISTRY → watchdog никогда не прыгнет в безтуннельный режим сам), но пользователь
# может ВРУЧНУЮ выбрать его как несущую (весь трафик напрямую, заблок-категории пробивает
# nfqws на форварде). В отличие от xray/hy2/byedpi (делят socks 10808 ⇒ АКТИВЕН один за раз,
# хотя лежать на флеше могут рядом) zapret ставится ОРТОГОНАЛЬНО (~0.13 МБ) и работает поверх
# любого набора. Готовность = бинарь nfqws.
SELECTABLE="$REGISTRY zapret"

# ВЕЗЁТ ЛИ ТРАНСПОРТ ТРАФИК ПО МАРКЕ (0 да · 1 нет) — единственный ответ на роутер.
# Спрашивают те, кто рассуждает «снял марку = выключил»: тумблер панели (`vpn-toggle off`) и
# rule-heal сторожа. У zapret марок НЕТ ВООБЩЕ — трафик идёт напрямую, mark-core его сеты
# пропускает, а пробивает их nfqws на форварде ⇒ снятие `ip rule` для него полный no-op:
# тумблер писал «VPN выключён», десинк работал дальше и через 10 с поллинга возвращался в ON
# (тестер, 18.08.2026). Список ЯВНЫЙ, а не "$REGISTRY": сегодня они совпадают, но REGISTRY —
# про ПОРЯДОК cross-перебора, а этот — про способ доставки трафика; совпадение двух смыслов
# не делает их одним. Держать копию у каждого рассуждающего нельзя: шестой транспорт допишут
# в одном месте и забудут в двух.
MARKING="awg xray hy2 byedpi"
cmd_marking() {
    [ -n "$1" ] || return 1
    for _mk in $MARKING; do [ "$_mk" = "$1" ] && return 0; done
    return 1
}

# Имя транспорта -> путь плагина (явная карта: имена файлов исторически разные —
# transport-awg.sh, но xray-transport.sh; сводим тут, без переименований).
#
# ЧУЖОЙ СКРИПТ ЗОВЁМ ТОЛЬКО `sh <путь>`, А ГАРД — ПО НАЛИЧИЮ ФАЙЛА (`-f`), НЕ ПО БИТУ `-x`.
# Бит исполнения нам не принадлежит: chmod на накопителе с exFAT/NTFS молча не делает ничего
# (это уже учтено в gh-update при закачке бинарей), точечный `--push` кладёт файл 644 (поймано
# на железе у clock-lib.sh), а откат из .gh-backup возвращает права такими, какими их сняли.
# Цена ошибки НЕСИММЕТРИЧНА: `[ -x "$p" ] && "$p" up` на слетевшем бите — это ТИХИЙ отказ с
# кодом 0 (несущая не поднята, маркировки нет, а звавший рапортует успех), тогда как через `sh`
# бит не нужен вовсе и работает ЛЮБАЯ копия файла. +x остаётся нужен ровно там, где запускаем НЕ
# мы и гарда быть не может: cron-строки и CGI панели (их исполняет uhttpd). Следит проверка C27.
plugin_for() {
    case "$1" in
        awg)    echo "$ENODIA_DIR/transport-awg.sh" ;;
        xray)   echo "$ENODIA_DIR/xray-transport.sh" ;;
        hy2)    echo "$ENODIA_DIR/transport-hy2.sh" ;;
        byedpi) echo "$ENODIA_DIR/transport-byedpi.sh" ;;
        # zapret — псевдо-транспорт: сам zapret.sh несёт контракт up|down|health|failover
        # (адаптеры над on/off/apply + прямой DNS). См. zapret.sh «транспорт-адаптер».
        zapret) echo "$ENODIA_DIR/zapret.sh" ;;
        *)      echo "" ;;
    esac
}

# Готов ли транспорт к подъёму: плагин установлен + есть его секрет-конфиг.
transport_ready() {
    p=$(plugin_for "$1"); [ -n "$p" ] && [ -f "$p" ] || return 1
    transport_installed "$1" || return 1
    case "$1" in
        # awg — БАЗА, но awg.conf мог появиться позже (залили конфиг страны через «Серверы»).
        awg)  [ -f "$ENODIA_STATE/awg.conf" ] ;;
        # Для альтов требуем И секрет-конфиг: осиротевший конфиг на флеше не должен выдавать
        # транспорт за готовый, а бинарь без конфига — тем более.
        xray) [ -s "$ENODIA_STATE/xray.json" ] ;;
        hy2)  [ -s "$ENODIA_STATE/hysteria.yaml" ] ;;
        # byedpi — БЕЗ секрет-конфига (нет VPS): десинк локальный, бинарей достаточно.
        # Десинк-аргументы опциональны (.byedpi-args или дефолт).
        byedpi) : ;;
        # zapret — БЕЗ конфига, но требует сборку iptables, УМЕЮЩУЮ NFQUEUE: на AX3600 (ядро 4.4,
        # iptables 1.6.2 без libxt_NFQUEUE) бинарь есть, а правило перехвата не поставить —
        # «готов» там означало бы «предложи человеку транспорт, который не встанет». Ответ у
        # плагина (verb nfq-ok), он же его кэширует; плагина нет/верб не знает (старая копия) —
        # не сужу, оставляю как раньше.
        zapret) _zp=$(plugin_for zapret)
                if [ -f "$_zp" ]; then sh "$_zp" nfq-ok >/dev/null 2>&1 || [ "$?" = 2 ]; else :; fi ;;
        *)    return 1 ;;
    esac
}

# ЧТО ЛЕЖИТ НА РОУТЕРЕ — только БИНАРИ, без конфига и без «а умеет ли это ядро». Вопрос ОТДЕЛЬНЫЙ
# от `transport_ready`, и разница видна человеку глазами: «Компоненты» показывают ПОСТАВЛЕН, а
# включить нельзя. Причин ровно три — не поставлен · поставлен, но нет сервера · поставлен, но на
# этом роутере невозможен — и панель обязана назвать ту, что есть, вместо общего «не установлен»
# (жалоба 15.08.2026 на AX3600: AmneziaWG и Zapret стоят, а пикер звал их в «Компоненты», где
# первому нечего ставить, а второму установка не поможет никогда).
# Знание «какой бинарь несёт транспорт» живёт ЗДЕСЬ, в одном месте: `transport_ready` выше зовёт
# нас первым шагом, второй копии списка в проекте нет.
transport_installed() {
    case "$1" in
        # ОБА бинаря: amneziawg-go (ДЕМОН несущей awg0) И awg (CLI amneziawg-tools — им
        # awg_setup.sh делает `awg setconf awg0`, без него awg0 НЕ встаёт). Раньше проверяли лишь
        # amneziawg-go: при половинной установке (демон докачался, а awg-CLI пропал — реальный
        # кейс из proto-install) list/switch/next считали awg «готовым», и switch awg РОНЯЛ
        # рабочую несущую. awg-база РЕЗИДЕНТНА всегда ($ENODIA_DIR, без bin_path): поднимается на
        # буте раньше любого монтирования, несёт «доступ домой» (awgs0 — тот же демон) и служит
        # последним рубежом failover, поэтому на съёмный носитель её не выносят вовсе.
        awg)    [ -x "$ENODIA_BIN/amneziawg-go" ] && [ -x "$ENODIA_BIN/awg" ] ;;
        # Бинарь ищем через bin_path — «его нет» и «он на выдернутой флешке» тут ОДИН И ТОТ ЖЕ
        # ответ, и это правильно: и там, и там подниматься нечем.
        xray)   [ -x "$(bin_path xray)" ] ;;
        hy2)    [ -x "$(bin_path hysteria)" ] ;;
        # byedpi несёт трафик через общий hev (tun2socks-слой) — без него он не транспорт.
        byedpi) [ -x "$(bin_path byedpi)" ] && [ -x "$(bin_path hev)" ] ;;
        # zapret работает на форварде через NFQUEUE, а не через socks ⇒ hev ему не нужен.
        zapret) [ -x "$(bin_path nfqws)" ] ;;
        *)      return 1 ;;
    esac
}

active() { cat "$TRANSPORT_FLAG" 2>/dev/null | tr -d ' \r\n'; }
apply_marking() { [ -f "$MARK_CORE" ] && sh "$MARK_CORE" >/dev/null 2>&1; }

# «ТРАНСПОРТА НЕТ ВООБЩЕ» — состояние установки «только панель»: роутер обычный, наших правил в
# ядре НЕТ, весь трафик идёт как у стока, а человек добирает протоколы в панели. Отличать его
# нужно ВСЕМ, кто иначе примется «чинить» несущую, которой никто не заводил: сторож (лестница
# failover → письмо «VPN упал» на роутере, где VPN и не настраивали), heal (подъём awg-несущей),
# vpn-toggle repair, mipctld-гард (переиграл бы mark-core и вернул маркировку в пустую table 1000).
#
# ПРИЗНАК ДВОЙНОЙ, и второе условие тут не педантизм, а совместимость: `.transport` появился
# позже самого проекта, и на роутере, установленном до него, файла НЕТ, а несущая — awg. Судить
# по одному пустому флагу значило бы объявить «транспорта нет» на живом рабочем роутере и
# ВЫКЛЮЧИТЬ там сторожа. Поэтому: пусто И нет awg.conf.
#
# Ответ живёт ЗДЕСЬ, потому что весь рантайм ходит к транспортам только через оркестратор.
# Потребители отличают старую копию скрипта по коду 2 (верб не знаком) и в этом случае ведут
# себя как раньше — то есть обновление в любом порядке безопасно.
cmd_configured() {
    [ -n "$(active)" ] && return 0
    [ -f "$ENODIA_STATE/awg.conf" ] && return 0
    return 1
}

# «А ПОДНИМЕТСЯ ЛИ ОН ЗДЕСЬ» — вопрос, ОТДЕЛЬНЫЙ от `configured` выше, и путать их дорого:
# `configured` судит по НАМЕРЕНИЮ (флаг/конфиг ЕСТЬ), а намерение приезжает и ИЗ БЭКАПА ЧУЖОГО
# роутера. Замерено на AX3600 16.08.2026: импорт архива с BE7000 вернул `.transport=awg` и
# `awg.conf`, бинарей AmneziaWG на этом роутере не было ни разу — и рантайм принялся «чинить»
# несущую, которой неоткуда взяться: сторож каждые 2 минуты снимал heal-лок, heal каждую минуту
# гонял ПОЛНЫЙ бутовый сценарий, а его вердикт слал письмо «после загрузки VPN НЕ поднялся».
# Ответ тот же, что у `list` (плагин + бинари + секрет-конфиг + «умеет ли ядро»), но одним
# транспортом и КОДОМ ВОЗВРАТА: читателю не нужно решать, чем пустой вывод `list` отличается от
# старой копии скрипта, — он отличает её по коду 2, как у `configured`.
cmd_ready() {
    _rt="${1:-$(active)}"
    [ -n "$_rt" ] || return 1          # транспорт не выбран вовсе — подниматься нечему
    transport_ready "$_rt"
}

# Список для СЕЛЕКТОРА (панель/меню) — реестр + zapret. Авто-cross берёт только REGISTRY.
# `return 0` ОБЯЗАТЕЛЕН, ровно по той же причине, что и у cmd_slot_list ниже: без него код
# возврата = вердикт ПОСЛЕДНЕЙ итерации, а последний в SELECTABLE — zapret, и на ядре без NFQUEUE
# (AX3600/BE3600) `list` печатал ВЕРНЫЙ список с кодом 1. Потребитель судит по коду: в диаг-архиве
# под правильным списком стояло «(list не отработал)» (dump.sh), а фолбэк слотов (slots.sh)
# строится на кодах этой пары. Пустой список ≠ ошибка; старую копию скрипта читатель отличает по 2.
cmd_list() { for t in $SELECTABLE; do transport_ready "$t" && echo "$t"; done; return 0; }
# Установленные (бинари на месте) — НЕ то же, что готовые: разницу показывает панель, называя
# причину «почему стоит, а включить нельзя». См. transport_installed.
# С ИМЕНЕМ — тот же вопрос про ОДИН транспорт, но КОДОМ ВОЗВРАТА: это разные вопросы, и цена
# путаницы разная. «Не готов» бывает от трёх причин (нет бинаря · нет конфига · ядро не умеет), а
# совет «поставьте компонент» верен ровно для первой — сторож обязан спрашивать именно про бинари,
# иначе он посоветует установку там, где она не поможет никогда (zapret на ядре 4.4).
cmd_installed() {
    if [ -n "$1" ]; then transport_installed "$1"; return $?; fi
    for t in $SELECTABLE; do transport_installed "$t" && echo "$t"; done
    return 0            # ПЕРЕЧИСЛЕНИЕ — код 0 всегда (та же грабля, что у cmd_list выше)
}
# ВСЕ известные имена — БЕЗ проверки готовности. Нужен тем, кто валидирует ввод, а не подъём:
# реестр выходов (slots.sh valid_transport) заводит слот и до установки бинаря (deferred-config),
# и вшитая копия списка там означала бы «шестой транспорт = неизвестный транспорт».
cmd_names() { for t in $SELECTABLE; do echo "$t"; done; }

# Готовность транспорта нести ДОП-ВЫХОД (слот) — НЕ то же, что transport_ready. Разница
# принципиальная: transport_ready отвечает «может стать ОСНОВНОЙ несущей» и потому требует
# АКТИВНЫЙ конфиг (xray.json / hysteria.yaml — тот, что скопирован при активации). Выходу же
# активный конфиг не нужен: у него СВОЙ сервер из каталога xray-configs/ (hy2-configs/), и
# типовой сценарий Ф3 — «основной awg, а нейронки через xray-сервер», где xray основным НЕ
# активировался НИ РАЗУ и xray.json отсутствует. По transport_ready такой xray в пикер выходов
# не попал бы вовсе — фича выглядела бы «не работает».
# Условие: плагин умеет слоты (список ниже = зеркало реализованных slot-up/slot-down) +
# бинарь + для конфиг-зависимых хотя бы один конфиг в каталоге.
SLOT_CAPABLE="zapret awg byedpi xray hy2"
slot_ready() {
    case " $SLOT_CAPABLE " in *" $1 "*) ;; *) return 1 ;; esac
    p=$(plugin_for "$1"); [ -n "$p" ] && [ -f "$p" ] || return 1
    case "$1" in
        awg)    [ -x "$ENODIA_BIN/amneziawg-go" ] && [ -x "$ENODIA_BIN/awg" ] && ls "$ENODIA_STATE"/configs/*.conf     >/dev/null 2>&1 ;;
        xray)   [ -x "$(bin_path xray)" ]     && [ -x "$(bin_path hev)" ] && ls "$ENODIA_STATE"/xray-configs/*.json >/dev/null 2>&1 ;;
        hy2)    [ -x "$(bin_path hysteria)" ] && [ -x "$(bin_path hev)" ] && ls "$ENODIA_STATE"/hy2-configs/*.yaml  >/dev/null 2>&1 ;;
        byedpi) [ -x "$(bin_path byedpi)" ]   && [ -x "$(bin_path hev)" ] ;;   # десинк без сервера
        # zapret — десинк без несущей, но одного бинаря МАЛО: нужен ЯДЕРНЫЙ NFQUEUE. Вопрос тот
        # же, что у transport_ready, а ответ был свой — по бинарю, — и на ядре 4.4 (AX3600/BE3600,
        # libxt_NFQUEUE вырезан) расходился с ним ровно наоборот: `list` zapret не показывал, а
        # `slot-list` предлагал (замерено на AX3600 16.08.2026). Пикер «добавить выход» обещал
        # человеку выход, который на этом роутере не встанет ВООБЩЕ. Спрашиваем владельца ответа —
        # плагин (он же кэширует); код 2 = старая копия без верба ⇒ не сужу, веду себя как раньше.
        # Имя `_szp` СВОЁ: `local` в busybox нет, а `$p` тут общий на всю функцию и `_zp` уже занят
        # в transport_ready — на одинаковых именах этот проект уже обжигался (см. `srv_rules`).
        zapret) [ -x "$(bin_path nfqws)" ] || return 1
                _szp=$(plugin_for zapret)
                sh "$_szp" nfq-ok >/dev/null 2>&1 || [ "$?" = 2 ] ;;
        *)      return 1 ;;
    esac
}
cmd_slot_list() { for t in $SLOT_CAPABLE; do slot_ready "$t" && echo "$t"; done; return 0; }   # rc всегда 0: пустой список ≠ ошибка (вызывающий отличает старый скрипт по rc=2 usage)

# Следующий готовый транспорт, отличный от $1 (первый по РЕЕСТРУ — авто-cross). Код 1 — нет
# другого. zapret в cross НЕ участвует: как ИСТОЧНИК (его нет в REGISTRY) и как ЦЕЛЬ — из
# безтуннельного режима осознанно НЕ убегаем на VPS сами (нет VPS = выбор пользователя;
# не оживёт nfqws → watchdog уводит в прямой режим, а не тайком в туннель). [[zapret-as-5th-transport]]
cmd_next() {
    [ "$1" = zapret ] && return 1
    for t in $REGISTRY; do
        [ "$t" = "$1" ] && continue
        transport_ready "$t" && { echo "$t"; return 0; }
    done
    return 1
}

# Поднять несущую транспорта поверх общего ядра (mark-core). Деф. — активный.
cmd_up() {
    # Пустой флаг = либо роутер, установленный ДО появления `.transport` (несущая там awg —
    # исторический фолбэк ниже), либо установка «только панель», где транспорта нет вовсе. Во
    # втором случае фолбэк на awg означал бы «подними то, чего не ставили»: плагин честно не
    # найдёт бинарей, но каждый вызыватель (heal на буте, repair, тик сторожа) платил бы за это
    # попыткой и строкой ошибки в логе, а человек читал бы про AmneziaWG на роутере, где он
    # ничего, кроме панели, не ставил.
    t="${1:-$(active)}"
    [ -n "$t" ] || { [ -f "$ENODIA_STATE/awg.conf" ] && t=awg; }
    [ -n "$t" ] || { echo "[transport] транспорт не настроен — поднимать нечего"; return 1; }
    p=$(plugin_for "$t"); [ -f "$p" ] || { echo "[transport] нет плагина для '$t'"; return 1; }
    apply_marking
    sh "$p" up
}

# Переключить активный транспорт: отпустить текущую несущую (плагин down — чистый
# релинквиш), поднять несущую нового. awg0-интерфейс при этом НЕ опускается (тёплый резерв;
# down снимает лишь маршрутизацию).
#
# ПРО .transport, чтобы не искать: файл пишем и МЫ, и КАЖДЫЙ плагин в своём `up`. Это не
# небрежность, а семантика «кто СЕЙЧАС несёт»: плагин поднимают и напрямую (switch-vpn после
# смены страны, `vpn-toggle repair`, ручной вызов), и промолчи он — флаг остался бы на прежнем
# транспорте, а heal/watchdog на буте поднимали бы ЧУЖУЮ несущую. Единственная точка ПЕРЕХОДА
# (down старого → up нового) — этот верб, и обязанность вызывающего именно в том, чтобы менять
# транспорт через него, а не поднимать плагин в обход (см. switch-vpn.sh switch_to, где перед
# сменой awg-сервера явно опускается чужая несущая).
# Лок берём ТОЛЬКО если его ещё нет: когда нас зовут ИЗ-ПОД чужого лока (switch-vpn держит его на
# всю смену страны), снять чужой лок в конце — значит открыть окно ровно там, где вызывающий его
# закрывал. Свой снимаем trap'ом на EXIT (идиома switch-vpn.sh), сохраняя код возврата: его читают
# watchdog/proto-install.
SWITCH_LOCK_MINE=0
take_switch_lock() {
    [ -e "$SWITCH_LOCK" ] && return 0
    : > "$SWITCH_LOCK" 2>/dev/null && SWITCH_LOCK_MINE=1
    trap 'drop_switch_lock' EXIT INT TERM HUP
    return 0
}
drop_switch_lock() {
    _slrc=$?
    [ "$SWITCH_LOCK_MINE" = 1 ] && rm -f "$SWITCH_LOCK" 2>/dev/null
    return $_slrc
}

cmd_switch() {
    new="$1"
    # Отказ обязан НАЗВАТЬ ПРИЧИНУ: «нет плагина/конфига» — верно для альтов, но на роутере без
    # NFQUEUE (AX3600) причина другая и лечится не конфигом, а другим роутером. Спрашиваем плагин
    # (verb nfq-ok, ответ кэширован); rc=2 = старая копия не знает верба ⇒ прежний общий текст.
    transport_ready "$new" || {
        _why="нет плагина/конфига"
        if [ "$new" = zapret ] && [ -x "$(bin_path nfqws)" ]; then
            _zp2=$(plugin_for zapret)
            if [ -f "$_zp2" ]; then
                sh "$_zp2" nfq-ok >/dev/null 2>&1 || [ "$?" = 2 ] || \
                    _why="сборка iptables на этом роутере не умеет NFQUEUE — десинк здесь невозможен"
            fi
        fi
        echo "[transport] '$new' не готов ($_why)"; return 1
    }
    take_switch_lock         # сторож/heal на время переключения не вмешиваются (см. SWITCH_LOCK)
    cur=$(active)
    if [ -n "$cur" ] && [ "$cur" != "$new" ]; then
        cp=$(plugin_for "$cur"); [ -f "$cp" ] && sh "$cp" down
    fi
    apply_marking            # гарантируем ядро (на случай прихода из safety_off, где маркировка снята)
    echo "$new" > "$TRANSPORT_FLAG"
    np=$(plugin_for "$new"); [ -f "$np" ] || { echo "[transport] нет плагина для '$new'"; return 1; }
    sh "$np" up && return 0
    # up НЕ удался (сервер по имени не резолвится / кривой конфиг / демон не встал). Без
    # отката .transport ЗАЛИП бы на дохлом транспорте: heal/watchdog на КАЖДОМ буте поднимали
    # бы именно его, а рабочая старая несущая осталась бы снятой (down выше). Откатываемся:
    # возвращаем флаг на прежний транспорт и поднимаем его обратно (best-effort). Возврат 1 —
    # вызывающий (watchdog/proto-install) видит провал и эскалирует штатно.
    echo "[transport] '$new' up НЕ удался → откат на '${cur:-—}'"
    if [ -n "$cur" ] && [ "$cur" != "$new" ] && transport_ready "$cur"; then
        echo "$cur" > "$TRANSPORT_FLAG"
        cp2=$(plugin_for "$cur"); [ -f "$cp2" ] && sh "$cp2" up >/dev/null 2>&1
    fi
    return 1
}

# Отпустить несущую транспорта (плагин down — ЧИСТЫЙ релинквиш -> fail-open в прямой).
# НЕ решает, что поднять следом, и НЕ переписывает .transport (это забота switch/вызывающего:
# напр. watchdog зовёт down при уходе в прямой режим, оставляя .transport прежним для boot/heal).
cmd_down()     { t="${1:-$(active)}"; p=$(plugin_for "$t"); [ -f "$p" ] && sh "$p" down; }
cmd_health()   { t="${1:-$(active)}"; p=$(plugin_for "$t"); [ -f "$p" ] && sh "$p" health; }
cmd_failover() { t="${1:-$(active)}"; p=$(plugin_for "$t"); [ -f "$p" ] && sh "$p" failover; }

# Переиграть DNS АКТИВНОГО транспорта (не трогая маршрутизацию/несущую). Панель зовёт при
# live-переключении DoH (on/off) и смене резолвера: каждый DNS-сеттер плагина проходит через
# doh_apply_dns — DoH-вкл ставит dnsmasq→локальный прокси + марку резолвера, DoH-выкл
# возвращает прежний путь транспорта БАЙТ-В-БАЙТ. Единая «reapply DNS» для всех транспортов.
# Нет активного транспорта (fail-open) → применяем DoH direct напрямую (при выключенном DoH —
# no-op: прямой публичный DNS уже стоит с момента релинквиша несущей).
cmd_dns() {
    t="${1:-$(active)}"
    if [ -n "$t" ]; then
        p=$(plugin_for "$t"); [ -f "$p" ] && { sh "$p" dns; return $?; }
    fi
    if [ -f "$ENODIA_DIR/doh-lib.sh" ]; then . "$ENODIA_DIR/doh-lib.sh"; fi
    command -v doh_apply_dns >/dev/null 2>&1 && doh_apply_dns direct
    return 0
}

# --- ДОП-ВЫХОДЫ (слоты мульти-транспорта, Ф0; дизайн: local/CLAUDE-мультитранспорт-дизайн.md) ---
# Оркестратор — единственная точка, через которую рантайм (heal/watchdog/панель) трогает
# НЕСУЩИЕ слотов (как с основным транспортом: имя файла плагина нигде больше не хардкодится).
# Контракт плагина расширен ОПЦИОНАЛЬНЫМИ вербами `slot-up|slot-down <id> <config>`: плагин
# без поддержки слотов (Ф0 — все) падает в своё `*) usage; exit 2` — глотаем шум и честно
# сообщаем, слот остаётся жить по fallback-политике. Куда смотрит ip rule слота, решает
# mark-core (FALLBACK-AWARE, см. его слот-блок): после любого slot-up/down достаточно
# переиграть маркировку — правило само встанет (живая table 100N / table 1000 = main / direct).
SLOTS_SH="$ENODIA_DIR/slots.sh"
TAB=$(printf '\t')

# Диспетч верба в плагин транспорта слота БЕЗ переигрыша маркировки (внутренний кирпич:
# slots-up гоняет его в цикле и переигрывает mark-core ОДИН раз на всех). Код 2 = «плагин
# слоты не умеет» (Ф0-норма, usage-шум глотаем), 1 = слот не найден/выключен/нет плагина.
_slot_dispatch() {
    sverb="$1"; sid="$2"
    sline=$([ -f "$SLOTS_SH" ] && sh "$SLOTS_SH" show "$sid" 2>/dev/null)
    [ -n "$sline" ] || { echo "[transport] нет слота №$sid"; return 1; }
    [ "$(echo "$sline" | cut -f6)" = on ] || { echo "[transport] слот №$sid выключен"; return 1; }
    st=$(echo "$sline" | cut -f3); scfg=$(echo "$sline" | cut -f4)
    sp=$(plugin_for "$st"); [ -f "$sp" ] || { echo "[transport] нет плагина для '$st'"; return 1; }
    sout=$(sh "$sp" "$sverb" "$sid" "$scfg" 2>&1); src=$?
    if [ "$src" = 2 ]; then
        echo "[transport] '$st' пока не умеет слоты — выход №$sid живёт по fallback-политике"
    else
        [ -n "$sout" ] && printf '%s\n' "$sout"
    fi
    return $src
}

cmd_slot_up()   { _slot_dispatch slot-up "$1";   src=$?; apply_marking; return $src; }
cmd_slot_down() { _slot_dispatch slot-down "$1"; src=$?; apply_marking; return $src; }
# Здоровье ДОП-ВЫХОДА (Ф3) — БЕЗ переигрыша маркировки: проба read-only, её зовёт watchdog
# каждый тик. Плагин отвечает 0 = жив / 1 = просел; 2 = «не умеет slot-health» (тогда сторож
# решает по своим признакам, как для awg/byedpi). Вывод плагина глушим — в лог пишет сторож.
cmd_slot_health() { _slot_dispatch slot-health "$1" >/dev/null 2>&1; return $?; }

# Поднять несущие ВСЕХ включённых слотов (boot/heal, зовёт heal.sh 5.13b). Ф0: плагины
# слоты не умеют — каждый слот сообщит и останется на fallback; mark-core переигрываем один
# раз в конце (он же донесёт марки слот-сетов, созданных groups/geo ПОСЛЕ up-пути несущей).
cmd_slots_up() {
    [ -f "$SLOTS_SH" ] || return 0
    sids=$(sh "$SLOTS_SH" list-enabled 2>/dev/null | cut -f1)
    [ -n "$sids" ] || return 0
    for sid in $sids; do _slot_dispatch slot-up "$sid"; done
    apply_marking
    return 0
}

# Верб `slots` (статус включённых доп-выходов) СНЯТ — это был мёртвый дубль: на тот же вопрос
# отвечает `slots.sh state` (его читают панель и cgi-bin/status), а здешняя копия отвечала
# СВОИМ словарём (table100N/main/direct против up/dead/fallback/direct/down/idle/off) и уже
# начала расходиться — плюс её `grep -E "\S"` был GNU-расширением, на busybox не гарантированным.
# Потребителей в репо не было ни одного. Единственная истина по состоянию выхода — slots.sh.

case "$1" in
    active)   active; echo ;;
    configured) cmd_configured ;;
    ready)    cmd_ready "$2" ;;
    marking)  cmd_marking "$2" ;;   # машинно: везёт ли транспорт по марке (0 да · 1 нет · 2 старая копия)
    names)    cmd_names ;;
    list)     cmd_list ;;
    installed) cmd_installed "$2" ;;
    next)     cmd_next "$2" ;;
    up)       cmd_up "$2" ;;
    down)     cmd_down "$2" ;;
    switch)   cmd_switch "$2" ;;
    health)   cmd_health "$2" ;;
    failover) cmd_failover "$2" ;;
    dns)      cmd_dns "$2" ;;
    slots-up) cmd_slots_up ;;
    slot-up)   cmd_slot_up "$2" ;;
    slot-down) cmd_slot_down "$2" ;;
    slot-health) cmd_slot_health "$2" ;;
    slot-list) cmd_slot_list ;;      # транспорты, готовые нести ДОП-ВЫХОД (пикер в панели; ≠ list)
    *) echo "usage: $0 active|configured|ready [t]|marking <t>|names|list|installed [t]|next <t>|up [t]|down [t]|switch <t>|health [t]|failover [t]|dns [t]|slots-up|slot-up <id>|slot-down <id>|slot-health <id>|slot-list"; exit 2 ;;
esac
