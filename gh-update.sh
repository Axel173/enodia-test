#!/bin/sh
# gh-update.sh — апдейтер с GitHub (Ф4). Скачивает скрипты/бинари из ПУБЛИЧНОГО репо
# Axel173/enodia. На роутере НЕТ ПК-источника бинарей, поэтому смена
# набора протоколов (proto-install.sh) и обновление кода идут отсюда.
#
# ПОЧЕМУ так / грабли:
#   * curl -fsSL к raw.githubusercontent.com на роутере РАБОТАЕТ (установщик так же качает
#     RE_FILTER_URL). При живом VPN запрос идёт через туннель (Fastly-IP в iplist), при
#     мёртвом — напрямую (safety_off делает DNS публичным). Сетевой сбой не фатален.
#   * Замена файла НЕ роняет демоны (они в RAM) и НЕ перезапускает их — после apply нужен
#     repair/ребут. Авто-switch НЕ делаем.
#   * Защита от ДАУНГРЕЙДА: публичный репо может ОТСТАВАТЬ от рантайма роутера (на роутере
#     бывают НЕвыпущенные dev-скрипты). apply-scripts обновляет ТОЛЬКО если remote CODE >
#     local CODE; remote без VERSION → отказ (не «обновляем в ноль»).
#   * Бинарь качаем в .dl, проверяем (ELF-magic + минимальный размер + sha256 из SHA256SUMS),
#     atomic mv — обрыв закачки не оставит полу-файл вместо рабочего бинаря.
#   * rm живёт ЗДЕСЬ, в .sh на роутере (PS-guard ложно блокирует литерал rm в SSH-командах).
#   * busybox этого роутера БЕЗ od/hexdump → ELF-magic сверяем через printf '\177ELF' + cmp.

ENODIA_DIR=/data/usr/app/enodia
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
# Репозиторий-источник. Override: строка `владелец/репо` в $ENODIA_STATE/.gh-repo — ею тестовый
# роутер переключается на черновой репозиторий, не трогая код. Форму ПРОВЕРЯЕМ: кривая строка
# построила бы URL, который просто не резолвится, и отказ читался бы как «нет сети».
# Обрезаем ТОЛЬКО обрамляющие пробелы, а не все подряд (у соседних `.gh-ref`/`.gh-bin-tag` стоит
# `tr -d ' \r\n'`, и здесь это ловушка): «Axel173/enodia test» склеилось бы в «Axel173/enodiatest»
# — синтаксически верное, но ЧУЖОЕ имя, и опечатка увела бы источник кода молча. Пробел внутри
# обязан отвергаться гардом ниже, а не исправляться.
REPO=$(cat "$ENODIA_STATE/.gh-repo" 2>/dev/null | tr -d '\r\n' | sed 's/^[ 	]*//; s/[ 	]*$//')
case "$REPO" in ''|*[!A-Za-z0-9._/-]*|/*|*/|*/*/*) REPO= ;; */*) : ;; *) REPO= ;; esac
[ -n "$REPO" ] || REPO="Axel173/enodia"
# Ветка/тег источника. Override: положить строку в $ENODIA_STATE/.gh-ref (напр. v0.4.0).
GH_REF=$(cat "$ENODIA_STATE/.gh-ref" 2>/dev/null | tr -d ' \r\n'); [ -n "$GH_REF" ] || GH_REF=main
RAW="https://raw.githubusercontent.com/$REPO/$GH_REF"
# --- ОТКУДА БЕРЁМ БИНАРИ: из папки `bin/` через raw; ассет релиза — ВТОРОЙ канал. -----------
# Байты у обоих ОДНИ И ТЕ ЖЕ — файл `bin/<арка>/<имя>.user` этого репозитория; ассет лишь
# раздаётся ДРУГИМ сервисом (редирект на release-assets/objects.githubusercontent.com). Поэтому
# ключом целостности остаётся ПУТЬ ПО РЕПО и `SHA256SUMS` не меняется вовсе. В релизах НЕТ ПАПОК
# ⇒ имя ассета плоское: `<арка>-<файл>.user`. Тег отдельный (`bin`) и переносится при обновлении
# бинарей — к версии КОДА он отношения не имеет.
#
# ПОПРАВКА 30.08.2026 — чтобы не решить это второй раз неверно. Здесь стояло «ассет ОСНОВНОЙ,
# raw защищается от массовой закачки бинарей», со ссылкой на замер 17.08.2026 (AX3600: raw дал
# 429 на `bin/arm64/amneziawg-go.user`, тот же файл ассетом приехал за 1.05 с). ЗАМЕРЕН был
# только сам факт; ПРИЧИНА была ДОГАДКОЙ, и она неверна: в тот день шла глобальная авария
# GitHub (13:28–21:15 UTC, ~7.5 ч), при которой загрузка raw-контента и архивов шла с ~50%
# ошибок. То есть 429 — почти наверняка сброс нагрузки во время аварии, а не наш «скрейпинг».
# КОНТРЗАМЕР 30.08.2026: десять бинарей подряд (16 МБ) с raw — ВСЕ 200, суммарно 5.6 с, ни
# одного 429. Рейт-лимита на такой объём у raw нет.
# ⇒ Порядок вернулся к прежнему: сперва raw, ассет — резерв на случай аварии (в тот день
# работал именно он). Ассеты при этом можно НЕ ЗАЛИВАТЬ вовсе: отсутствующий ассет = 404, а
# отказом (`gh_code_refused`) считаются только 429/403 ⇒ цикл спокойно уходит дальше. Понадобится
# запасной канал — залил тег `bin`, и он включился сам, без обновления роутеров.
GH_BIN_TAG=$(cat "$ENODIA_STATE/.gh-bin-tag" 2>/dev/null | tr -d ' \r\n'); [ -n "$GH_BIN_TAG" ] || GH_BIN_TAG=bin
GH_REL="https://github.com/$REPO/releases/download/$GH_BIN_TAG"
BACKUP_ROOT="$ENODIA_DIR/.gh-backup"
# Сколько СНИМКОВ бэкапа держим. apply-scripts копирует ВЕСЬ манифест (на dev-сборке это ~3 МБ:
# скрипты + web/assets/panel.js + шрифт), а /data — 20 МБ. Без ротации три обновления подряд
# забивают флеш, и первым ложится DNS/туннель (грабля «всё тяжёлое — в ОЗУ, не на флеш»);
# «Компоненты» такой бэкап считают мусором, но чистит его ЧЕЛОВЕК и только руками. Откатить
# можно всё равно лишь ПОСЛЕДНИЙ снимок ⇒ два — уже запас.
BACKUP_KEEP=${BACKUP_KEEP:-2}
# Ниже этого свободного места на /data обновление не начинаем: нужен снимок + `.new`-файлы, а
# «No space» посреди apply оставит набор скриптов ПОЛУОБНОВЛЁННЫМ. Тот же гард, что у подписок.
GH_MINFREE_KB=${GH_MINFREE_KB:-4096}
# Надёжная закачка с raw.githubusercontent ЧЕРЕЗ VPN. ВАЖНО (поймано на железе 2026-06-16):
# у raw.githubusercontent.com 4 anycast-IP (185.199.108-111.133), ВСЕ в iplist_set → идут через
# VPN/VPS. Часть anycast-узлов через VPS «мёртвая»: TCP-connect к ним УСПЕШЕН и быстрый
# (t_connect≈0.03с), но дальше соединение МОЛЧИТ (данные не идут). Поэтому --connect-timeout НЕ
# спасает (connect-то прошёл!), curl коммитится на мёртвый IP и висит до --max-time, не пробуя
# живые, а --retry переснимает тот же набор → закачка «то идёт, то нет» (лотерея, какой IP DNS
# отдал первым; замер: .110.133 мёртв, .108/.109/.111 живы). Решение — gh_get(): ЯВНО перебираем
# известные IP (--resolve) до первого живого + рубим «молчащее» соединение через --speed-time.
CURL_TIMEOUT=150
# Опции ОДНОЙ попытки. --speed-limit/--speed-time — главное: рубит соединение, которое
# подключилось, но отдаёт <4 КБ/с дольше 8с (мёртвый узел = 0 Б/с → обрыв за 8с). connect-timeout
# на случай реально недоступного узла. БЕЗ --retry: перебор IP делает gh_get сам (curl --retry
# переснял бы тот же набор и мог снова сесть на мёртвый IP).
CURL_OPTS="--connect-timeout 8 --speed-limit 4096 --speed-time 8 --max-time $CURL_TIMEOUT"
GH_RAW_HOST=raw.githubusercontent.com
GH_RAW_IPS="185.199.108.133 185.199.109.133 185.199.110.133 185.199.111.133"
# Хосты, на которые уезжает РЕДИРЕКТ за ассетом релиза (сам запрос идёт на github.com по DNS).
# Замерено: они резолвятся в ТЕ ЖЕ четыре anycast-адреса, что и raw, — значит и болезнь та же
# («узел подключился и молчит»), и лечится тем же списком. Имён два: GitHub отдаёт то одно, то
# другое; пиним оба, незадействованное просто не встретится.
GH_ASSET_HOSTS="release-assets.githubusercontent.com objects.githubusercontent.com"

# --- ЧТО ИМЕННО ОТВЕТИЛ GITHUB. Отдельный слой, потому что вопрос «почему не скачалось» имеет
# РАЗНЫЕ ответы с разными действиями человека, а раньше все они схлопывались в одну строку
# «не скачался (сеть/нет места?)». Поймано на железе AX3600 17.08.2026: raw.githubusercontent
# ответил 429 (ограничение по частоте — за день сделали десяток чистых установок с одного
# внешнего адреса), панель написала «Часть компонентов не установилась», и в логе не было НИ
# ОДНОГО намёка, что ждать надо минут десять, а не чинить сеть.
# Состояние держим В ФАЙЛЕ, а не в переменной: закачку fetch_bin гоняет в ФОНОВОЙ подоболочке
# (`gh_get … &` ради строк прогресса), а присваивание оттуда наружу не возвращается.
GH_CODE_FILE="/tmp/.gh-code.$$"
gh_code_reset() { : > "$GH_CODE_FILE" 2>/dev/null; }
gh_code_note() {
    case "$1" in ''|000) return 0 ;; esac   # 000 = не соединились, это не ответ сервера
    # УСПЕШНЫЙ код причиной ОТКАЗА не бывает, а попасть сюда может: `--speed-time` рубит закачку,
    # которая началась (заголовок 200 уже пришёл) и замолчала на середине — curl отдаёт rc=28 и
    # http_code=200. Запиши мы его, и оборванный на полпути бинарь объяснялся бы человеку строкой
    # «GitHub ответил HTTP 200». Молчим — пусть говорит вызвавший («нет связи/нет места»).
    case "$1" in [123]??) return 0 ;; esac
    # Отказ ПО ЧАСТОТЕ старше прочих кодов: перебор anycast-IP и второго пути даёт после него
    # 404/000, и «последний увиденный код» затёр бы единственный, который что-то объясняет.
    case "$(cat "$GH_CODE_FILE" 2>/dev/null)" in 429|403) return 0 ;; esac
    printf '%s' "$1" > "$GH_CODE_FILE" 2>/dev/null
}
gh_code_get() { cat "$GH_CODE_FILE" 2>/dev/null; }
# Человеческая причина по коду; пусто = сказать нечего (обычный сетевой сбой, пусть говорит вызвавший).
gh_code_reason() {
    case "$1" in
        429) echo "GitHub ограничил скачивание с вашего внешнего адреса (HTTP 429, слишком много обращений) — подождите 10-15 минут и повторите" ;;
        403) echo "GitHub отказал в выдаче файла (HTTP 403) — как правило, то же ограничение по частоте; подождите и повторите" ;;
        404) echo "на GitHub нет файла по этому пути (HTTP 404)" ;;
        5??) echo "GitHub отвечает ошибкой $1 — это на его стороне, повторите позже" ;;
        ''|000) echo "" ;;
        *)   echo "GitHub ответил HTTP $1" ;;
    esac
}
# «Сеть жива, но качать не дадут» — вердикт, которого не обойти ни другим доверием TLS, ни
# десинком (внешний адрес тот же). Отдельный предикат, потому что спрашивают его ДВОЕ.
gh_code_refused() { case "$(gh_code_get)" in 429|403) return 0 ;; *) return 1 ;; esac; }

# --- ДОВЕРИЕ TLS НА СБОРКАХ, ГДЕ curl НЕ НАХОДИТ СИСТЕМНОГО ХРАНИЛИЩА -----------------------
# ЗАМЕРЕНО на AX3600 15.08.2026: ЛЮБОЙ `curl https://` падал rc=60 «unable to get local issuer
# certificate», хотя нужный корень в бандле ЕСТЬ и с `--cacert` на ЭТОТ ЖЕ файл всё проходит —
# curl собран с CApath, где нет хешированных симлинков. Цена: на таких прошивках канал обновления
# закрыт целиком (панель пишет «обновление недоступно», proto-install отказывается менять набор).
# Разбор и сам примитив — В `dns-lib.sh::curl_ca_opt`: вопрос «чем ЭТОМУ curl доверять» про
# РОУТЕР, а не про GitHub, и ответ на него в проекте ОДИН (им же ходит DoH-цикл). Здесь только
# шим: старая установка без свежей библиотеки обязана вести себя ровно как раньше, а не падать.
if [ -f "$ENODIA_DIR/dns-lib.sh" ]; then . "$ENODIA_DIR/dns-lib.sh"; fi
command -v curl_ca_opt >/dev/null 2>&1 || curl_ca_opt() { return 0; }

# Опция доверия для ЭТОГО роутера. Пусто = системного доверия хватает (обычный случай).
gh_ca_opt() { curl_ca_opt; }

# Выяснить рабочий бандл. Зовётся ТОЛЬКО после провала обычного пути; 0 = нашли (и запомнили).
# ПРОБА ОБЯЗАНА ХОДИТЬ ТЕМ ЖЕ ПУТЁМ, ЧТО И ЗАКАЧКА. Для raw.githubusercontent это `--resolve` на
# известный anycast-IP: сюда попадают ровно тогда, когда DNS роутера мёртв (бут, несущая не встала,
# upstream заперт в туннель) — а проба «по имени» в этот момент не дозвонится никуда, вернёт
# «не помогло» и (до фикса в curl_ca_opt) запомнила бы это на весь бут, закрыв канал обновления
# насовсем. Один IP достаточно: вопрос не «жив ли GitHub», а «чем доверять сертификату».
gh_ca_probe() {   # $1 = URL, на котором споткнулись
    case "$1" in
        https://$GH_RAW_HOST/*) _capr="--resolve $GH_RAW_HOST:443:${GH_RAW_IPS%% *}" ;;
        *) _capr="" ;;
    esac
    _cap=$(curl_ca_opt "$1" $_capr)
    [ -n "$_cap" ] || return 1
    log "TLS: системное хранилище curl пусто — доверяю системному бандлу"
    return 0
}

log() { printf '%s\n' "$*"; }

# Надёжно скачать $1 → $2. Для raw.githubusercontent перебираем известные anycast-IP по очереди
# (--resolve), останавливаемся на ПЕРВОМ живом; __dns__ в конце — фолбэк через обычный DNS (вдруг
# GitHub сменил IP). Прочие хосты — одиночная попытка. Код 0 = успех. НЕ печатает (фон/прогресс
# наружи — в fetch_bin).
# Круг попыток (все anycast-IP либо одиночный хост) с ЗАДАННОЙ опцией доверия. Код 60 от curl =
# «не проверить сертификат» — его отличаем от прочих, чтобы знать, есть ли смысл во втором круге.
# ВЕРДИКТ КРУГА — ПО ВСЕМ ПОПЫТКАМ, А НЕ ПО ПОСЛЕДНЕЙ. Попытки идут в порядке «anycast-IP …, потом
# __dns__ по имени», а зовут этот круг как раз при мёртвом DNS ⇒ последняя попытка штатно падает
# с rc=6 («не резолвится») и ЗАТИРАЛА бы код 60 от всех предыдущих. Итог был бы ровно тот, от
# которого фикс и заведён: на роутере со сломанным CApath второй круг по доверию не запускается
# никогда, канал обновления закрыт. Поэтому 60, увиденный ХОТЬ РАЗ, и есть вердикт круга.
# `-w %{http_code}` пишет В STDOUT, поэтому забираем его подстановкой, а не отпускаем наружу:
# gh_get зовут внутри `$( )` (remote_version_raw), и лишняя строка ушла бы в разбор VERSION.
# Какие ИМЕНА пришпиливаем к перебираемому anycast-адресу. У raw это он сам; у ассета релиза —
# хосты РЕДИРЕКТА (запрос уходит на github.com по DNS, а файл отдают они). Пусто = хост нам
# незнаком, перебирать нечего, одна честная попытка.
gh_pin_hosts() {
    case "$1" in
        https://$GH_RAW_HOST/*) echo "$GH_RAW_HOST" ;;
        https://github.com/*)   echo "$GH_ASSET_HOSTS" ;;
        *)                      echo "" ;;
    esac
}
gh_get_round() {   # $1=url $2=out $3=опция доверия («» = системная)
    _gr=1; _g60=0
    _pin=$(gh_pin_hosts "$1")
    if [ -n "$_pin" ]; then
        for _ipx in $GH_RAW_IPS __dns__; do
            _res=""
            if [ "$_ipx" != __dns__ ]; then
                for _ph in $_pin; do _res="$_res --resolve $_ph:443:$_ipx"; done
            fi
            _c=$(curl -fsSL $CURL_OPTS $3 $_res -w '%{http_code}' -o "$2" "$1" 2>/dev/null); _gr=$?
            gh_code_note "$_c"
            [ "$_gr" = 0 ] && return 0
            [ "$_gr" = 60 ] && _g60=1
            # Отказ по частоте одинаков на ВСЕХ anycast-узлах (лимит на клиентский адрес, не
            # на узел) — перебирать остальные незачем, это только время на экране установки.
            gh_code_refused && break
            rm -f "$2"
        done
    else
        _c=$(curl -fsSL $CURL_OPTS $3 -w '%{http_code}' -o "$2" "$1" 2>/dev/null); _gr=$?
        gh_code_note "$_c"
        [ "$_gr" = 0 ] && return 0
        [ "$_gr" = 60 ] && _g60=1
    fi
    rm -f "$2"
    [ "$_g60" = 1 ] && return 60
    return "$_gr"
}
gh_get() {
    _ghu="$1"; _gho="$2"
    gh_code_reset          # вердикт — про ЭТОТ URL, а не про предыдущий
    _cao=$(gh_ca_opt)
    gh_get_round "$_ghu" "$_gho" "$_cao" && return 0
    _grc=$?
    # ВТОРОЙ КРУГ — только если споткнулись именно о ПРОВЕРКУ СЕРТИФИКАТА (60) и рабочий бандл
    # ещё не найден. На здоровом роутере сюда не заходят вовсе: там первый круг либо успешен,
    # либо провалился по другой причине (сеть, 404), и лишнего запроса не делается.
    if [ "$_grc" = 60 ] && [ -z "$_cao" ] && gh_ca_probe "$_ghu"; then
        _cao=$(gh_ca_opt)
        gh_get_round "$_ghu" "$_gho" "$_cao" && return 0
        # Вердикт ПЕРЕЗАПИСЫВАЕМ: дальше по коду решается, стоит ли будить десинк, а решает это
        # `_grc`. Оставь тут код ПЕРВОГО круга (60 = «сертификат не проверить») — и HTTP-ошибка,
        # полученная уже со здоровым бандлом, полетела бы в аварийный канал мимо отсечки ниже.
        _grc=$?
    fi
    # ТРЕТИЙ КРУГ — АВАРИЙНЫЙ КАНАЛ ЧЕРЕЗ ДЕСИНК (см. gh_socks_try). НО НЕ НА HTTP-ОШИБКЕ: `curl
    # -f` отдаёт 22 на 4xx/5xx, а это «сервер ответил», то есть сеть в порядке и десинку пробивать
    # нечего. Разница не теоретическая: `check` КАЖДЫЙ раз качает VERSION, которого в публичном
    # репо нет by design (404) — без этой отсечки любая проверка обновлений на любом роутере
    # поднимала бы ciadpi, ждала порт, повторяла запрос и получала тот же 404.
    [ "$_grc" = 22 ] && return 1
    # …и то же самое, когда вердикт круга затёрт кодом 60 от СОСЕДНЕГО узла (у одного не сошёлся
    # сертификат, другой ответил 429): решение принимает не `_grc`, а сам ответ GitHub.
    gh_code_refused && return 1
    gh_socks_round "$_ghu" "$_gho" "$_cao"
}

# --- АВАРИЙНЫЙ КАНАЛ: raw.github через локальный десинк (ciadpi) ------------------------------
# ЗАЧЕМ. Роутер теперь добирает ВСЕ протоколы сам, с GitHub — и упирается ровно в то, ради чего
# его и ставят: у части провайдеров raw.githubusercontent душится по SNI (соединение встаёт и
# молчит — тот самый случай, что рубит `--speed-time`). Раньше это лечилось заливкой бинарей с
# ПК; после реформы «ставим только панель» ПК из цепочки ушёл, и единственный оставшийся ответ —
# пробить блокировку тем, что уже лежит на роутере: ciadpi (0.13 МБ, кладётся вместе с панелью).
# Он тут НЕ транспорт: ни tun, ни правил, ни `.transport` — только socks на время закачки.
#
# Порядок кругов сознателен: сперва обычный путь (на здоровом провайдере он и работает), потом
# доверие, и лишь затем десинк. Обратный порядок гнал бы ВЕСЬ трафик обновлений через прокси,
# который на 176-МБ моделях стоит памяти, а на здоровой сети не нужен вовсе.
GH_SOCKS=""        # "" = ещё не пробовали · "-" = не вышло (второй раз не дёргаем) · адрес = есть
GH_SOCKS_MINE=0    # 1 = демон подняли МЫ и обязаны погасить
BYEDPI_SH="$ENODIA_DIR/transport-byedpi.sh"
gh_socks_try() {
    [ "$GH_SOCKS" = "-" ] && return 1
    [ -n "$GH_SOCKS" ] && return 0
    GH_SOCKS="-"
    [ -f "$BYEDPI_SH" ] || return 1
    # Код 2 = старая копия плагина не знает верба ⇒ канала нет, ведём себя как раньше.
    # Метка `$$` — наш pid для ref-счёта на стороне плагина: прокси РАЗДЕЛЯЕМЫЙ (нас могут
    # запустить в двух процессах сразу — «Обновить скрипты» и установка компонента), и без метки
    # закончивший первым гасил бы демона посреди чужой закачки. Старый плагин лишний аргумент
    # игнорирует, поэтому передаём его безусловно.
    _sa=$(sh "$BYEDPI_SH" socks-up "$$" 2>/dev/null | tail -n1 | tr -d ' \r')
    case "$_sa" in
        [0-9]*.[0-9]*.[0-9]*.[0-9]*:[0-9]*) : ;;
        *) return 1 ;;
    esac
    GH_SOCKS="$_sa"; GH_SOCKS_MINE=1
    log "GitHub напрямую не отвечает — пробую через локальный десинк ($GH_SOCKS)"
    return 0
}
# Гасим за собой ВСЕГДА: демон нужен ровно на время закачки, а на 176-МБ модели забытый ciadpi —
# это память, отнятая у несущей. Основную несущую byedpi (если она и была socks'ом) плагин не
# трогает — там свой пидфайл.
# СПРАШИВАЕМ ПЛАГИН ВСЕГДА, а не по своей переменной. `GH_SOCKS_MINE` живёт в ПАМЯТИ ТОГО шелла,
# который поднял прокси, — а поднимаем мы его сплошь и рядом внутри КОМАНДНОЙ ПОДСТАНОВКИ
# (`rv=$(remote_version_raw)` в cmd_check и т.п.). Из `$( )` присваивание наружу не возвращается,
# родитель видит 0, ловушка молчит, и ciadpi переживает процесс — на 176-МБ моделях это память,
# отнятая у несущей, и висит она до ребута. Поймано на железе AX3600 15.08.2026: после `check`
# порт 10809 остался слушать. Состояние, которое ПЕРЕЖИВАЕТ подоболочку, — не переменная, а файл,
# и владеет им плагин; `$$` в `$( )` тот же, что у родителя, значит метка совпадает. Лишний вызов
# безвреден: `socks-down` считает пользователей и чужого демона не трогает.
gh_socks_release() {
    [ -f "$BYEDPI_SH" ] && sh "$BYEDPI_SH" socks-down "$$" >/dev/null 2>&1
    GH_SOCKS_MINE=0
}
# Ловушка, а не строка в конце: закачку бинаря панель гоняет в фоне и может оборвать (человек
# закрыл экран, `-K` из CGI), а брошенный ciadpi остался бы жить до ребута, отнимая память у
# несущей. Сигналы перечислены явно — на busybox EXIT-ловушка по сигналу НЕ срабатывает.
trap 'gh_socks_release' EXIT INT TERM HUP
# ОДНА попытка через socks. `--resolve` здесь не нужен и не работает: имя резолвит прокси
# (--socks5-hostname), в этом половина смысла — DNS-путь тоже не наш.
gh_socks_round() {   # $1=url $2=out $3=опция доверия
    gh_socks_try || return 1
    curl -fsSL $CURL_OPTS $3 --socks5-hostname "$GH_SOCKS" -o "$2" "$1" 2>/dev/null && return 0
    rm -f "$2"
    return 1
}

# --- ДОСТИЖИМОСТЬ raw.githubusercontent (НЕ наличие файла). Для pre-check в proto-install:
#     цель — убедиться, что сетевой путь к GitHub жив ПЕРЕД сносом рабочего альта, а НЕ что
#     конкретный файл существует. Публичный репо может НЕ содержать пробный файл (напр. VERSION
#     туда не публикуется) → raw отдаёт HTTP 404, а `gh dl` c `curl -f` считал это «GitHub
#     недоступен» и блокировал смену набора (хотя bin/*.user на месте и качаются). Здесь
#     перебираем те же anycast-IP, но принимаем ЛЮБОЙ валидный HTTP-код (2xx/3xx/4xx/5xx) как
#     «сеть до GitHub жива»; только 000/пусто (нет коннекта) = недоступен. Пробный путь дешёвый
#     (тело отбрасываем в /dev/null), файл может и не существовать. Поймано на железе 2026-07-11.
#     ВТОРОЙ ПРОХОД ПО ДОВЕРИЮ (замерено на AX3600, разбор — в шапке gh_ca_probe): на сборках,
#     где curl не находит системного хранилища, КАЖДЫЙ IP отвечает `000` при живой сети, и проба
#     сообщала «GitHub недоступен» ВСЕГДА. Поэтому: не нашли путь обычным доверием — выясняем
#     рабочий бандл и пробуем ещё раз. Проверку сертификата НЕ отключаем (`-k` здесь больше нет):
#     раз проверяемый путь существует, пользоваться непроверяемым незачем.
#     ОТКАЗ ПО ЧАСТОТЕ — НЕ «доступен» (AX3600, 17.08.2026). Приняв ЛЮБОЙ код, проба зеленела на
#     429 «Too Many Requests»: пре-чек говорил «GitHub доступен», packages.sh шёл СНОСИТЬ старый
#     компонент, а закачка нового валилась на том же 429 — то есть ровно та авария («роутер без
#     транспорта»), ради которой пре-чек и написан. 429/403 значат «сеть до GitHub жива, но файла
#     он не даст», а вопрос здесь именно «дадут ли скачать».
gh_reach_round() {   # $1 = путь, $2 = опция доверия
    for _ipx in $GH_RAW_IPS __dns__; do
        if [ "$_ipx" = __dns__ ]; then _res=""; else _res="--resolve $GH_RAW_HOST:443:$_ipx"; fi
        _c=$(curl -s -o /dev/null -w '%{http_code}' $2 --connect-timeout 8 --max-time 12 $_res "$RAW/$1" 2>/dev/null)
        gh_code_note "$_c"
        case "$_c" in
            ''|000)  : ;;             # не соединились — пробуем следующий узел
            429|403) return 1 ;;      # лимит навешен на КЛИЕНТСКИЙ адрес ⇒ соседние узлы ответят тем же
            *)       return 0 ;;
        esac
    done
    return 1
}
# Печатает ПРИЧИНУ отказа в stdout (успех молчит): вызывающие — packages.sh/proto-install.sh —
# показывают её человеку вместо своего «GitHub недоступен», за которым он идёт чинить сеть.
gh_reachable() {
    _p="$1"
    gh_code_reset
    # ПРОБУЕМ ТОТ КАНАЛ, КОТОРЫМ ПОТОМ КАЧАЕМ — а качаем из папки `bin/` через raw (разбор
    # порядка в шапке файла). Значит первым спрашиваем raw, и только если он отшил ПО ЧАСТОТЕ —
    # второй канал: у ассетов другой хост и лимиты СВОИ. Обратный порядок стоил бы полного круга
    # на 404 при КАЖДОЙ проверке: ассетов в репозитории может не лежать вовсе, это норма.
    [ -n "$_p" ] || _p=VERSION
    gh_reach_round "$_p" "$(gh_ca_opt)" && return 0
    # Развилка. Ни второй круг (доверие TLS), ни третий (десинк) отказа ПО ЧАСТОТЕ не обойдут:
    # соединение состоялось, сертификат проверен, внешний адрес у десинка ТОТ ЖЕ. Поэтому при
    # 429/403 идём во второй канал, а круги доверия и десинка — только при ИНОМ отказе. Это не
    # осторожность, а экономия полуминуты на экране установки и честный текст вместо «недоступен».
    if gh_code_refused; then
        # Проба дешёвая: SHA256SUMS ассетом — 4 КБ, и это ровно тот путь (github.com → редирект).
        # Через gh_get, а не своим curl: у него перебор anycast-узлов и круг доверия — одиночный
        # запрос сел бы на молчащий узел и отчитался «канала нет».
        # Код raw ЗАПОМИНАЕМ и возвращаем при неудаче: иначе поверх «ограничил по частоте» ляжет
        # 404 от ненайденного ассета, и человек вместо «подождите 10-15 минут» прочтёт безликое
        # «GitHub недоступен» — то есть пойдёт чинить сеть.
        _ru=$(rel_flat_url "$SUMS_REL")
        if [ -n "$_ru" ]; then
            _rc=$(gh_code_get)
            _rt="/tmp/.gh-reach.$$"
            gh_get "$_ru" "$_rt"; _rr=$?
            rm -f "$_rt"
            [ "$_rr" = 0 ] && return 0
            gh_code_note "$_rc"
        fi
    else
        # рабочий бандл уже известен — значит дело не в доверии, но десинк попробовать ОБЯЗАНЫ
        if [ -z "$(gh_ca_opt)" ] && gh_ca_probe "$RAW/$_p"; then
            gh_reach_round "$_p" "$(gh_ca_opt)" && return 0
        fi
        # Аварийный канал спрашиваем и ЗДЕСЬ, а не только в закачке: `reachable` — это пре-чек, на
        # котором packages.sh/proto-install останавливаются ДО удаления и закачки. Отвечай он «нет»,
        # пока канал через десинк жив, — установка компонентов из панели была бы закрыта наглухо,
        # причём с формулировкой «GitHub недоступен», которая для человека означает «ждите».
        if gh_socks_try; then
            _c=$(curl -s -o /dev/null -w '%{http_code}' $(gh_ca_opt) --connect-timeout 8 --max-time 12 \
                 --socks5-hostname "$GH_SOCKS" "$RAW/$_p" 2>/dev/null)
            gh_code_note "$_c"
            case "$_c" in ''|000) : ;; 429|403) : ;; *) return 0 ;; esac
        fi
    fi
    _why=$(gh_code_reason "$(gh_code_get)")
    [ -n "$_why" ] || _why="GitHub недоступен — ни один канал не ответил"
    printf '%s\n' "$_why"
    return 1
}

# --- ELF-magic (7f 45 4c 46). printf '\177ELF' даёт ровно эти 4 байта. Без od/hexdump. ---
# Сверяем два РЕАЛЬНЫХ файла (не stdin '-' — busybox cmp с ним капризен). Если cmp нет
# или эталон не создать — НЕ блокируем (size-проверка в fetch_bin страхует от обрыва).
elf_ok() {
    f="$1"
    command -v cmp >/dev/null 2>&1 || return 0
    m="/tmp/.elfmagic.$$"; t="/tmp/.elfhead.$$"
    printf '\177ELF' > "$m" 2>/dev/null || { rm -f "$m" "$t"; return 0; }
    head -c 4 "$f" > "$t" 2>/dev/null
    cmp -s "$m" "$t"; rc=$?
    rm -f "$m" "$t"
    return $rc
}

# --- ЦЕЛОСТНОСТЬ СКАЧАННОГО: sha256 по SHA256SUMS из корня репо ----------------------
# ЗАЧЕМ: раньше единственной проверкой бинаря был порог minsize в fetch_bin — он ловит ОБРЫВ
# закачки, но НЕ подмену файла (публично признанная дыра в цепочке поставок; закрываем до
# того, как панель выходит наружу). Формат SHA256SUMS — coreutils: «<64hex>␠␠<репо-путь>»,
# т.е. на ПК/Linux его же читает `sha256sum -c SHA256SUMS`.
# ЧЕСТНАЯ ГРАНИЦА (так и написано в README): файл сумм приезжает ТЕМ ЖЕ каналом
# (raw.githubusercontent) ⇒ это защита от подмены/порчи ОТДЕЛЬНОГО ФАЙЛА, а не подпись и не
# защита канала. Отсюда политика деградации:
#   * суммы скачались → строка ОБЯЗАНА быть и совпасть (нет строки = так выглядит вырезанная
#     запись, значит отказ);
#   * SHA256SUMS в репо нет вовсе (старый публичный снимок) → громкое предупреждение и идём
#     дальше, иначе новый апдейтер закирпичил бы обновление со старого тега;
#   * `$ENODIA_STATE/.gh-strict` = «без сумм не обновляться и не качать бинари вовсе».
# ЧЕМ СЧИТАЕМ: `sha256sum` на стоке Xiaomi НЕТ (busybox несёт только md5sum — замер на BE7000
# 30.07.2026), считает стоковый openssl 1.1.1l, который уже вендорится ради notify.sh/panel-tls/
# totp.sh. Цена незаметна: 8-МБ xray хешируется меньше секунды.
SUMS_REL=SHA256SUMS
SUMS_CACHE=/tmp/.gh-sums.$$
SUMS_STATE=            # ''=ещё не пробовали · ok=скачали · no=в репо нет
GH_VERIFY_FATAL=0      # 1 = хеш не совпал: ОСТАЛЬНЫЕ пути качать нельзя (это не «файл не подошёл»)

gh_strict() { [ -f "$ENODIA_STATE/.gh-strict" ]; }

# sha256 файла (64 hex) или пусто, если считать нечем. `openssl dgst` печатает «SHA256(f)= hex»
# — тот же разбор, что в totp.sh (одна идиома на проект).
file_sha256() {
    _fh=""
    if command -v sha256sum >/dev/null 2>&1; then _fh=$(sha256sum "$1" 2>/dev/null | awk '{print $1; exit}'); fi
    if [ "${#_fh}" != 64 ]; then _fh=$(openssl dgst -sha256 "$1" 2>/dev/null | sed 's/.*= *//' | awk '{print $1; exit}'); fi
    case "$_fh" in *[!0-9a-f]*) _fh="" ;; esac
    [ "${#_fh}" = 64 ] || _fh=""
    printf '%s\n' "$_fh"
}

# Скачать SHA256SUMS ОДИН раз на процесс. Всегда 0 — вердикт живёт в $SUMS_STATE.
# Канонический источник сумм — репо (оттуда же едет код), ассет релиза — РЕЗЕРВ. Без резерва
# мёртвый raw означал бы «бинарь по второму каналу скачали, а проверить нечем» — то есть
# установку без сверки ровно в той аварии, ради которой второй канал и заведён.
sums_load() {
    [ -z "$SUMS_STATE" ] || return 0
    SUMS_STATE=no
    for _su in "$RAW/$SUMS_REL" "$(rel_flat_url "$SUMS_REL")"; do
        [ -n "$_su" ] || continue
        if gh_get "$_su" "$SUMS_CACHE" && [ -s "$SUMS_CACHE" ]; then SUMS_STATE=ok; return 0; fi
        rm -f "$SUMS_CACHE"
    done
    return 0
}

# Ожидаемый хеш репо-пути. Терпим обе формы второго поля: «путь» и «*путь» (openssl -r).
sums_expect() {
    [ "$SUMS_STATE" = ok ] || return 0
    awk -v p="$1" '{ f=$2; sub(/^\*/, "", f); if (f == p && length($1) == 64) { print $1; exit } }' "$SUMS_CACHE" 2>/dev/null
}

# verify_file <локальный файл> <репо-путь>: 0 = ставить можно, 1 = НЕ ставить.
verify_file() {
    _vf="$1"; _vr="$2"
    sums_load
    if [ "$SUMS_STATE" != ok ]; then
        if gh_strict; then log "[verify] ОТКАЗ: в репо ($GH_REF) нет $SUMS_REL, а включён строгий режим (.gh-strict)"; return 1; fi
        log "[verify] ВНИМАНИЕ: в репо ($GH_REF) нет $SUMS_REL — целостность «$_vr» НЕ проверена"
        return 0
    fi
    _ve=$(sums_expect "$_vr")
    if [ -z "$_ve" ]; then
        log "[verify] ОТКАЗ: «$_vr» нет в $SUMS_REL (сам файл сумм есть, а строки нет — так выглядит вырезанная запись)"
        GH_VERIFY_FATAL=1; return 1
    fi
    _vg=$(file_sha256 "$_vf")
    if [ -z "$_vg" ]; then
        if gh_strict; then log "[verify] ОТКАЗ: нечем посчитать sha256 (нет openssl/sha256sum), строгий режим"; return 1; fi
        log "[verify] ВНИМАНИЕ: нечем посчитать sha256 (нет openssl/sha256sum) — целостность «$_vr» не проверена"
        return 0
    fi
    if [ "$_vg" != "$_ve" ]; then
        log "[verify] ОТКАЗ: «$_vr» не совпал с $SUMS_REL"
        log "[verify]   ожидали $_ve"
        log "[verify]   получили $_vg"
        GH_VERIFY_FATAL=1; return 1
    fi
    return 0
}

# --- Скачать один файл репо (rel) в dest атомарно + сверить хеш. Код 0/1. ---------
dl() {
    rel="$1"; dst="$2"
    gh_get "$RAW/$rel" "$dst.dl" || { rm -f "$dst.dl"; return 1; }
    [ -s "$dst.dl" ] || { rm -f "$dst.dl"; return 1; }
    verify_file "$dst.dl" "$rel" || { rm -f "$dst.dl"; return 1; }
    mv "$dst.dl" "$dst"
}

# То же, но с резервным каналом «ассет релиза» — ТОЛЬКО для файлов, которые там и лежат
# (bin-manifest.txt). Скрипты по манифесту через него не качаем: их в релизе нет, и лишняя
# попытка была бы гарантированным 404 на каждый файл.
dl_any() {
    dl "$1" "$2" && return 0
    _da=$(rel_flat_url "$1"); [ -n "$_da" ] || return 1
    gh_get "$_da" "$2.dl" || { rm -f "$2.dl"; return 1; }
    [ -s "$2.dl" ] || { rm -f "$2.dl"; return 1; }
    verify_file "$2.dl" "$1" || { rm -f "$2.dl"; return 1; }
    mv "$2.dl" "$2"
}

# --- Арка роутера для выбора набора bin/<арка>/ на GitHub. --------------------------
# Бинари в репозитории разложены по аркам (bin/arm64/, bin/armv7/) — качать надо СВОЙ
# набор, иначе ENOEXEC и busybox печатает «syntax error» вместо версии (BE3600, лог
# тестера 2026-07-15). Опознаём по e_machine (байты 18-19 ELF) заведомо рабочего
# /bin/busybox, а НЕ по `uname -m`: при 64-битном ядре с 32-битным userspace uname
# говорит aarch64, но исполнять придётся armv7. Тот же критерий, что у гарда
# bin_arch_matches в install.sh. `od` в busybox НЕТ (грабля) → dd + cmp с
# эталоном из printf. Не опознали → пусто, fetch_bin уйдёт на легаси-путь (fail-open).
bin_arch() {
    [ -r /bin/busybox ] || return 0
    command -v dd >/dev/null 2>&1 || return 0
    command -v cmp >/dev/null 2>&1 || return 0
    _m=/tmp/.gh-arch.$$
    dd if=/bin/busybox of="$_m" bs=1 skip=18 count=2 2>/dev/null || { rm -f "$_m"; return 0; }
    printf '\267\000' > "$_m.a64" 2>/dev/null   # 0xB7 0x00 = EM_AARCH64
    printf '\050\000' > "$_m.a32" 2>/dev/null   # 0x28 0x00 = EM_ARM
    _r=""
    if cmp -s "$_m" "$_m.a64"; then _r=arm64
    elif cmp -s "$_m" "$_m.a32"; then _r=armv7
    fi
    rm -f "$_m" "$_m.a64" "$_m.a32"
    echo "$_r"
}

# --- МАНИФЕСТ БИНАРЕЙ: сколько займёт и какая это версия — ДО закачки ---------------
# ЗАЧЕМ: «размер» и «версия» бинаря не были известны роутеру НИОТКУДА. Размеры жили хардкодом
# (need=$((need+8)) в proto-install, minsize в восьми вызовах fetch-bin) и врали при каждой
# пересборке, а версию нельзя было даже показать: UPX-сжатый бинарь её не отдаёт (`go version -m`
# на паке не работает, у amneziawg-go к тому же const Version не меняется между тегами). Панель
# à la carte обязана сказать «Hysteria2 v2.10.0, 4.55 МБ, после установки останется 0.5 МБ» ПЕРЕД
# тем, как что-то качать — отсюда bin-manifest.txt в корне репо (генерит local/build-bin-manifest.ps1).
# Формат — TSV «имя⇥арка⇥байты⇥версия», качается как обычный файл репо ⇒ сверяется по SHA256SUMS
# наравне со скриптами (подменённый манифест иначе подсунул бы заниженный minsize).
# Кэш на ФЛЕШЕ, а не в /tmp: панель рисует список компонентов и в офлайне, а он ~1 КБ.
BM_REL=bin-manifest.txt
BM_CACHE="$ENODIA_STATE/.bin-manifest"
BM_MISS=/tmp/.bin-manifest.miss   # «в этом репо манифеста нет» — до ребута или явного refresh

# bm_ensure [refresh] — положить манифест в кэш. Всегда 0: нет манифеста (старый публичный
# снимок, нет сети) — не повод ронять закачку, ниже есть фолбэк-пороги.
# МАРКЕР ПРОМАХА обязателен: bin-size вызывают ОТДЕЛЬНЫМИ процессами (proto-install спрашивает
# по бинарю), и без него каждый вопрос платил бы полный anycast-перебор впустую — гард места
# растянулся бы на минуту там, где ответа всё равно не будет. Маркер в /tmp ⇒ ребут и явный
# `bin-manifest refresh` (панель, proto-install после проверки сети) его снимают.
#
# КЭШ СТАРШЕ СУТОК ОБНОВЛЯЕМ САМИ (найдено обходом панели 15.08.2026). Раньше `refresh` звали
# ровно два места — `packages.sh` и `proto-install.sh`, и ОБА уже В МОМЕНТ УСТАНОВКИ. Значит на
# роутере, где ничего не доставляли, кэш не обновлялся НИКОГДА: на AX3600 экран «Компоненты»
# показывал AmneziaWG v3.0.20260805 и byedpi 288.8 КБ, когда в репозитории лежали v3.1.20260814
# и 135.1 КБ. Врал не только текст — на тех же числах считается ГАРД МЕСТА на 20-МБ флеше.
# ЧИТАЮЩИЙ ПУТЬ СЕТИ НЕ КАСАЕТСЯ — СОЗНАТЕЛЬНО, и это цена, а не лень. Экран «Компоненты»
# считается СИНХРОННО в CGI, а один круг закачки на ЗАБЛЭКХОЛЕННОМ канале стоит до
# 5×`--connect-timeout 8` (четыре anycast-IP + имя), да ещё и второй круг по доверию — то есть
# человек с оборванным WAN смотрел бы на висящий экран до минуты ради КОСМЕТИКИ (версия рядом с
# компонентом). Поэтому свежесть добираем там, где в сеть идут ПО КНОПКЕ и ответа и так ждут:
# `cmd_check` («Проверить обновления») и `cmd_apply_scripts` — см. вызовы `bm_ensure refresh` ниже.
bm_ensure() {
    if [ "$1" = refresh ]; then
        rm -f "$BM_MISS"
    else
        [ -s "$BM_CACHE" ] && return 0
        [ -f "$BM_MISS" ] && return 0
    fi
    if dl_any "$BM_REL" "$BM_CACHE.new" && [ -s "$BM_CACHE.new" ]; then
        mv "$BM_CACHE.new" "$BM_CACHE"
    else
        rm -f "$BM_CACHE.new"
        if [ -s "$BM_CACHE" ]; then
            log "[bin-manifest] не обновился (сеть/целостность) — использую прежний кэш"
        else
            touch "$BM_MISS" 2>/dev/null
            log "[bin-manifest] нет $BM_REL в репо ($GH_REF) — размеры/версии неизвестны"
        fi
    fi
    return 0
}

# bm_field <имя> <3=байты|4=версия> [min|max] — поле из кэша для СВОЕЙ арки.
# Арку опознать не вышло (fail-open bin_arch) → берём крайнее значение по всем аркам, и какое
# именно — зависит от вопроса: «сколько займёт» = MAX (гард места должен ошибаться в запас),
# «порог обрыва закачки» = MIN (иначе 563-КБ armv7-сборка https-dns-proxy забракует законные
# 21 КБ arm64). Одна функция, режим параметром — двух копий разбора не заводим.
bm_field() {
    [ -s "$BM_CACHE" ] || return 0
    _bf_a=$(bin_arch)
    awk -F'\t' -v n="$1" -v c="$2" -v a="$_bf_a" -v m="${3:-max}" '
        $1 != n { next }
        a != "" && $2 == a { print $c; found=1; exit }
        a == "" { s=$3+0
                  if (best=="" || (m=="max" && s>best) || (m=="min" && s<best)) { best=s; val=$c } }
        END { if (!found && best!="") print val }
    ' "$BM_CACHE"
}

# Публичные хелперы (их же зовут proto-install.sh и панель через вербы bin-size/bin-ver).
# `bm_ensure >&2` ОБЯЗАТЕЛЕН: log() в этом скрипте пишет в stdout (его вывод целиком уходит в
# лог закачки), а тут stdout — это ЗНАЧЕНИЕ, которое вызывающий подставляет в $(...). Без
# развода потоков «размер» приезжал как «[bin-manifest] нет … \n 0».
bin_size() { bm_ensure >&2; _bs=$(bm_field "$1" 3 "${2:-max}"); case "$_bs" in ''|*[!0-9]*) _bs=0 ;; esac; echo "$_bs"; }
bin_ver()  { bm_ensure >&2; bm_field "$1" 4 max; }

# Порог «обрыв закачки» на случай, когда манифеста нет вовсе (старый публичный снимок). Раньше
# эти числа стояли в КАЖДОМ вызове fetch-bin у вызывающих — пережал UPX и надо было править
# восемь мест. Теперь одно, и оно фолбэк, а не основной путь.
bin_minsize_fallback() {
    case "$1" in
        amneziawg-go)  echo 500000 ;;
        xray|hysteria) echo 1000000 ;;
        hev)           echo 60000 ;;
        awg)           echo 50000 ;;
        byedpi|nfqws)  echo 30000 ;;
        https-dns-proxy|dot-proxy|panel-tls) echo 10000 ;;
        *)             echo 100000 ;;
    esac
}

# --- Скачать бинарь bin/<арка>/<name>.user в dst (рабочее имя без .user) с проверкой.
#     fetch-bin <name> <dst> [minsize]. Используется proto-install.sh.
#     minsize можно НЕ передавать: возьмём 90% размера из манифеста (10% — запас на пересборку,
#     точную сверку всё равно делает sha256), а без манифеста — фолбэк-таблицу выше.
#     Порядок путей: сначала свой набор bin/<арка>/, затем ЛЕГАСИ плоский bin/<name>.user
#     (он оставлен в публичном репо ради старых установок и снимков без подпапок).
fetch_bin() {
    name="$1"; dst="$2"; minsz="$3"
    case "$minsz" in ''|*[!0-9]*|0) minsz="" ;; esac
    if [ -z "$minsz" ]; then
        _ms=$(bin_size "$name" min)
        if [ "${_ms:-0}" -gt 0 ]; then minsz=$(( _ms * 9 / 10 )); else minsz=$(bin_minsize_fallback "$name"); fi
    fi
    _arch=$(bin_arch)
    if [ -n "$_arch" ]; then
        _try="bin/$_arch/$name.user bin/$name.user"
    else
        log "[fetch-bin] арку роутера опознать не вышло — беру легаси-путь bin/$name.user"
        _try="bin/$name.user"
    fi
    for _rel in $_try; do
        # ДВА КАНАЛА на один и тот же путь: raw из папки `bin/` (основной) и ассет релиза
        # (резерв, может отсутствовать вовсе). Ключ целостности у обоих ОДИН — `$_rel`, путь
        # по репо: в `SHA256SUMS` перечислен он. Разбор порядка — в шапке файла.
        _bref=0
        for _bsrc in "$RAW/$_rel" $(bin_asset_url "$_rel"); do
            if fetch_bin_one "$_bsrc" "$_rel" "$name" "$dst" "$minsz"; then return 0; fi
            # Несовпадение хеша — НЕ «канал не подошёл»: прочие пути в этом случае не пробуем,
            # иначе проверка обходится сама собой (подменил bin/<арка>/ → поставили из bin/).
            [ "$GH_VERIFY_FATAL" = 0 ] || { log "[fetch-bin] $name: остановился на проверке целостности — другие пути НЕ пробую"; return 1; }
            gh_code_refused && _bref=1
        done
        # Отказ ПО ЧАСТОТЕ (429/403) хотя бы от одного канала — легаси-путь лежит на тех же
        # хостах и ответит тем же кодом, только добьёт лимит ⇒ не пробуем. Судим по ЛЮБОМУ
        # каналу, а не по последнему: последний может ответить 404 (ассет не залит), и тогда
        # «нас отшили» потерялось бы, а мы пошли бы долбиться в уже лимитированный raw.
        [ "$_bref" = 1 ] && return 1
        log "[fetch-bin] $name: $_rel не подошёл — пробую следующий путь"
    done
    return 1
}

# --- Путь по репо → URL ассета релиза. Пусто = ассета для него не бывает. ------------
# Пусто отдаём в двух случаях: путь не вида `bin/<арка>/<файл>` (в релизе лежат только бинари)
# ИЛИ источник пришпилен к своему тегу через `.gh-ref` — там бинари обязаны ехать ИЗ ЭТОГО
# СНИМКА, а тег `bin` несёт всегда свежие, и подменять одно другим нельзя.
bin_asset_url() {
    case "$1" in
        bin/*/*) _ba=${1#bin/}; _bn=${_ba#*/}; _ba=${_ba%%/*}; rel_flat_url "$_ba-$_bn" ;;
        *) : ;;
    esac
}
# URL ассета по ПЛОСКОМУ имени — для того, что лежит в релизе рядом с бинарями (SHA256SUMS,
# bin-manifest.txt). Пусто при пришпиленном `.gh-ref`: тег `bin` несёт всегда свежее, и
# подсовывать его снимку под чужим тегом нельзя.
rel_flat_url() { [ "$GH_REF" = main ] || return 0; echo "$GH_REL/$1"; }

# --- Одна попытка закачки конкретного пути. Возвращает 0 только при рабочем бинаре. --
fetch_bin_one() {
    url="$1"; rel="$2"; name="$3"; dst="$4"; minsz="$5"
    log "[fetch-bin] $name <- $url"
    # Закачка В ФОНЕ (gh_get перебирает anycast-IP) + опрос размера .dl → прогресс/скорость в лог
    # (его опрашивает панель, показывая последнюю строку). Без HEAD за Content-Length (лишний
    # connect-цикл) — печатаем скачанные КБ и среднюю скорость. Быстрая закачка (<2с) проскочит
    # цикл без строк прогресса — норма. Мёртвый IP даст «0 КБ» на ≤8с, затем gh_get берёт живой.
    t0=$(date +%s)
    gh_code_reset          # чтобы ответ прошлого канала не выдали за причину этого
    gh_get "$url" "$dst.dl" &
    cpid=$!
    while kill -0 "$cpid" 2>/dev/null; do
        sleep 2
        cur=$(stat -c%s "$dst.dl" 2>/dev/null || echo 0); case "$cur" in ''|*[!0-9]*) cur=0;; esac
        # clock-raw: не возраст отметки, а длительность ВНУТРИ одного прогона (t0 взят строкой выше) —
    # клампу по аптайму тут нечего делать.
    el=$(( $(date +%s) - t0 )); [ "$el" -gt 0 ] || el=1
        log "[fetch-bin] $name: $((cur/1024)) КБ ($((cur/1024/el)) КБ/с)"
    done
    wait "$cpid" 2>/dev/null; rc=$?
    # ПРИЧИНУ НАЗЫВАЕМ, а не гадаем. «(сеть/нет места?)» стояло тут годом раньше и оба раза мимо:
    # на 429 сеть в порядке и места вдоволь, а человек по такой строке идёт чинить не то.
    if [ "$rc" != 0 ]; then
        rm -f "$dst.dl"
        _why=$(gh_code_reason "$(gh_code_get)")
        [ -n "$_why" ] || _why="нет связи с GitHub (или кончилось место)"
        log "[fetch-bin] FAIL: не скачался $name — $_why"
        return 1
    fi
    sz=$(stat -c%s "$dst.dl" 2>/dev/null || echo 0)
    if [ "${sz:-0}" -lt "$minsz" ]; then rm -f "$dst.dl"; log "[fetch-bin] FAIL: $name мал ($sz < $minsz) — обрыв закачки"; return 1; fi
    if ! elf_ok "$dst.dl"; then rm -f "$dst.dl"; log "[fetch-bin] FAIL: $name не ELF (не бинарь)"; return 1; fi
    # sha256 ПОСЛЕ размера/ELF (дешёвые отсевы первыми) и ДО chmod+mv — не пускаем на диск
    # исполняемым то, чего нет в SHA256SUMS.
    if ! verify_file "$dst.dl" "$rel"; then rm -f "$dst.dl"; log "[fetch-bin] FAIL: $name не прошёл проверку целостности ($rel)"; return 1; fi
    chmod +x "$dst.dl"
    mv "$dst.dl" "$dst" || { rm -f "$dst.dl"; log "[fetch-bin] FAIL: не смог поставить $name"; return 1; }
    # Исполняемость судим ПО ФАКТУ, а не по тому, что chmod отработал: с появлением внешнего
    # накопителя $dst бывает на exFAT/NTFS, где права задаёт МОНТИРОВАНИЕ (fmask), а chmod молча
    # не делает ничего. Файл, легший без +x, — это связка, которая навсегда осталась «не
    # установлена» после успешной закачки, без единой причины на экране. Лучше явный отказ.
    if [ ! -x "$dst" ]; then
        chmod +x "$dst" 2>/dev/null
        [ -x "$dst" ] || { rm -f "$dst"; log "[fetch-bin] FAIL: $name лёг без права на исполнение ($dst) — накопитель смонтирован без exec?"; return 1; }
    fi
    log "[fetch-bin] OK: $name ($sz байт) -> $dst"
}

# --- Версии. CODE — целое для busybox-сравнения; VERSION — человекочитаемое имя. ----
local_code() { c=$(sed -n 's/^CODE=//p' "$ENODIA_DIR/VERSION" 2>/dev/null | head -1 | tr -d ' \r'); case "$c" in ''|*[!0-9]*) echo 0;; *) echo "$c";; esac; }
local_name() { sed -n 's/^VERSION=//p' "$ENODIA_DIR/VERSION" 2>/dev/null | head -1 | tr -d ' \r"\\'; }
# ЧЕРЕЗ gh_get, а не голым curl: у raw.githubusercontent часть anycast-узлов через VPS «мёртвая»
# (connect проходит, данные не идут) — одиночная попытка садилась на такой узел лотереей, и
# панель показывала «на GitHub VERSION не найден → обновление не предлагается» на ровном месте.
remote_version_raw() {
    _vt=/tmp/.gh-ver.$$
    gh_get "$RAW/VERSION" "$_vt" && cat "$_vt" 2>/dev/null
    rm -f "$_vt" 2>/dev/null
}

cmd_check() {
    lc=$(local_code); ln=$(local_name); [ -n "$ln" ] || ln="?"
    rv=$(remote_version_raw)
    # Вердикт GitHub снимаем ЗДЕСЬ: `bm_ensure` ниже делает СВОЙ запрос и перетрёт отметку.
    _ghc=$(gh_code_get)
    # ЗАОДНО ОБНОВЛЯЕМ КЭШ МАНИФЕСТА БИНАРЕЙ. Найдено обходом панели 15.08.2026: `refresh` звали
    # ровно два места — packages.sh и proto-install.sh, и ОБА уже В МОМЕНТ УСТАНОВКИ. На роутере,
    # где ничего не доставляли, кэш не обновлялся НИКОГДА: AX3600 рисовал «AmneziaWG v3.0.20260805»,
    # когда в репозитории лежала v3.1.20260814. Врал не только текст рядом с компонентом — на тех же
    # числах считается ГАРД МЕСТА на 20-МБ флеше и порог обрыва закачки.
    # Место выбрано за цену: мы УЖЕ сходили в сеть за VERSION, человек нажал кнопку и ждёт ответа,
    # а сам манифест — 1.4 КБ (замер на AX3600: полный refresh 1 с). Провал ничего не ломает:
    # bm_ensure оставляет прежний кэш и молчит в stderr.
    bm_ensure refresh >/dev/null 2>&1 || true
    rc=$(printf '%s' "$rv" | sed -n 's/^CODE=//p' | head -1 | tr -d ' \r')
    rn=$(printf '%s' "$rv" | sed -n 's/^VERSION=//p' | head -1 | tr -d ' \r"\\')
    case "$rc" in ''|*[!0-9]*) rc="" ;; esac
    if [ -z "$rc" ]; then
        # «VERSION не найден» — ШТАТНЫЙ ответ (в публичный репо он не публикуется), поэтому под
        # ним пряталось бы и «GitHub нас сейчас не обслуживает». Отказ по частоте называем прямо:
        # иначе человек читает «обновления нет» там, где на деле «канал закрыт, подождите».
        case "$_ghc" in
            429|403) log "локально: $ln (код $lc); $(gh_code_reason "$_ghc")"; return 0 ;;
        esac
        log "локально: $ln (код $lc); на GitHub: VERSION не найден ($GH_REF) → обновление НЕ предлагается"
        return 0
    fi
    if [ "$rc" -gt "$lc" ]; then
        log "локально: $ln (код $lc); на GitHub: $rn (код $rc) → ЕСТЬ ОБНОВЛЕНИЕ"
    else
        log "локально: $ln (код $lc); на GitHub: $rn (код $rc) → у тебя актуальная версия"
    fi
}

# --- Обновление скриптов по манифесту (update-manifest.txt в репо). ---------------
# Манифест = по одному репо-относительному пути в строке (# — коммент). Берём ТОЛЬКО
# безопасные к замене: *.sh / *.conf.example / VERSION / update-manifest.txt / hev.yaml
# / web/*. Секреты (awg.conf, configs/, *.json, *.yaml кроме hev.yaml, notify.conf) —
# НЕ трогаем (в манифест их не кладём, плюс гард ниже).
manifest_safe() {
    case "$1" in
        */../*|/*|*..*) return 1 ;;                              # path-traversal/абсолют
        awg.conf|notify.conf|xray.json|hysteria.yaml) return 1 ;;
        configs/*|xray-configs/*|hy2-configs/*) return 1 ;;
        # Каталоги гео (geo-v2fly/rfip/rfgs-catalog.txt) — данные, не код: список ключей
        # категорий, из которого панель строит поиск. Они ЕСТЬ в манифесте с 19.07, но под
        # прежний набор масок не подходили ⇒ apply-scripts молча их пропускал, и у тестеров
        # каталог оставался тем, что приехал с установкой. Маска УЗКАЯ (`geo-*-catalog.txt`),
        # а не `*.txt`: это фильтр безопасности, и широкая маска впустила бы сюда что угодно.
        *.sh|*.conf.example|VERSION|update-manifest.txt|hev.yaml|web/*) return 0 ;;
        geo-*-catalog.txt) return 0 ;;
        *) return 1 ;;
    esac
}

cmd_apply_scripts() {
    force="$1"
    lc=$(local_code)
    # VERSION и манифест качаем В ФАЙЛ и сверяем хеш: первый решает «обновляться ли вообще»
    # (downgrade-guard), второй — «какие файлы взять». Подмена любого из двух обходит всю
    # остальную проверку, поэтому они в SHA256SUMS наравне со скриптами.
    ver_tmp=/tmp/.gh-version.$$
    if ! gh_get "$RAW/VERSION" "$ver_tmp" || [ ! -s "$ver_tmp" ]; then
        rm -f "$ver_tmp"; log "[apply] на GitHub нет VERSION ($GH_REF) — обновление отменено"; return 1
    fi
    if ! verify_file "$ver_tmp" VERSION; then rm -f "$ver_tmp"; log "[apply] VERSION не прошёл проверку целостности — обновление отменено"; return 1; fi
    rc=$(sed -n 's/^CODE=//p' "$ver_tmp" | head -1 | tr -d ' \r'); case "$rc" in ''|*[!0-9]*) rc=0;; esac
    rm -f "$ver_tmp"
    if [ "$rc" = 0 ]; then log "[apply] на GitHub нет VERSION ($GH_REF) — обновление отменено"; return 1; fi
    if [ "$force" != "--force" ] && [ "$rc" -le "$lc" ]; then
        log "[apply] на GitHub код $rc <= локального $lc — это даунгрейд, отмена (--force чтобы всё равно)"; return 1
    fi
    man_tmp=/tmp/.gh-manifest-raw.$$
    if ! gh_get "$RAW/update-manifest.txt" "$man_tmp" || [ ! -s "$man_tmp" ]; then
        rm -f "$man_tmp"; log "[apply] нет update-manifest.txt в репо ($GH_REF) — нечего обновлять"; return 1
    fi
    if ! verify_file "$man_tmp" update-manifest.txt; then rm -f "$man_tmp"; log "[apply] манифест не прошёл проверку целостности — обновление отменено"; return 1; fi
    # Ротация СНАЧАЛА (освобождает место), потом гард свободного, потом уже пишем.
    backup_rotate $((BACKUP_KEEP - 1))
    _free=$(df -k "$ENODIA_DIR" 2>/dev/null | awk 'NR==2{print $4+0}')
    case "$_free" in ''|*[!0-9]*) _free="" ;; esac
    if [ -n "$_free" ] && [ "$_free" -lt "$GH_MINFREE_KB" ]; then
        rm -f "$man_tmp"
        log "[apply] на /data свободно ${_free} КБ (нужно ≥ ${GH_MINFREE_KB}) — обновление отменено"
        log "[apply] освободить место: панель → «Компоненты» → очистка (там же лежат старые бэкапы)"
        return 1
    fi
    ts=$(date +%Y%m%d-%H%M%S); bdir="$BACKUP_ROOT/$ts"; mkdir -p "$bdir"
    nok=0; nfail=0
    tr -d '\r' < "$man_tmp" > /tmp/.gh-manifest.$$; rm -f "$man_tmp"
    # `|| [ -n "$rel" ]`: манифест без хвостового \n иначе терял бы ПОСЛЕДНЮЮ строку (busybox
    # read возвращает 1 на EOF, уже прочитав её) — а последними в манифесте идут CGI панели.
    while IFS= read -r rel || [ -n "$rel" ]; do
        # Обрезаем ТОЛЬКО края: `tr -d ' '` резал пробелы и ВНУТРИ строки, то есть путь с
        # пробелом молча превращался в ДРУГОЙ путь (а манифест правит человек руками).
        rel=$(printf '%s' "$rel" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//'); [ -n "$rel" ] || continue
        case "$rel" in \#*) continue ;; esac
        if ! manifest_safe "$rel"; then log "[apply] пропуск (не в whitelist): $rel"; continue; fi
        dst="$ENODIA_DIR/$rel"
        # бэкап текущего (если есть)
        if [ -f "$dst" ]; then mkdir -p "$bdir/$(dirname "$rel")" 2>/dev/null; cp "$dst" "$bdir/$rel" 2>/dev/null; fi
        mkdir -p "$(dirname "$dst")" 2>/dev/null
        if ! gh_get "$RAW/$rel" "$dst.new"; then
            rm -f "$dst.new"; log "[apply] FAIL скачивание: $rel"; nfail=$((nfail+1)); continue
        fi
        [ -s "$dst.new" ] || { rm -f "$dst.new"; log "[apply] FAIL пусто: $rel"; nfail=$((nfail+1)); continue; }
        if ! verify_file "$dst.new" "$rel"; then
            rm -f "$dst.new"; nfail=$((nfail+1))
            # Несовпадение хеша — НЕ «этот файл не подошёл», а «каналу больше нельзя верить».
            # Продолжать = разложить на роутере СМЕШАННЫЙ набор версий (ровно тот дрейф деплоя,
            # который ловится хуже всего), поэтому останавливаемся — как fetch_bin с путями.
            if [ "$GH_VERIFY_FATAL" != 0 ]; then
                log "[apply] СТОП: «$rel» разошёлся с $SUMS_REL — остальные файлы НЕ обновляю"
                break
            fi
            log "[apply] FAIL целостность: $rel (старый файл оставлен)"; continue
        fi
        # Синтаксис проверяем у ВСЕГО, чему ставим +x: CGI панели — такие же sh-скрипты, просто
        # без расширения, и битый `action`/`status` = мёртвая панель без единой причины на экране.
        case "$rel" in *.sh|web/cgi-bin/*|web/htmlwrap) sh -n "$dst.new" 2>/dev/null || { rm -f "$dst.new"; log "[apply] FAIL синтаксис: $rel"; nfail=$((nfail+1)); continue; } ;; esac
        mv "$dst.new" "$dst" && { case "$rel" in *.sh) chmod +x "$dst" ;; web/cgi-bin/*|web/htmlwrap) chmod +x "$dst" ;; esac; log "[apply] OK: $rel"; nok=$((nok+1)); } \
            || { rm -f "$dst.new"; log "[apply] FAIL запись: $rel"; nfail=$((nfail+1)); }
    done < /tmp/.gh-manifest.$$
    rm -f /tmp/.gh-manifest.$$
    log "[apply] готово: обновлено $nok, ошибок $nfail. Бэкап: $bdir"
    if [ "$nfail" = 0 ]; then
        # Версия сменилась ⇒ мог смениться и набор бинарей (их версии/размеры живут в
        # bin-manifest.txt отдельным кэшем и по apply-scripts НЕ едут: файла нет в манифесте
        # обновляемых). Мы прямо сейчас онлайн и уже всё скачали — момент самый дешёвый.
        bm_ensure refresh >/dev/null 2>&1 || true
        log "[apply] применить правила: vpn-toggle.sh repair (или ребут)"
    else
        log "[apply] ВНИМАНИЕ: набор файлов теперь СМЕШАННЫЙ (часть новая, часть старая) — либо повторите обновление, либо откатитесь: gh-update.sh rollback"
    fi
    [ "$nfail" = 0 ]
}

# backup_rotate <сколько оставить> — снять самые старые снимки бэкапа.
backup_rotate() {
    _keep="$1"; case "$_keep" in ''|*[!0-9]*) _keep=$BACKUP_KEEP ;; esac
    [ -d "$BACKUP_ROOT" ] || return 0
    _cnt=$(ls -1 "$BACKUP_ROOT" 2>/dev/null | wc -l); case "$_cnt" in ''|*[!0-9]*) _cnt=0 ;; esac
    [ "$_cnt" -gt "$_keep" ] || return 0
    ls -1 "$BACKUP_ROOT" 2>/dev/null | sort | head -n $((_cnt - _keep)) > /tmp/.gh-rot.$$
    while IFS= read -r _old || [ -n "$_old" ]; do
        [ -n "$_old" ] || continue
        rm -rf "${BACKUP_ROOT:?}/$_old" 2>/dev/null
        log "[apply] снят старый бэкап: $_old"
    done < /tmp/.gh-rot.$$
    rm -f /tmp/.gh-rot.$$
    return 0
}

cmd_rollback() {
    last=$(ls -1 "$BACKUP_ROOT" 2>/dev/null | sort | tail -1)
    [ -n "$last" ] || { log "[rollback] нет бэкапов в $BACKUP_ROOT"; return 1; }
    bdir="$BACKUP_ROOT/$last"; n=0; nf=0
    [ -d "$bdir" ] || { log "[rollback] не открыть $bdir"; return 1; }
    # Список — В ФАЙЛ, а не в пайп: счётчики в `find | while` считались бы в подоболочке и
    # наружу не выходили (итог отката был бы неизвестен ни человеку, ни коду возврата).
    find "$bdir" -type f 2>/dev/null > /tmp/.gh-rb.$$
    while IFS= read -r f || [ -n "$f" ]; do
        [ -n "$f" ] || continue
        rel=${f#"$bdir/"}
        [ -n "$rel" ] && [ "$rel" != "$f" ] || continue
        mkdir -p "$ENODIA_DIR/$(dirname "$rel")" 2>/dev/null
        if cp "$f" "$ENODIA_DIR/$rel" 2>/dev/null; then
            case "$rel" in *.sh|web/cgi-bin/*|web/htmlwrap) chmod +x "$ENODIA_DIR/$rel" ;; esac
            n=$((n+1))
        else
            log "[rollback] НЕ вернулся: $rel"; nf=$((nf+1))
        fi
    done < /tmp/.gh-rb.$$
    rm -f /tmp/.gh-rb.$$
    log "[rollback] возвращено $n, ошибок $nf (снимок $last)"
    log "[rollback] применить: vpn-toggle.sh repair (или ребут)."
    [ "$nf" = 0 ] && [ "$n" -gt 0 ]
}

# --- Обновить сам gh-update.sh (вызывать ПЕРЕД apply-scripts, чтобы логика была свежей). -
cmd_self() {
    tmp="$ENODIA_DIR/gh-update.sh"
    if dl gh-update.sh "$tmp.upd"; then
        sh -n "$tmp.upd" 2>/dev/null || { rm -f "$tmp.upd"; log "[self] новый gh-update.sh не парсится — оставляю старый"; return 1; }
        chmod +x "$tmp.upd"; mv "$tmp.upd" "$tmp"; log "[self] gh-update.sh обновлён"
    else
        log "[self] не скачал gh-update.sh (сеть или проверка целостности) — оставляю текущий"; return 1
    fi
}

# --- АУДИТ: что из установленного расходится с SHA256SUMS в репо (только ЧТЕНИЕ). ------
# Зачем отдельный верб: ровно этот вопрос раньше закрывался ручным md5-аудитом манифеста —
# «на роутере лежит файл не той версии» (дрейф деплоя ловится глазами очень плохо). Дев-сборка
# заведомо новее публичного снимка ⇒ расхождения здесь НОРМА, верб информационный.
# Бинарь в репо лежит как bin/<арка>/<имя>.user, а на роутере — ПЛОСКО $ENODIA_DIR/<имя>: чужую
# арку пропускаем, иначе получили бы «расхождение» на каждом бинаре.
cmd_verify() {
    only="$1"
    sums_load
    [ "$SUMS_STATE" = ok ] || { log "[verify] в репо ($GH_REF) нет $SUMS_REL — сверять не с чем"; return 1; }
    _arch=$(bin_arch)
    nsame=0; ndiff=0; nmiss=0
    while read -r _h _p; do
        case "$_h" in ''|\#*) continue ;; esac
        [ "${#_h}" = 64 ] || continue
        _p=${_p#\*}
        # bin-manifest.txt на роутере живёт КЭШЕМ (.bin-manifest) и обновляется отдельно от
        # скриптов — «расхождение» тут было бы нормой, а не находкой. Пропускаем.
        [ "$_p" = "$BM_REL" ] && continue
        if [ -n "$only" ]; then case "$_p" in *"$only"*) : ;; *) continue ;; esac; fi
        case "$_p" in
            bin/*/*.user)
                _pa=${_p#bin/}; _pa=${_pa%%/*}
                [ -z "$_arch" ] || [ "$_pa" = "$_arch" ] || continue
                _n=${_p##*/}; _l="$ENODIA_BIN/${_n%.user}" ;;
            bin/*.user) _n=${_p##*/}; _l="$ENODIA_BIN/${_n%.user}" ;;
            *) _l="$ENODIA_DIR/$_p" ;;
        esac
        if [ ! -f "$_l" ]; then log "[verify] нет на роутере: $_p"; nmiss=$((nmiss+1)); continue; fi
        _g=$(file_sha256 "$_l")
        if [ "$_g" = "$_h" ]; then nsame=$((nsame+1)); else log "[verify] РАСХОЖДЕНИЕ: $_p"; ndiff=$((ndiff+1)); fi
    done < "$SUMS_CACHE"
    log "[verify] совпало $nsame, расходится $ndiff, нет на роутере $nmiss (репо $GH_REF, локально $(local_name))"
    [ "$ndiff" = 0 ]
}

case "$1" in
    fetch-bin)     fetch_bin "$2" "$3" "$4" ;;
    check)         cmd_check ;;
    apply-scripts) cmd_apply_scripts "$2" ;;
    rollback)      cmd_rollback ;;
    self)          cmd_self ;;
    dl)            dl "$2" "$3" ;;
    verify)        cmd_verify "$2" ;;
    reachable)     gh_reachable "$2" ;;
    # Манифест бинарей: `bin-manifest` = взять из кэша (скачать, если пусто), `bin-manifest refresh`
    # = перекачать принудительно. Зовут refresh ЧЕТВЕРО, и все — там, где сеть уже под рукой:
    # `check` и `apply-scripts` (здесь же, выше), packages.sh и proto-install.sh перед установкой.
    # bin-size/bin-ver — ответы на «сколько займёт» и «что за версия» одним словом, чтобы
    # вызывающему не разбирать TSV.
    bin-manifest)  bm_ensure "$2" >&2; cat "$BM_CACHE" 2>/dev/null ;;
    bin-size)      bin_size "$2" "$3" ;;
    bin-ver)       bin_ver "$2" ;;
    *) echo "usage: $0 fetch-bin <name> <dst> [minsz] | check | apply-scripts [--force] | rollback | self | dl <rel> <dst> | verify [путь] | reachable [path] | bin-manifest [refresh] | bin-size <имя> [min|max] | bin-ver <имя>"; exit 2 ;;
esac
_rc=$?
# Кэш сумм — временный (свежий на каждый запуск): протухшая копия молча пропустила бы
# подменённый файл следующего релиза. Отметку кода GitHub убираем ЗДЕСЬ и только здесь: в
# trap её ставить нельзя — EXIT срабатывает и в ФОНОВОЙ подоболочке закачки, то есть стёр бы
# вердикт ровно перед тем, как родитель его прочтёт.
rm -f "$SUMS_CACHE" "$GH_CODE_FILE"
exit $_rc
