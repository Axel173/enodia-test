#!/bin/sh
# json-lib.sh — ЕДИНСТВЕННЫЙ перевод «вывод скрипта → строка внутри JSON» на весь проект.
# СОРСИТСЯ (не исполняется): потребители — CGI панели (action/data/2fa) и web-ui.sh.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Конвейер «обрезать и заэкранировать» переписывали в каждом месте, где
# сообщение роутера уезжает в панель, и копии РАЗОШЛИСЬ: батч 12 свёл шесть копий внутри
# cgi-bin/action в jesc(), но ровно тот же конвейер жил ещё в четырёх ветках cgi-bin/data, трёх
# ветках cgi-bin/2fa и в web-ui.sh — и там он остался в прежнем, дефектном виде (где-то кавычки
# ВЫРЕЗАЛИСЬ вместо экранирования, где-то обрезка шла ПОСЛЕ экранирования, нигде не снимался
# сырой TAB). Общего файла у этих четверых нет: action/data сорсят store-lib, 2fa — totp.sh,
# web-ui — nf-i18n. Поэтому дом у примитива свой.
#
# ТРИ ЛОВУШКИ, ради которых функция вообще существует (все замерены на железе):
#  - `cut -c` у busybox режет БАЙТАМИ (`printf 'абв' | cut -c1-3` → D0 B0 D0): обрыв приходится
#    на середину кириллической буквы, и хвост сообщения приезжает в панель «ромбиком». Недобитую
#    последовательность снимаем — и ТОЛЬКО её (целый символ на конце не трогаем, иначе каждое
#    короткое сообщение теряло бы последнюю букву);
#  - режем ДО экранирования: после него на границе мог остаться нечётный `\` от пары `\\`, а это
#    уже не «кривой хвост», а сломанный JSON — падает разбор ВСЕГО ответа, не одного поля;
#  - сырой TAB внутри JSON-строки невалиден, а TSV в проекте печатает половина скриптов.
#
# ШИМ У ПОТРЕБИТЕЛЕЙ ОБЯЗАТЕЛЕН: файл может не доехать на старую установку. Сорсить только
# `if [ -f "$lib" ]; then . "$lib"; fi` — провалившийся `.` в busybox ash фатален для шелла.

# jtrim — снять НЕДОБИТУЮ UTF-8 последовательность в конце. Ведущий байт без положенного числа
# продолжений: 2-байтовый C2..DF, 3-байтовый E0..EF, 4-байтовый F0..F4.
jtrim() { sed "s/[$(printf '\302-\337')]\$//; s/[$(printf '\340-\357')][$(printf '\200-\277')]\{0,1\}\$//; s/[$(printf '\360-\364')][$(printf '\200-\277')]\{0,2\}\$//"; }

# jesc <лимит байт> — текст со stdin → безопасное содержимое JSON-строки (без обрамляющих кавычек).
jesc() { tr -d '\033\r' | sed 's/\[[0-9;]*m//g' | tr '\n\t' '  ' | cut -c1-"$1" | jtrim | sed 's/\\/\\\\/g; s/"/\\"/g'; }
