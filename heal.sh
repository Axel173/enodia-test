#!/bin/sh
# heal.sh — самовосстановление AmneziaWG + iplist после ребута.
# Запускается из cron каждую минуту; lock-файл в /tmp гарантирует выполнение
# один раз за загрузку. НЕ зависит от re-filter и dnsmasq-обвязки.
#
# Версия 2.0 / май 2026:
#   - Чистит пустые I1..I5 в awg.conf перед запуском awg_setup.sh
#   - Восстанавливает amnezia_for_awg.conf если он пропал
#   - (исторически восстанавливал бинарники из .working.bak; .working.bak ретайрнут
#     июнь 2026 — curl-угроза в awg_setup.sh устранена, восстановление = переустановка с ПК)
#   - Добавляет FORWARD ACCEPT на awg0 (без этого fw3 дропает LAN-трафик)
#   - Вызывает split-route.sh если он есть (DRY: правила в одном месте)

LOCK=/tmp/enodia-heal.lock
SWITCH_LOCK=/tmp/enodia-switching.lock
LOG=/tmp/enodia-startup.log
ENODIA_DIR=/data/usr/app/enodia
ENODIA_STATE=${ENODIA_STATE:-/data/usr/app/enodia-state}
ENODIA_BIN=${ENODIA_BIN:-/data/usr/app/enodia-bin}
TABLE=1000

# Каталоги состояния и бинарей заводит установщик, но НЕ он один их видит: до ближайшей
# установки роутер живёт на cron, а `> "$ENODIA_STATE/<имя>"` в НЕСУЩЕСТВУЮЩЕМ каталоге —
# не «пусто», а ошибка записи, то есть тихо потерянный персист. Поэтому heal (он бежит
# раньше всех и чаще всех) держит их наличие сам. Гард `[ -d ]` — БИЛТИН: на роутере без
# происшествий это ноль форков в минуту, mkdir рождается только в аварии.
[ -d "$ENODIA_STATE" ] || { mkdir -p "$ENODIA_STATE" 2>/dev/null; chmod 700 "$ENODIA_STATE" 2>/dev/null; }
[ -d "$ENODIA_BIN" ]   || { mkdir -p "$ENODIA_BIN" 2>/dev/null; chmod 755 "$ENODIA_BIN" 2>/dev/null; }

# Подсистемы ниже зовём `sh ./x.sh` с гардом по НАЛИЧИЮ файла: бут — это единственный проход,
# на котором персист возвращается в ядро, и слетевший бит исполнения у одного файла означал бы
# тихо пропущенную подсистему при зелёном логе. Полный разбор — у plugin_for в transport.sh.

# Общий примитив «внешний IPv4» (ip-lib.sh) для строки «Внешний IP» в boot-письме: IP-литерал,
# DNS-free — на ядре 4.4 hostname api.ipify.org молча пустел. Шим на случай установки без lib.
if [ -f "$ENODIA_DIR/ip-lib.sh" ]; then . "$ENODIA_DIR/ip-lib.sh"; fi
# Ожидание xtables-лока: ipt-lib.sh подменяет команду `iptables` и добавляет `-w`. Лок занят
# чужим кроном ⇒ без ожидания правило МОЛЧА не встаёт. Нет файла — прежний путь байт-в-байт.
if [ -f "$ENODIA_DIR/ipt-lib.sh" ]; then . "$ENODIA_DIR/ipt-lib.sh"; fi
# Имя LAN-моста (router-lib.sh::lan_if): оба гарда подъёма панели ниже смотрят на ЕГО адрес,
# а `br-lan` — имя моста ИМЕННО BE7000. Нет файла — шим отдаёт прежний литерал байт-в-байт.
if [ -f "$ENODIA_DIR/router-lib.sh" ]; then . "$ENODIA_DIR/router-lib.sh"; fi
command -v lan_if >/dev/null 2>&1 || lan_if() { echo br-lan; }   # lan-lit: шим без router-lib.sh
command -v probe_ext_ip >/dev/null 2>&1 || probe_ext_ip() { curl -s $1 --max-time "${2:-7}" https://api.ipify.org 2>/dev/null; }

# Возраст отметки времени (clock-lib.sh). Здесь по нему решается «поднялся ли VPN после загрузки»,
# то есть уйдёт ли письмо boot-ok или boot-fail. Часы на буте заведомо КРИВЫЕ (RTC нет, стоковый ntp
# в это окно ещё не прошёл) ⇒ голая разность «now - hs» тут врёт по определению. Шим = прежнее.
if [ -f "$ENODIA_DIR/clock-lib.sh" ]; then . "$ENODIA_DIR/clock-lib.sh"; fi
command -v age_since >/dev/null 2>&1 || age_since() {
    case "$1" in ''|*[!0-9]*) echo 999999; return ;; esac
    [ "$1" -gt 0 ] && echo $(( $(date +%s) - $1 )) || echo 999999
}

# Язык boot-письма/события — панельный pref lang (деф. ru). Шим на случай установки без файла.
if [ -f "$ENODIA_DIR/nf-i18n.sh" ]; then . "$ENODIA_DIR/nf-i18n.sh"; fi
command -v nf_lang >/dev/null 2>&1 || nf_lang() { echo ru; }

# Слой шифрованного DNS (doh-lib.sh): подъём https_dns_proxy на буте (секция 5.14 ниже). Шим —
# без lib DoH недоступен, doh_want=false ⇒ секция no-op. [[doh-direct-modes-backlog]]
if [ -f "$ENODIA_DIR/doh-lib.sh" ]; then . "$ENODIA_DIR/doh-lib.sh"; fi
command -v doh_enabled >/dev/null 2>&1 || doh_enabled() { return 1; }
command -v doh_want >/dev/null 2>&1 || doh_want() { return 1; }   # старая lib без авто-режима

# Где лежит бинарь (store-lib.sh) — нужен ОДНОМУ месту: диагностическому срезу `awg show` в конце
# (секция 6). С внешним накопителем awg живёт не в $ENODIA_DIR, и путь оттуда знает только lib.
# Шим — прежний путь байт-в-байт, как у всех остальных потребителей.
if [ -f "$ENODIA_DIR/store-lib.sh" ]; then . "$ENODIA_DIR/store-lib.sh"; fi
command -v bin_path >/dev/null 2>&1 || bin_path() { printf '%s' "$ENODIA_BIN/$1"; }

# ВЕРБ `replay` — переигрыш ПЕРСИСТА ПОДСИСТЕМ без бутового сценария.
#
# ЗАЧЕМ. Порядок восстановления групп/гео/доп-выходов/десинка/«доступа домой» описан РОВНО
# ЗДЕСЬ (секции 5.5–5.14) и больше нигде: `install.sh` поднимает только базу, а
# `vpn-toggle.sh repair` — только семью вырезов. Но heal гейтится бутовым локом (1×/boot), и
# тот, кто отключил VPN и включил обратно БЕЗ РЕБУТА, молча оставался без групп, гео, десинка
# и доп-выходов: настройки на месте, панель показывает их включёнными, а в ядре их нет.
# Замерено на железе 08.08.2026 дважды (панельное «Отключить VPN» и полный цикл
# uninstall deactivate → установка поверх): из 13 наших ipset оставалось 2.
#
# ПОЧЕМУ ВЕРБ, А НЕ КОПИЯ ПОРЯДКА У ВЫЗЫВАЮЩИХ: копия немедленно разъедется с оригиналом —
# порядок здесь не произвольный (mark-core ПОСЛЕ groups/geo, иначе слот-сетов ещё нет; слоты
# ПОСЛЕ mark-core; прогрев доменов ПОСЛЕ подъёма транспорта). Владелец порядка остаётся один.
#
# ЧЕМ replay ОТЛИЧАЕТСЯ от бутового прогона: без бутового лока (иначе он и есть причина), без
# `awg_setup.sh` (тот кончается `firewall reload` = СНОС всех iptables — на живом роутере это
# разрыв связи), без перезаписи туннельного DNS (его уже поставил живой транспорт, а при
# включённом DoH секция 2 вернула бы upstream в туннель), без тяжёлой перекачки iplist и без
# бутового письма «загрузка OK» (роутер не перезагружался — письмо было бы ложью).
REPLAY=0
if [ "${1:-}" = replay ]; then REPLAY=1; fi

# ЛОК ЗДЕСЬ ЗНАЧИТ «heal в ЭТУ загрузку уже отработал», а не «идёт прямо сейчас» — потому он и
# остаётся после успеха. Беда была в том, что УБИТЫЙ прогон оставлял РОВНО ТАКОЙ ЖЕ след: heal,
# срезанный OOM-киллером на буте (176 МБ ОЗУ, awg-go растит кучу — см. CLAUDE.md), выглядел как
# отработавший, и автозапуск оставался мёртвым ДО РЕБУТА при зелёной панели. Различаем по
# СОДЕРЖИМОМУ: «<pid> try<N> <дата>» пока идём, «done <дата>» когда дошли до конца.
#   done…  — отработал, выходим (прежнее поведение)
#   пусто  — лок чужой формы (старая копия скрипта, `touch` руками) ⇒ судим как раньше: выходим
#   pid жив И это правда heal (по cmdline) — прогон идёт ПРЯМО СЕЙЧАС, второму тут делать нечего
#   pid мёртв и «done» не написано — держателя убили: забираем лок и пробуем снова, но НЕ вечно
# Судим о смерти держателя по /proc, а не по возрасту: «нет pid-файла ≠ лок протух» — этой граблёй
# уже платили в менеджере списков.
# ПОТОЛОК ПОПЫТОК ОБЯЗАТЕЛЕН. Разовая смерть (OOM на буте) обязана лечиться, а вот падение
# ДЕТЕРМИНИРОВАННОЕ — нет: cron гонял бы полный бутовый сценарий каждую минуту ВЕЧНО, а в нём
# `awg_setup.sh` с его `firewall reload` (снос ВСЕХ iptables). Три обрыва подряд ⇒ считаем «heal
# в эту загрузку не жилец», пишем это в лок словами (его печатает dump.sh) и ведём себя
# как раньше. Разбудить может человек или сторож — оба снимают лок `rm -f`.
HEAL_TRY=1
if [ "$REPLAY" = 0 ] && [ -e "$LOCK" ]; then
    _hlk=$(cat "$LOCK" 2>/dev/null | tr -d '\r')
    case "$_hlk" in
        done*|'') exit 0 ;;
    esac
    _hlp=${_hlk%% *}
    case "$_hlp" in ''|*[!0-9]*) exit 0 ;; esac          # непонятное содержимое = чужой лок
    if [ -d "/proc/$_hlp" ]; then
        # ПИД МОГ БЫТЬ ПЕРЕИСПОЛЬЗОВАН: «каталог есть» значит лишь «какой-то процесс есть», а
        # ядро раздаёт номера по кругу. Спрашиваем cmdline — тем же приёмом проект гасит СВОЙ
        # инстанс демона, а не первый попавшийся (никаких killall/pidof). Не прочли cmdline ⇒
        # НЕ отнимаем: неизвестность трактуем в пользу прежнего поведения.
        case "$(tr '\000' ' ' < "/proc/$_hlp/cmdline" 2>/dev/null)" in
            ''|*heal.sh*) exit 0 ;;
        esac
    fi
    _hlr=${_hlk#* }; _hlr=${_hlr%% *}; _hlr=${_hlr#try}  # «try<N>» из второго поля
    case "$_hlr" in ''|*[!0-9]*) _hlr=1 ;; esac
    if [ "$_hlr" -ge 3 ]; then
        echo "done (три прогона подряд оборвались — heal в эту загрузку остановлен) $(date 2>/dev/null)" > "$LOCK" 2>/dev/null
        exit 0
    fi
    HEAL_TRY=$((_hlr + 1))
    rm -f "$LOCK" 2>/dev/null
fi

# Если прямо сейчас идёт переключение страны через switch-vpn.sh —
# не лезем. Иначе мы можем поднять awg0 с НЕправильным конфигом
# (старый amnezia_for_awg.conf) посреди операции переключения,
# или подсунуть свои iptables-правила пока switch-vpn делает свою
# работу. switch-vpn.sh ставит этот лок при старте и снимает в конце.
[ -e "$SWITCH_LOCK" ] && exit 0

if [ "$REPLAY" = 0 ]; then
    # ЛОК БЕРЁМ ДО ОЖИДАНИЯ СЕТИ И АТОМАРНО. Раньше он ставился ПОСЛЕ тридцатисекундного ожидания,
    # а проверка выше — обычный `[ -e ]`: cron-тик, попавший в это окно (а на буте тики идут каждую
    # минуту), проверку проходил и запускал ВТОРОЙ heal параллельно первому — оба чинили одни и те
    # же правила и оба звали awg_setup.sh с его `firewall reload`. `set -C` даёт O_EXCL: «проверил
    # и создал» ОДНИМ системным вызовом, без окна между ними.
    # ФОРМА — ФАЙЛ, а не mkdir-каталог, хотя каталог «атомарнее по учебнику»: этот лок снимают
    # ЧУЖИЕ руки — `rm -f` у сторожа (три ветки) и человек по подсказке из vpn-toggle. Каталог им
    # не удалить, и цена «правильной» формы была бы мёртвый автозапуск до ребута.
    # Содержимое (pid + номер попытки + время) — это и есть механизм различения «идёт / отработал /
    # убит», а заодно разбор: `dump.sh` печатает непустые локи, и «кто держит» раньше
    # приходилось угадывать.
    ( set -C; echo "$$ try$HEAL_TRY $(date 2>/dev/null)" > "$LOCK" ) 2>/dev/null || exit 0
    # TRAP тут НЕ помощник, и это ЗАМЕРЕНО на роутере 23.08.2026: ash откладывает обработчик до
    # конца текущей команды (в `sleep 5` он ждёт её целиком), а OOM-киллер бьёт SIGKILL, которого
    # не поймать вовсе. Поэтому «прогон умер» распознаём НЕ ловушкой, а содержимым лока — см.
    # разбор у проверки выше; последняя строка файла пишет сюда «done».

    # Ждём поднятия сети (до 30 сек)
    i=0
    while [ $i -lt 6 ]; do
        ip route get 1.1.1.1 >/dev/null 2>&1 && break
        sleep 5; i=$((i+1))
    done

    : > "$LOG"
else
    # Лог НЕ обнуляем: бутовый прогон — единственный след того, как поднялся роутер, и
    # затирать его ручным переигрышем нельзя. fd 3 — исходный stdout: всё остальное уедет
    # в лог, а вызывающему (панель, vpn-toggle, установщик) нужна одна честная строка.
    exec 3>&1
fi
exec >>"$LOG" 2>&1
if [ "$REPLAY" = 1 ]; then
    echo "===== heal.sh replay $(date) ====="
else
    echo "===== heal.sh $(date) ====="
fi

cd "$ENODIA_DIR" || exit 1

# АКТИВНЫЙ ТРАНСПОРТ читаем В САМОМ НАЧАЛЕ (флаг переживает ребут; нет файла => awg). Раньше он
# читался только перед секцией 5.6, а секция 2 БЕЗУСЛОВНО прописывала dnsmasq ТУННЕЛЬНЫЙ DNS из
# awg.conf — даже когда несёт xray/hy2/byedpi/zapret. Цена: на буте альт-установки резолвер весь
# отрезок 2→5.6 смотрел в мёртвый туннель (а на установке БЕЗ awg.conf — в фолбэк 172.29.172.254,
# которого не существует нигде), и если несущая не поднималась, DNS так и оставался мёртвым —
# полный SPOF вместо честного «идём напрямую». Теперь туннельный DNS ставит ВЛАДЕЛЕЦ: awg-ветка
# здесь, у прочих — DNS-сеттер их плагина в секции 5.6.
active_t=$(cat "$ENODIA_STATE/.transport" 2>/dev/null | tr -d ' \r\n')
# Пусто = ЛИБО роутер, установленный до появления флага (несущая там awg — историческое
# поведение, ломать нельзя), ЛИБО установка «только панель», где транспорта нет вовсе. Отличает
# их наличие awg.conf, и владелец этого ответа один — оркестратор (transport.sh configured);
# код 2 = старая копия скрипта, тогда как раньше. active_t=none гасит РОВНО ЧЕТЫРЕ шага ниже —
# те, что кладут наши правила в ядро или поднимают несущую: разводку доменных сетов (2b, и то
# лишь когда правил нет вовсе), ядро маркировки (5), вырезы «мимо VPN» (5.5) и подъём несущей
# (5.6), плюс бутовый вердикт/письмо. Всё прочее (панель, накопитель, закреплённые адреса,
# группы, гео, «доступ домой», DoH, прогрев доменов) на буте нужно ровно так же.
if [ -z "$active_t" ]; then
    active_t=awg                                   # исторический фолбэк: роутер старше флага
    if [ -f "$ENODIA_DIR/transport.sh" ]; then
        sh "$ENODIA_DIR/transport.sh" configured >/dev/null 2>&1
        [ "$?" = 1 ] && active_t=none
    fi
fi

# 0a. ВНЕШНИЙ НАКОПИТЕЛЬ — ДО подъёма чего бы то ни было. /mnt = ramfs, а стоковый automount
# (hotplug.d/block) отрабатывает по своему таймингу, асинхронно нашему cron: не смонтируем сами —
# bin_path отдаст резидентный путь, которого нет, и транспорт честно окажется «не готов»
# (fail-open вместо несущей). Роутер БЕЗ накопителя (основной сценарий) не платит ничего: нет
# маркера .bin-store — usb-offload.sh выходит первой строкой. Ошибка нефатальна: без накопителя
# загрузка обязана идти как всегда, поэтому дальше heal работает по резидентным путям.
[ -f "$ENODIA_DIR/usb-offload.sh" ] && sh "$ENODIA_DIR/usb-offload.sh" mount-ensure

# 0a+. …и ВТОРОЙ вопрос про транспорт, которого прежде не задавали вовсе: а ПОДНИМЕТСЯ ли он на
# ЭТОМ роутере. `configured` выше судит по НАМЕРЕНИЮ, а намерение приезжает и ИЗ БЭКАПА ЧУЖОГО
# роутера: замерено на AX3600 16.08.2026 — импорт архива с BE7000 вернул `.transport=awg` и
# `awg.conf`, бинарей AmneziaWG тут не было НИ РАЗУ. Heal каждую минуту (сторож снимал ему лок)
# гонял полный бутовый сценарий ради несущей, которой неоткуда взяться, а вердикт слал письмо
# «после загрузки VPN НЕ поднялся» — то же по классу враньё, ради которого заведён active_t=none.
# Владелец ответа один — оркестратор (`transport.sh ready`); код 2 = старая копия скрипта ⇒ ведём
# себя как раньше. Гасит РОВНО ДВА шага: подъём несущей (5.6) и бутовый вердикт/письмо. Маркировку
# и вырезы оставляем: они переживают ребут как персист человека, а без несущей table 1000 пуста =
# честный fail-open, и в ту же минуту, когда компонент поставят, всё уже разведено.
# МЕСТО НЕ ПРОИЗВОЛЬНО — строго ПОСЛЕ 0a: «есть ли бинарь» отвечает store-lib (`bin_path`), а он
# на роутере с накопителем смотрит в /mnt, который ДО mount-ensure ещё не смонтирован. Спроси мы
# раньше — на таком роутере heal сам объявил бы транспорт неподъёмным на весь бут.
active_ready=1
if [ "$active_t" != none ] && [ -f "$ENODIA_DIR/transport.sh" ]; then
    sh "$ENODIA_DIR/transport.sh" ready "$active_t" >/dev/null 2>&1
    [ "$?" = 1 ] && active_ready=0
fi
# Тот же вопрос про САМ AmneziaWG — отдельно от активного транспорта: awg0 поднимается и как
# ТЁПЛЫЙ РЕЗЕРВ при активном xray, а секция 0+1 гейтилась одним `awg.conf`. Без бинарей
# `awg_setup.sh` честно падает (exit 1), но до того heal успевает снести живой awg0 (`ip link del`)
# и переписать конфиги — и на роутере с импортированным намерением это повторялось КАЖДУЮ минуту.
awg_ready=1
if [ -f "$ENODIA_DIR/transport.sh" ]; then
    sh "$ENODIA_DIR/transport.sh" ready awg >/dev/null 2>&1
    [ "$?" = 1 ] && awg_ready=0
fi

# 0b. ВЕБ-ПАНЕЛЬ — КАК МОЖНО РАНЬШЕ, а не в конце (жалоба тестера 14.08.2026: «после ребута
# панель отваливается, помогает перезапуск с ПК»). Подъём панели стоял шагом 5.17, ПОСЛЕ всего:
# несущей, списков, гео, слотов, прогрева доменов. На здоровом роутере это 49 с от буты (замер
# BE7000: старт uhttpd на 49-й секунде) — почти незаметно. Но каждый из этих шагов ходит в СЕТЬ, и
# ровно когда с сетью беда, они и тянутся минутами: подъём несущей ПО ИМЕНИ — до шести ожиданий
# резолва, закачки списков и гео — свои таймауты. То есть панель приходила тем позже, чем сильнее
# она была нужна: это ЕДИНСТВЕННЫЙ инструмент, которым человек видит, что пошло не так, и меняет
# сервер. Панель ни от чего в этом списке не зависит (свой uhttpd, статика + CGI по файлам
# состояния), поэтому её место — здесь.
# Шаг 5.17 ОСТАЁТСЯ и нужен: `start` при живой панели идёт к tls_start + wan_rule_apply, а
# «доступ снаружи» смывает `firewall reload` из awg_setup.sh ниже. Плюс это второй заход, если
# сейчас у br-lan ещё нет адреса (гард тот же, что в 5.17: без адреса LISTEN упал бы на литерал
# 192.168.31.1 и uhttpd занял бы ЧУЖОЙ адрес насовсем).
# В REPLAY не лезем: там панель заведомо жива, а поведение переигрыша менять незачем — 5.17 своё
# сделает.
if [ "$REPLAY" = 0 ] && [ -f ./web-ui.sh ] && ip -4 addr show "$(lan_if)" 2>/dev/null | grep -q 'inet '; then
    echo "--- панель: поднимаю uhttpd:8088 (рано, до сетевых шагов) ---"
    # Вывод НЕ глушим: `start` обязан назвать причину отказа (под `-b` stdio уходит в /dev/null,
    # и это ЕДИНСТВЕННОЕ место, где она видна). Глушилка означала «панель не поднялась, а в логе
    # бута только заголовок» — ровно то, ради чего лог и читают.
    sh ./web-ui.sh start 2>&1 || true
fi

# 0+1. AmneziaWG: подготовка конфига + поднятие awg0 — несущая (если активен awg)
# ИЛИ тёплый резерв (если активен xray). Всё это нужно ТОЛЬКО когда awg установлен
# (есть awg.conf). При xray-only (awg.conf нет) — пропускаем целиком: ядро + xray
# поднимутся ниже без awg0. Это и есть расцепка, делающая возможной установку без awg.
# В replay эта секция ПРОПУСКАЕТСЯ целиком: `awg_setup.sh` кончается `firewall reload`, то есть
# сносом ВСЕХ iptables. На буте это штатно (heal сразу переигрывает своё), а на живом роутере —
# разрыв связи ради правил, которые и так стоят.
if [ "$REPLAY" = 0 ] && [ -f "$ENODIA_STATE/awg.conf" ] && [ "$awg_ready" = 0 ]; then
    echo "awg.conf есть, а компонента AmneziaWG нет (бинари не установлены) — awg0 не трогаю"
elif [ "$REPLAY" = 0 ] && [ -f "$ENODIA_STATE/awg.conf" ]; then
    echo "--- preparing awg config ---"
    if grep -qE '^I[1-5]\s*=\s*$' "$ENODIA_STATE/awg.conf" 2>/dev/null; then
        sed -i '/^I[1-5]\s*=\s*$/d' "$ENODIA_STATE/awg.conf"
        echo "cleaned empty I1..I5 from awg.conf"
    fi
    # amnezia_for_awg.conf нужен вендорному awg_setup.sh
    if [ ! -f "$ENODIA_STATE/amnezia_for_awg.conf" ]; then
        cp "$ENODIA_STATE/awg.conf" "$ENODIA_STATE/amnezia_for_awg.conf"
        echo "amnezia_for_awg.conf recreated from awg.conf"
    fi
    # Аналогично awg0.conf — могут чистить пустые I
    if [ -f "$ENODIA_STATE/awg0.conf" ] && grep -qE '^I[1-5]\s*=\s*$' "$ENODIA_STATE/awg0.conf"; then
        sed -i '/^I[1-5]\s*=\s*$/d' "$ENODIA_STATE/awg0.conf"
    fi
    # Поднимаем awg0 (вендорный awg_setup.sh, идемпотентный — НЕ перекачивает бинарники
    # если они есть; при их отсутствии честно падает с exit 1).
    echo "--- bringing up awg0 ---"
    ip link del awg0 2>/dev/null
    sh ./awg_setup.sh
fi

# 2. Прописываем upstream DNS изнутри VPN (защита от подмен провайдером) — ТОЛЬКО когда несущая
# наша, awg. У прочих транспортов свой DNS-режим (xray/hy2 — через туннель, byedpi/zapret —
# ПРЯМОЙ), и ставит его DNS-сеттер плагина в секции 5.6; до него dnsmasq работает на upstream'ах
# провайдера из resolv.conf — то есть интернет на буте жив в любом случае (см. шапку про active_t).
# DNS адрес берём из awg.conf, fallback — 172.29.172.254 (типовой у Amnezia)
mkdir -p /etc/dnsmasq.d
# В replay upstream НЕ трогаем: его уже поставил живой транспорт (или слой DoH — там upstream
# смотрит на 127.0.0.1#5053, и запись туннельного адреса поверх увела бы резолвер в туннель).
if [ "$REPLAY" = 1 ]; then
    echo "DNS: replay — upstream не трогаю (его владелец — активный транспорт / DoH)"
elif [ "$active_t" = awg ] && { [ -f ./transport.sh ] || [ -f ./transport-awg.sh ]; }; then
    # ГРАБЛЯ (железо 10.08.2026): раньше туннельный адрес прописывался ЗДЕСЬ — то есть ДО того, как
    # несущая поднята (она встаёт в 5.6). Всё это окно роутер резолвит через адрес, которого ещё нет,
    # а если несущая не встала вовсе (VPS молчит — ровно наш случай), то и до самого failover'а.
    # Слепнет не только наш код: стоковый ntpsetclock резолвит пул ПО ИМЕНАМ и в это окно падает,
    # его htp-фолбэк рапортует «ok», часы не поправив, и время уезжает на часы вперёд позже
    # (см. [[watchdog-clock-step-false-death]]); туда же Xiaomi-облако, OTA и всё стоковое.
    # Владелец туннельного DNS — ПЛАГИН (transport-awg cmd_up → restore_vpn_dns), и он же знает про
    # DoH (тут этого знания нет — при включённом DoH секция уводила резолвер мимо прокси, в туннель).
    # Поэтому на буте upstream НЕ трогаем: до 5.6 dnsmasq работает на резолверах провайдера из
    # resolv.conf — как уже сделано у всех остальных транспортов. Несущая не встала ⇒ так и остаёмся
    # напрямую, это штатный fail-open, а не потеря DNS.
    echo "DNS: upstream ставит плагин awg при подъёме несущей (5.6) — на буте не трогаю"
elif [ "$active_t" = awg ]; then
    # Фолбэк для установки без transport.sh (старый layout): владельца DNS нет, пишем сами, как было.
    VPN_DNS=$(grep -E '^DNS\s*=' "$ENODIA_STATE/awg.conf" 2>/dev/null | head -1 | awk -F'= *' '{print $2}' | awk -F',' '{print $1}' | tr -d ' ')
    [ -z "$VPN_DNS" ] && VPN_DNS=172.29.172.254
    echo "VPN_DNS: $VPN_DNS (нет плагина awg — ставлю сам)"
    cat > /etc/dnsmasq.d/00-upstream.conf <<UPSTREAM
no-resolv
server=$VPN_DNS
UPSTREAM
else
    echo "DNS: транспорт $active_t — upstream ставит его плагин (секция 5.6), туннельный DNS не прописываю"
fi
# conf-dir — БЕЗУСЛОВНО: /etc = ramfs, строка нужна на КАЖДОМ буте и любому транспорту (без неё
# dnsmasq не увидит ни ipset=-правил доменов, ни блокировок).
grep -q '^conf-dir=/etc/dnsmasq.d' /etc/dnsmasq.conf || \
    echo 'conf-dir=/etc/dnsmasq.d,*.conf' >> /etc/dnsmasq.conf

# 2b. Пользовательские правила доменов («в VPN» / «мимо VPN», domain.sh) живут в
# /etc/dnsmasq.d/enodia-custom.conf = ramfs → на ребуте стираются, и раньше их ничто не
# восстанавливало (юзер: «очистился список, который добавлял»). Персист .enodia-custom.conf
# на /data переживает ребут — кладём его обратно в /etc ДО рестарта dnsmasq ниже, чтобы
# ipset=/дом/enodia_list|enodia_bypass снова заработали одним рестартом. Без персиста/доменов — no-op.
# Сама копия персист→/etc живёт в domain.sh (верб `restore`) — ОДИН владелец на всех потребителей.
# Строка стояла здесь, и это значило «восстановление бывает только на буте, под локом 1×/boot»:
# импорт бэкапа клал персист, живой файл не трогал, и панель показывала пустой список правил.
if [ -f ./domain.sh ]; then
    echo "--- custom domains: восстановление из персиста (.enodia-custom.conf) ---"
    sh ./domain.sh restore || true
fi
# Сеты доменных правил (RAM → на ребуте их нет). Обязательно ДО apply-bypass ниже: правило
# «сет enodia_bypass → мимо VPN» ставится только для СУЩЕСТВУЮЩЕГО сета (см. rule_add_set_dst).
# ПРОПУСКАЕМ ровно в одном случае: транспорта нет И правил доменов нет ни одного. Тогда `apply`
# заводит цепочку VPN_EXCLUDE, её jump'ы и reply-guard в mangle — на чистом роутере это
# единственные наши следы в ядре, и они там ни за чем (сеты пусты, метить некому). Условие
# ДВОЙНОЕ: есть хоть одно правило — ведём себя как раньше, чтобы не оставить его без проводки.
if [ "$active_t" = none ] && [ ! -s "$ENODIA_STATE/.enodia-custom.conf" ]; then
    echo "транспорт не настроен и доменных правил нет — сеты не развожу (нечего)"
else
    [ -f ./domain.sh ] && sh ./domain.sh apply 2>/dev/null || true
fi

# 2c. ЗАКРЕПЛЁННЫЕ АДРЕСА (dhcp-static.sh). Сниппет `dhcp-host=` лежит РОВНО В ОДНОМ месте —
# /tmp/dnsmasq.d, и это не мелочь: копия в /etc/dnsmasq.d размножается стоковым init'ом обратно
# в /tmp, а на дубле `dhcp-host` демон НЕ СТАРТУЕТ («duplicate dhcp-host IP address») и сеть
# остаётся без DNS вообще (поймано 10.08.2026, разбор — в шапке dhcp-static.sh; там же `place_conf`
# сносит /etc-копию всегда). /tmp гибнет на ребуте, а персист резерваций живёт на /data. Без переигрыша
# закрепление действовало бы до первой перезагрузки: устройство получило бы адрес из общего пула,
# и все правила, ключованные по адресу, тихо разъехались бы — ровно то, от чего резервация лечит.
# Собственного рестарта dnsmasq здесь не нужно: он идёт ниже одной общей строкой.
if [ -f "$ENODIA_STATE/.dhcp-static" ] && [ -f ./dhcp-static.sh ]; then
    echo "--- dhcp: восстановление закреплённых адресов ---"
    sh ./dhcp-static.sh apply norestart 2>/dev/null || true
fi

# Маршрут к туннельному резолверу нужен только СТАРОМУ layout'у: там `VPN_DNS` присвоен ветвью выше
# и awg0 уже поднят установщиком. На современном пути DNS целиком ведёт плагин (5.6) — переменная
# пуста, awg0 ещё не существует, и вызов был бы дважды бессмысленным. Гейт по непустоте, а не по
# транспорту: именно она и отличает один путь от другого.
[ "$active_t" = awg ] && [ -n "$VPN_DNS" ] && ip route replace "$VPN_DNS/32" dev awg0 2>/dev/null
# Через агрегатор ipset=-строк: на буте рядом оживают личные правила (enodia-custom.conf) и большой
# список re-filter (enodia-domains.conf), а dnsmasq применяет к домену РОВНО ОДНУ строку — без
# склейки личное правило человека проиграло бы массовому списку (его файл читается раньше по
# алфавиту). Нет агрегатора → прежний путь байт-в-байт.
sh "$ENODIA_DIR/dns-merge.sh" reload 2>/dev/null || /etc/init.d/dnsmasq restart 2>/dev/null

# 3. ipset enodia_list — наполняется dnsmasq'ом по ipset-правилам из
# /etc/dnsmasq.d/enodia-domains.conf (если re-filter включён, v2.1+) и/или
# /etc/dnsmasq.d/awg-domains-custom.conf (твои `domain add ...`).
# Если re-filter выключен и ручных доменов нет — ipset остаётся пустым,
# и это нормально: маршрутизация работает через iplist_set (CIDR).
ipset list -n 2>/dev/null | grep -qx enodia_list || \
    ipset create enodia_list hash:net family inet hashsize 1024 maxelem 1000000

# 4. CIDR от iplist (создаёт ipset iplist_set + mangle PREROUTING)
# В replay пропускаем ТОЛЬКО когда набор уже наполнен: перекачка ~3500 CIDR — минуты и трафик,
# а на буте она обязательна (ipset живёт в RAM). Пустой набор = маршрутизации нет ⇒ наполняем.
_ipl_n=$(ipset list iplist_set 2>/dev/null | grep -c '^[0-9]' || true)
case "$_ipl_n" in ''|*[!0-9]*) _ipl_n=0 ;; esac
if [ "$REPLAY" = 1 ] && [ "$_ipl_n" -gt 0 ]; then
    echo "iplist: replay — набор уже наполнен ($_ipl_n), перекачку пропускаю"
elif [ -f ./iplist-update.sh ]; then
    sh ./iplist-update.sh
fi

# 5. ОБЩЕЕ ЯДРО маршрутизации (транспорт-агностично): маркировка ipset -> MARK 0x1
# + ip rule fwmark -> table $TABLE. Несущую (default в table $TABLE) + FORWARD/MASQ/DNS
# кладёт АКТИВНЫЙ транспорт ниже (секция 5.6). Фолбэки: старый split-route.sh
# (делает ядро+awg-несущую), затем inline-ядро.
echo "--- mark-core (ядро: маркировка + ip rule) ---"
if [ "$active_t" = none ]; then
    # Установка «только панель»: транспорта нет, метить некуда. Ставить ядро всё равно —
    # значит подписать роутер нашими правилами там, где человек ещё ничего не выбрал.
    echo "транспорт не настроен — ядро маркировки не ставлю (роутер работает как сток)"
elif [ -f ./mark-core.sh ]; then
    sh ./mark-core.sh
elif [ -f ./split-route.sh ]; then
    sh ./split-route.sh
else
    ip rule del fwmark 0x1 table $TABLE 2>/dev/null
    ip rule add fwmark 0x1 table $TABLE pref 99
    for set in enodia_list iplist_set; do
        if ipset list -n 2>/dev/null | grep -qx "$set"; then
            iptables -t mangle -C PREROUTING -m set --match-set "$set" dst -j MARK --set-mark 0x1 2>/dev/null || \
                iptables -t mangle -A PREROUTING -m set --match-set "$set" dst -j MARK --set-mark 0x1
            iptables -t mangle -C OUTPUT -m set --match-set "$set" dst -j MARK --set-mark 0x1 2>/dev/null || \
                iptables -t mangle -A OUTPUT -m set --match-set "$set" dst -j MARK --set-mark 0x1
        fi
    done
fi

# 5.5. Восстанавливаем «вырезы мимо VPN» (исключения устройств / SSID / guest).
# Базовую маршрутизацию (трафик из списков->VPN) подняли выше; здесь возвращаем то, что
# пользователь увёл НАПРЯМУЮ через меню/vpn-toggle — иначе после ребута эти
# исключения (живут только в iptables/ip rule = RAM) молча уходят обратно в VPN.
# Безопасно: apply работает только с прямым путём, awg0 не затрагивает.
# Транспорта нет вовсе — восстанавливать нечего: «мимо VPN» без VPN бессмысленно, а «целиком в
# VPN» и «целиком в десинк» требуют несущей, которой не заводили. Пропуск здесь — не мелочь, а
# буквальность обещания «роутер работает как сток»: apply создаёт цепочку VPN_EXCLUDE и
# reply-guard в mangle ДАЖЕ на пустом персисте, и на чистом роутере это единственные наши следы
# в ядре (замерено на AX3600 15.08.2026). Появится транспорт — heal/repair позовут apply как
# раньше, персист от этого не страдает (он на /data).
if [ "$active_t" = none ]; then
    echo "транспорт не настроен — вырезы «мимо VPN» не переигрываю (нечего и не от чего)"
elif [ -f ./apply-bypass.sh ]; then
    echo "--- restoring bypass carve-outs ---"
    sh ./apply-bypass.sh apply
fi

# 5.6. АКТИВНЫЙ ТРАНСПОРТ кладёт несущую (default в table $TABLE) + FORWARD/MASQ/DNS,
# каждый через свой плагин (единый контракт up). awg0 уже поднят выше (секция 1) как
# несущая (для awg) или тёплый резерв (для xray). $active_t прочитан в начале файла
# (флаг переживает ребут; нет файла => awg).
echo "--- active transport: $active_t ---"
# Несущую активного транспорта поднимает ОРКЕСТРАТОР (transport.sh up <name>) — единая
# точка, через неё же подключатся будущие транспорты (hysteria2…) без правок heal.
# mark-core применён выше; transport.sh up идемпотентно переиграет его. Фолбэк — прямой
# вызов плагина (старый роутер без transport.sh).
if [ "$active_t" = none ]; then
    echo "транспорт не настроен — несущую не поднимаю (всё через панель: «Компоненты» → «Серверы»)"
elif [ "$active_ready" = 0 ]; then
    # Транспорт ВЫБРАН, но подняться ему нечем (см. 0a+). Причин у «не готов» три — нет программы,
    # нет конфига сервера, ядро не умеет, — и все три лечатся в панели, поэтому тут общая формула:
    # называть одну из них наугад хуже, чем честно сказать «нечем». Плагин и сам не найдёт бинарей,
    # но платит за это КАЖДЫЙ вызыватель, а лог получает «up» без результата вместо причины.
    echo "транспорт $active_t выбран, но поднять его нечем (нет программы/конфига) — несущую не поднимаю, см. панель :8088"
elif [ -f ./transport.sh ]; then
    sh ./transport.sh up "$active_t"
else
    case "$active_t" in
        xray) [ -f ./xray-transport.sh ] && sh ./xray-transport.sh up ;;
        *)    [ -f ./transport-awg.sh ] && sh ./transport-awg.sh up ;;
    esac
fi

# 5.7. Zapret теперь 5-й ТРАНСПОРТ (десинк направо БЕЗ VPS), а не параллельный слой: его
# несущую поднимает секция 5.6 (transport.sh up zapret), когда .transport=zapret. Здесь —
# одноразовая МИГРАЦИЯ: если остался флаг .zapret-on от старой ПАРАЛЛЕЛЬНОЙ версии, а активен
# ДРУГОЙ транспорт, снимаем старый параллельный десинк (apply при снятом ON_FLAG = teardown),
# чтобы не плодить phantom-правила поверх туннеля. [[zapret-as-5th-transport]]
if [ -f ./zapret.sh ] && [ -f ./.zapret-on ] && [ "$active_t" != zapret ]; then
    echo "--- zapret: миграция parallel→transport (снимаю старый параллельный десинк) ---"
    rm -f ./.zapret-on
    sh ./zapret.sh apply
fi

# 5.8. Блокировка рекламы/вредоносных IP (менеджер источников). ВСЁ тяжёлое (сырьё списков,
# кэш-фолбэк, снимок block-категорий) живёт в ОЗУ (/tmp/lists): на 20-МБ флеше мегабайтные
# блоклисты (StevenBlack/OISD/Hagezi) держать нельзя — переполняли /data → падал DNS/туннель.
# ОЗУ на ребуте стирается → списки перекачиваем заново ФОНОМ (сеть уже поднята выше; тянем через
