# 5.15. Глубина стокового syslog. `/etc` = ramfs ⇒ на КАЖДОМ буте возвращается заводской
# `log_size 1024` (КБ) — кольцо /tmp/messages при обычной болтливости прошивки (odhcpd, hostapd,
# sp_lib, dnsmasq) переполняется примерно за 13 часов. Именно этого не хватило при разборе ночных
# ложных rule-heal 30.07.2026: к утру окно уже прокрутилось, и «трогал ли кто-то фаервол ночью»
# было не проверить. 8 МБ (~4 суток) на 800-МБ железке ничего не стоят. Идемпотентно: если значение
# уже наше — ничего не делаем, syslog-ng не дёргаем.
SYSLOG_KB=8192
if command -v uci >/dev/null 2>&1; then
    _cur=$(uci -q get system.@system[0].log_size 2>/dev/null)
    case "$_cur" in ''|*[!0-9]*) _cur=0 ;; esac
    if [ "$_cur" -lt "$SYSLOG_KB" ]; then
        echo "--- syslog: расширяю кольцо ${_cur}K -> ${SYSLOG_KB}K ---"
        uci set system.@system[0].log_size="$SYSLOG_KB" 2>/dev/null && \
        uci commit system 2>/dev/null && \
        /etc/init.d/syslog-ng restart >/dev/null 2>&1
    fi
fi

