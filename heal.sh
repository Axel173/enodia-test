# посылка «heal бывает 1×/boot». Она мертва с тех пор, как сторож научился снимать heal-лок:
# теперь за один бут heal проходит вердикт СКОЛЬКО УГОДНО раз. Единственной защитой оставался
# маркер /tmp/enodia-heal.reason, а он гоночный — сторож пишет его раз в 2 мин, heal УДАЛЯЕТ на
# вердикте, и прогон, попавший в зазор, отправлял письмо (замерено на AX3600 16.08.2026).
# 6 часов не ломают смысл «раз за загрузку»: отметки throttle лежат в /tmp и гибнут с ребутом,
# то есть первое письмо после КАЖДОЙ загрузки проходит сразу, как и задумано.
BOOT_MAIL_THROTTLE=21600
# Порядок: сперва НАШ awg, потом системный wg (инвариант «handshake читает awg, НЕ wg» —
# wg_bin() в transport-awg.sh; обычный wg не понимает A-параметры AmneziaWG).
WG=""
[ -x "$ENODIA_BIN/awg" ] && WG="$ENODIA_BIN/awg"
[ -z "$WG" ] && command -v wg >/dev/null 2>&1 && WG=wg

hs=0
if ip link show awg0 >/dev/null 2>&1 && [ -n "$WG" ]; then
    i=0
    while [ $i -lt 25 ]; do
        hs=$($WG show awg0 latest-handshakes 2>/dev/null | awk 'NR==1{print $2}')
        case "$hs" in ''|*[!0-9]*) hs=0 ;; esac
        [ "$hs" -gt 0 ] && [ "$(age_since "$hs")" -lt 300 ] && break
        sleep 1; i=$((i+1))
    done
fi

# При xray-транспорте вердикт по здоровью Xray (awg0 может не давать handshake,
