# .<t>-active (xray → .xray-active), а .active — лишь тёплый awg-резерв (иначе письмо
# назвало бы не тот конфиг). «Handshake» — термин awg; у tunnel его нет (живость от health-пробы).
if [ "$heal_t" != "awg" ]; then
    active="$tlabel $(cat "$ENODIA_STATE/.$heal_t-active" 2>/dev/null)"
else
    active="AmneziaWG $(cat "$ENODIA_STATE/.active" 2>/dev/null)"
fi
NF_LANG=$(nf_lang)   # язык boot-письма (панельный pref); ru-ветки ниже — байт-в-байт прежние
# ВНЕПЛАНОВЫЙ прогон: сторож снял наш лок, потому что awg0 физически исчез (см. HEAL_REASON в
# watchdog.sh). Роутер НЕ перезагружался, а бутовое письмо читается ровно как «он сам
# ребутнулся» — тот же ложный сигнал, из-за которого `vpn-toggle repair` лок не снимает вовсе
# ([[ruleheal-pseudo-reboot-emails]]). Работу делаем полностью, письмо о ЗАГРУЗКЕ глушим: про
# падение и восстановление awg0 сторож пишет сам (пара «awg0 упал» → «VPN восстановлен»).
HEAL_REASON=/tmp/enodia-heal.reason
# Судим по ФАКТУ файла, а не по его содержимому. Сторож причину пишет всегда, но маркер кладут и
# руками (снял лок, гоняю heal на живом роутере) — а пустой файл, созданный `: >`, прежнее условие
# `[ -n "$heal_why" ]` не ловило, и письмо «загрузка OK» уходило при том, что роутер не
# перезагружался. Проверено 08.08.2026 на себе: ложное письмо в 00:43.
_heal_unplanned=0
[ -e "$HEAL_REASON" ] && _heal_unplanned=1
heal_why=$(cat "$HEAL_REASON" 2>/dev/null | tr -d ' \r\n')
rm -f "$HEAL_REASON" 2>/dev/null
[ "$_heal_unplanned" = 1 ] && [ -z "$heal_why" ] && heal_why="вручную"
if [ -n "$heal_why" ]; then
    echo "verdict: внеплановый прогон (причина: $heal_why) — бутовое письмо не шлю, о событии сообщает watchdog"
    NOTIFY_EVENT=""
fi
# Транспорта нет вовсе (установка «только панель»): вердикт про несущую бессмыслен, а письмо
# «после загрузки VPN НЕ поднялся» на роутере, где VPN ещё не настраивали, — прямая дезинформация.
# Гасим и вердикт, и письмо; вернутся сами, как только человек выберет транспорт в панели.
if [ "$active_t" = none ]; then
    echo "verdict: транспорт не настроен — роутер работает напрямую, настройка в панели :8088"
    NOTIFY_EVENT=""
fi
# ...и ровно то же, когда транспорт ВЫБРАН, а поднять его нечем (импорт бэкапа с другого роутера,
# см. 0a+): «после загрузки VPN НЕ поднялся» отправляет человека искать поломку там, где её нет.
# Письмо про этот случай — за сторожем (ключ transport-missing, раз в сутки; он же отличает «нет
# программы» от «нет конфига»), и второй голос отсюда был бы дублем: вердикт печатаем, письмо гасим.
if [ "$active_ready" = 0 ]; then
    echo "verdict: транспорт $active_t выбран, но поднять его нечем (нет программы/конфига) — настройка в панели :8088"
    NOTIFY_EVENT=""
fi
if [ -f "$NOTIFY_EVENT" ]; then
    if [ "$hs" -gt 0 ]; then
        age=$(age_since "$hs")
        ip=$(probe_ext_ip "" 5)
        if [ "$heal_t" != "awg" ]; then hs_line="Проверка связи: OK"; else hs_line="Handshake: ${age} сек назад"; fi
        if [ "$NF_LANG" = en ]; then
            if [ "$heal_t" != "awg" ]; then hs_line="Link check: OK"; else hs_line="Handshake: ${age} s ago"; fi
        fi
        echo "verdict: VPN up (транспорт $heal_t)"
        if [ "$NF_LANG" = en ]; then
            sh "$NOTIFY_EVENT" boot-ok "$BOOT_MAIL_THROTTLE" "BE7000: boot OK, VPN up" \
"After startup/reboot the router brought the tunnel up.
Config: ${active:-?}. ${hs_line}.
External IP: ${ip:-unknown}.

(This email is sent once per boot — if the router rebooted on its own,
that's a signal: power spike, crash, or someone rebooted it.)" >/dev/null 2>&1
        else
            sh "$NOTIFY_EVENT" boot-ok "$BOOT_MAIL_THROTTLE" "BE7000: загрузка OK, VPN поднят" \
"После запуска/перезагрузки роутер поднял туннель.
Конфиг: ${active:-?}. ${hs_line}.
Внешний IP: ${ip:-неизвестен}.

(Письмо приходит раз за загрузку — если роутер ребутнулся сам,
это сигнал: скачок питания, краш или кто-то перезагрузил.)" >/dev/null 2>&1
        fi
    else
        if [ "$heal_t" != "awg" ]; then
            # Несущая xtun (общий hev/tun2socks) — у всех альт-транспортов (xray/hy2). Для
            # них даём деталь по xtun; для прочих tunnel с иным tun-именем — обобщённо.
            if { [ "$heal_t" = "xray" ] || [ "$heal_t" = "hy2" ]; } && ip link show xtun >/dev/null 2>&1; then
                carrier_state="xtun есть, но проба egress не прошла"
                [ "$NF_LANG" = en ] && carrier_state="xtun exists but egress probe failed"
            elif [ "$heal_t" = "xray" ] || [ "$heal_t" = "hy2" ]; then
                carrier_state="xtun не создан"
                [ "$NF_LANG" = en ] && carrier_state="xtun not created"
            else
                carrier_state="несущая $tlabel не поднялась"
                [ "$NF_LANG" = en ] && carrier_state="$tlabel carrier did not come up"
            fi
            echo "verdict: $heal_t down ($carrier_state)"
            if [ "$NF_LANG" = en ]; then
                sh "$NOTIFY_EVENT" boot-fail "$BOOT_MAIL_THROTTLE" "BE7000: VPN did NOT come up after boot" \
"heal.sh ran, but transport $tlabel did not come up ($carrier_state).
Config: ${active:-?}. Traffic to listed sites is not flowing right now.
Check via SSH: cat /tmp/enodia-startup.log; $ENODIA_DIR/status.sh test.

(If the VPS is simply dead — the watchdog will switch the router to
direct mode within 2 min and send its own email.)" >/dev/null 2>&1
            else
                sh "$NOTIFY_EVENT" boot-fail "$BOOT_MAIL_THROTTLE" "BE7000: после загрузки VPN НЕ поднялся" \
"heal.sh отработал, но транспорт $tlabel не поднялся ($carrier_state).
Конфиг: ${active:-?}. Трафик к сайтам из списка сейчас не идёт.
Загляни по SSH: cat /tmp/enodia-startup.log; $ENODIA_DIR/status.sh test.

(Если VPS просто мёртв — watchdog в ближайшие 2 мин переведёт роутер
в прямой режим и пришлёт своё письмо.)" >/dev/null 2>&1
            fi
        else
            if ip link show awg0 >/dev/null 2>&1; then awg0_state="есть, но handshake не пришёл"; else awg0_state="не создан"; fi
            if [ "$NF_LANG" = en ]; then
                if ip link show awg0 >/dev/null 2>&1; then awg0_state="exists but no handshake"; else awg0_state="not created"; fi
            fi
            echo "verdict: awg0 down ($awg0_state)"
            if [ "$NF_LANG" = en ]; then
                sh "$NOTIFY_EVENT" boot-fail "$BOOT_MAIL_THROTTLE" "BE7000: VPN did NOT come up after boot" \
"heal.sh ran, but the tunnel did not come up (awg0: $awg0_state).
Config: ${active:-?}. Traffic to listed sites is not flowing right now.
Check via SSH: cat /tmp/enodia-startup.log; $ENODIA_DIR/status.sh test.

(If the VPS is simply dead — the watchdog will switch the router to
direct mode within 2 min and send its own email.)" >/dev/null 2>&1
            else
                sh "$NOTIFY_EVENT" boot-fail "$BOOT_MAIL_THROTTLE" "BE7000: после загрузки VPN НЕ поднялся" \
"heal.sh отработал, но туннель не поднялся (awg0: $awg0_state).
Конфиг: ${active:-?}. Трафик к сайтам из списка сейчас не идёт.
Загляни по SSH: cat /tmp/enodia-startup.log; $ENODIA_DIR/status.sh test.

(Если VPS просто мёртв — watchdog в ближайшие 2 мин переведёт роутер
в прямой режим и пришлёт своё письмо.)" >/dev/null 2>&1
            fi
        fi
    fi
fi

# Прогон ДОШЁЛ до конца ⇒ переписываем лок с «done»: он остаётся отметкой «heal в эту загрузку
# отработал», и теперь её видно ОТДЕЛЬНО от «держатель был убит на полпути» (см. проверку вверху).
[ "$REPLAY" = 0 ] && echo "done $(date 2>/dev/null)" > "$LOCK" 2>/dev/null
echo "===== heal.sh done $(date) ====="
